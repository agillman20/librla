c
c
c
c
        subroutine rla_zsvdd(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,
     1      rtol,nb,npow,nextra,
     1      iseed,kcap,k,u,ldu,s,vt,ldvt,w,lw,ier)
        implicit real *8 (a-h,o-z)
        complex *16 a(lda,*)
        dimension ipar(*),rpar(*)
        complex *16 zpar(*)
        external mv
        complex *16 u(ldu,*),vt(ldvt,*),w(*)
        dimension iseed(4),jseed(4),ioff(24),s(*)
        logical fallbk
        integer rla_zranks
c
        k=0
        call rla_chkarg(idense,m,n,lda,rtol,nb,npow,nextra,iseed,
     1      kcap,ier)
        if( ier .eq. 0 .and. (ldu .lt. max(1,m) .or.
     1      ldvt .lt. max(1,kcap)) ) ier=2
        if( ier .ne. 0 ) return
c
c       the algorithm runs on the tall operator: A, or A^H if m < n
c
        jadj=iadj
        mt=m
        nt=n
        ladj=0
        if( m .lt. n ) then
        jadj=1-iadj
        mt=n
        nt=m
        ladj=1
        endif
        call rla_zsvdlay(mt,nt,rtol,nb,nextra,ladj,ioff,lneed)
        call rla_zlwchk(lw,lneed,w,ier)
        if( ier .ne. 0 .or. lw .lt. 0 ) return
c
        do 1100 i=1,4
        jseed(i)=iseed(i)
 1100 continue
        call rla_zorthc(idense,jadj,mt,nt,a,lda,mv,ipar,rpar,zpar,
     1      rtol,nb,npow,nextra,jseed,w(ioff(1)),w(ioff(2)),
     2      w(ioff(3)),w(ioff(4)),w(ioff(5)),w(ioff(6)),w(ioff(7)),
     3      w(ioff(8)),w(ioff(9)),kq,iflag,info)
        if( info .ne. 0 ) then
        ier=3
        return
        endif
        kk=nt
        if( iflag .eq. 0 ) kk=kq
        fallbk=(iflag .ne. 0 .or. kk .ge. nt) .and. rtol .lt. 1
c
c       op = L diag(s) R^H with L = w(il) (ld ldl) and R = w(ir)
c       (nt x iq, ld ldr), both from in-place Jacobi SVDs
c
        if( fallbk ) then
        il=ioff(15)
        call rla_zgetmat(idense,jadj,mt,nt,a,lda,mv,ipar,rpar,zpar,
     1      w(il),w(ioff(16)),w(ioff(17)))
        ir=ioff(18)
        is=ioff(19)
        call rla_zsvdip(mt,nt,w(il),mt,-1.0d0,-1.0d0,kqd,w(is),w(ir),
     1      nt,w(ioff(20)),info)
        iq=nt
        ldl=mt
        ldr=nt
        else
c
c       . . . B = Qs^H op (kq x nt), op = Qs B; the SVD of B or B^H
c
        ib=ioff(2)
        call rla_zqhta(idense,jadj,mt,nt,a,lda,mv,ipar,rpar,zpar,
     1      kq,w(ioff(3)),w(ib),w(ioff(1)))
        iv=ioff(10)
        is=ioff(11)
        if( kq .ge. nt ) then
        call rla_zsvdip(kq,nt,w(ib),max(1,kq),-1.0d0,-1.0d0,kqd,
     1      w(is),w(iv),max(1,nt),w(ioff(12)),info)
        iq=nt
        il=ib
        ldl=max(1,kq)
        ir=iv
        ldr=max(1,nt)
        else
        ig=ioff(1)
        do 1300 j=1,kq
        do 1200 i=1,nt
        w(ig+(i-1)+(j-1)*nt)=dconjg(w(ib+(j-1)+(i-1)*kq))
 1200 continue
 1300 continue
        call rla_zsvdip(nt,kq,w(ig),max(1,nt),-1.0d0,-1.0d0,kqd,
     1      w(is),w(iv),max(1,kq),w(ioff(12)),info)
        iq=kq
        il=iv
        ldl=max(1,kq)
        ir=ig
        ldr=max(1,nt)
        endif
        endif
        if( info .ne. 0 ) then
        ier=3
        return
        endif
c
        if( rtol .ge. 1 ) then
        k=min(int(rtol),iq)
        else
        k=rla_zranks(iq,w(is),rtol)
        endif
        if( k .gt. kcap ) then
        ier=4
        return
        endif
c
c       Ut (mt x k), the left factor of the tall operator: L itself
c       (fallback), Qs L straight into u (tall), or into w(ioff(13))
c
        iut=1
        ldut=1
        if( fallbk ) then
        iut=il
        ldut=ldl
        else if( m .ge. n ) then
        call rla_zgemm(0,mt,k,kq,w(ioff(3)),mt,w(il),ldl,u,ldu)
        else
        iut=ioff(13)
        ldut=mt
        call rla_zgemm(0,mt,k,kq,w(ioff(3)),mt,w(il),ldl,w(iut),
     1      ldut)
        endif
c
c       tall: u = Ut, vt = R^H; wide: u = R, vt = Ut^H
c
        do 2400 j=1,k
        s(j)=dble(w(is+j-1))
        if( m .ge. n .and. fallbk ) then
        do 1900 i=1,mt
        u(i,j)=w(iut+(i-1)+(j-1)*ldut)
 1900 continue
        endif
        if( m .lt. n ) then
        do 2000 i=1,mt
        vt(j,i)=dconjg(w(iut+(i-1)+(j-1)*ldut))
 2000 continue
        endif
        do 2200 i=1,nt
        if( m .ge. n ) then
        vt(j,i)=dconjg(w(ir+(i-1)+(j-1)*ldr))
        else
        u(i,j)=w(ir+(i-1)+(j-1)*ldr)
        endif
 2200 continue
 2400 continue
        do 2600 i=1,4
        iseed(i)=jseed(i)
 2600 continue
        return
        end
c
c
c
c
c
        subroutine rla_zidsd(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,
     1      rtol,nb,npow,nextra,method,iseed,
     1      kcap,k,ipiv,t,ldt,w,lw,ier)
        implicit real *8 (a-h,o-z)
        complex *16 a(lda,*)
        dimension ipar(*),rpar(*)
        complex *16 zpar(*)
        external mv
        complex *16 t(ldt,*),w(*)
        dimension iseed(4),jseed(4),ioff(24),ipiv(*)
c
        k=0
        call rla_chkmet(method,ier)
        if( ier .eq. 0 ) call rla_chkarg(idense,m,n,lda,rtol,nb,npow,
     1      nextra,iseed,kcap,ier)
        if( ier .eq. 0 .and. ldt .lt. max(1,kcap) ) ier=2
        if( ier .ne. 0 ) return
        kt=min(m,n)
        if( rtol .ge. 1 ) kt=min(int(rtol),kt)
        call rla_ztlay(m,n,kt,method,ltn)
        call rla_zqrlay(m,n,rtol,nb,nextra,ltn,ioff,lneed)
        call rla_zlwchk(lw,lneed,w,ier)
        if( ier .ne. 0 .or. lw .lt. 0 ) return
c
        do 1100 i=1,4
        jseed(i)=iseed(i)
 1100 continue
        call rla_zqrcore(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,rtol,
     1      nb,npow,nextra,jseed,w,ioff,
     1      .false.,kr,iq,ldqq,irc,ldrc,ipv,info)
        if( info .ne. 0 ) then
        ier=3
        return
        endif
        k=kr
        if( k .gt. kcap ) then
        ier=4
        return
        endif
        rts=rtol
        if( rtol .ge. 1 ) rts=0
        do 1200 j=1,n
        ipiv(j)=nint(dble(w(ipv+j-1)))
 1200 continue
        call rla_ztcomp(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,w(irc),
     1      ldrc,ipiv,k,method,rts,t,ldt,
     1      w(1),info)
        if( info .ne. 0 ) then
        ier=3
        return
        endif
        do 1600 i=1,4
        iseed(i)=jseed(i)
 1600 continue
        return
        end
c
c
c
c
c
        subroutine rla_zidqd(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,
     1      rtol,method,kcap,k,ipiv,t,ldt,w,lw,
     1      ier)
        implicit real *8 (a-h,o-z)
        complex *16 a(lda,*)
        dimension ipar(*),rpar(*)
        complex *16 zpar(*)
        external mv
        complex *16 t(ldt,*),w(*)
        dimension ipiv(*),iseed(4)
        integer rla_zrankd
c
        k=0
        iseed(1)=0
        iseed(2)=0
        iseed(3)=0
        iseed(4)=1
        call rla_chkmet(method,ier)
        if( ier .eq. 0 ) call rla_chkarg(idense,m,n,lda,rtol,0,0,0,
     1      iseed,kcap,ier)
        if( ier .eq. 0 .and. ldt .lt. max(1,kcap) ) ier=2
        if( ier .ne. 0 ) return
c
c       layout: A and e from 1, later overlaid by the T stage; then
c       jp tau vn1 vn2 hw (n each) and R (mn*n)
c
        mn=min(m,n)
        kt=mn
        if( rtol .ge. 1 ) kt=min(int(rtol),mn)
        call rla_ztlay(m,n,kt,method,ltn)
        iam=1
        ie=iam+m*n
        ijp=1+max(m*n+64*max(m,n),ltn)
        itau=ijp+n
        iv1=itau+n
        iv2=iv1+n
        ihw=iv2+n
        irc=ihw+n
        lneed=irc+mn*n
        call rla_zlwchk(lw,lneed,w,ier)
        if( ier .ne. 0 .or. lw .lt. 0 ) return
c
        call rla_zgetmat(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,w(iam),
     1      w(iam),w(ie))
        ldrc=max(1,mn)
        call rla_zqrfac(m,n,w(iam),max(1,m),w(ijp),w(itau),w(iv1),
     1      w(iv2),w(ihw),w(irc),ldrc,.false.)
        if( rtol .ge. 1 ) then
        k=min(int(rtol),mn)
        rts=0
        else
        k=rla_zrankd(mn,w(irc),ldrc,rtol)
        rts=rtol
        endif
        if( k .gt. kcap ) then
        ier=4
        return
        endif
        do 1200 j=1,n
        ipiv(j)=nint(dble(w(ijp+j-1)))
 1200 continue
        call rla_ztcomp(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,w(irc),
     1      ldrc,ipiv,k,method,rts,t,ldt,
     1      w(1),info)
        if( info .ne. 0 ) ier=3
        return
        end

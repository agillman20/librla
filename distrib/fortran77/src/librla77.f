        subroutine rla_dtlay(m,n,kmax,method,ltn)
        implicit real *8 (a-h,o-z)
c
c       workspace of rla_dtcomp for k <= kmax
c
        if( method .eq. 3 ) then
        ltn=m*n+64*max(m,n)+2*kmax*kmax+6*kmax+max(m,n)+10
        else
        ltn=3*kmax*kmax+7*kmax+10
        endif
        return

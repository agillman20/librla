c
c
c
        subroutine rla_dqhta(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,kq,
     1      q,b,zt)
        implicit real *8 (a-h,o-z)
        real *8 a(lda,*)
        dimension ipar(*),rpar(*)
        complex *16 zpar(*)
        external mv
        real *8 q(m,*),b(kq,*),zt(n,*)
c
c       b (kq x n) = Q^T A; for anything but a stored matrix,
c       (A^T Q)^T via zt (n x kq)
c
        if( idense .eq. 1 .and. iadj .eq. 0 ) then
        call rla_dgemm(1,kq,n,m,q,m,a,lda,b,kq)
        return
        endif
        call rla_dapply(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,1,kq,q,
     1      zt)
        do 1400 j=1,n
        do 1200 i=1,kq
        b(i,j)=zt(j,i)
 1200 continue
 1400 continue
        return
        end

        integer function rla_drankd(kk,r,ldr,rtol)
        implicit real *8 (a-h,o-z)
        real *8 r(ldr,*)
c
c       number of |r(i,i)| >= rtol*|r(1,1)|, i <= kk (pivoted R)
c
        rla_drankd=0
        if( kk .eq. 0 ) return
        d1=abs(r(1,1))
        if( d1 .le. 0 ) return
        do 1200 i=1,kk
        if( abs(r(i,i)) .ge. rtol*d1 ) rla_drankd=rla_drankd+1
 1200 continue
        return
        end

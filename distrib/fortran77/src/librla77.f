        subroutine rla_zqrcore(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,
     1      rtol,nb,npow,nextra,iseed,w,
     1      ioff,wantq,kr,iq,ldqq,irc,ldrc,ipv,info)
        implicit real *8 (a-h,o-z)
        complex *16 a(lda,*)
        dimension ipar(*),rpar(*)
        complex *16 zpar(*)
        external mv
        complex *16 w(*)
        dimension iseed(4),ioff(*)
        logical wantq,fallbk
        integer rla_zrankd
c
c       qr_sketch up to the final product, in the workspace laid out
c       by rla_zqrlay. On exit: rank kr, R = w(irc) (ld ldrc), the
c       pivots as real numbers w(ipv:ipv+n-1), and (when wantq) the
c       factor w(iq) (ld ldqq). Fallback: w(iq) is Q itself and
c       ioff(18)=0; sketch path: Q = Qs * w(iq)(:,1:kr) with
c       Qs = w(ioff(3)) (m x kq) and ioff(18)=kq
c
        mn=min(m,n)
        info=0
        call rla_zorthc(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,rtol,nb,
     1      npow,nextra,iseed,w(ioff(1)),
     1      w(ioff(2)),w(ioff(3)),w(ioff(4)),w(ioff(5)),w(ioff(6)),
     2      w(ioff(7)),w(ioff(8)),w(ioff(9)),kq,iflag,info)
        if( info .ne. 0 ) return
        k=mn
        if( iflag .eq. 0 ) k=kq
        fallbk=(iflag .ne. 0 .or. k .ge. mn) .and. rtol .lt. 1
c
        if( fallbk ) then
c
c       . . . deterministic pivoted QR of the materialized operator
c
        iam=ioff(16)
        call rla_zgetmat(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,w(iam),
     1      w(iam),w(ioff(17)))
        ldrc=max(1,mn)
        call rla_zqrfac(m,n,w(iam),m,w(ioff(10)),w(ioff(11)),
     1      w(ioff(12)),w(ioff(13)),w(ioff(14)),w(ioff(15)),ldrc,
     2      wantq)
        kk=mn
        iq=iam
        ldqq=m
        else
c
c       . . . pivoted QR of B = Q^H A (kq x n), Q2 into B
c
        ib=ioff(2)
        call rla_zqhta(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,kq,
     1      w(ioff(3)),w(ib),w(ioff(1)))
        kk=min(kq,n)
        ldrc=max(1,kk)
        call rla_zqrfac(kq,n,w(ib),max(1,kq),w(ioff(10)),
     1      w(ioff(11)),w(ioff(12)),w(ioff(13)),w(ioff(14)),
     2      w(ioff(15)),ldrc,wantq)
        iq=ib
        ldqq=max(1,kq)
        endif
c
        if( rtol .ge. 1 ) then
        kr=min(int(rtol),kk)
        else
        kr=rla_zrankd(kk,w(ioff(15)),ldrc,rtol)
        endif
        irc=ioff(15)
        ipv=ioff(10)
        ioff(18)=kq
        if( fallbk ) ioff(18)=0
        return
        end

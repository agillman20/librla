        subroutine rla_lcg(iseed,u)
        implicit real *8 (a-h,o-z)
        dimension iseed(4)
c
c       one step of the LAPACK dlaruv generator: iseed := a*iseed
c       mod 2**48 in base-4096 digits, a = (494,322,2508,2549), and
c       u = iseed/2**48 in (0,1). Integer arithmetic below 2**27,
c       so the stream equals LAPACK dlarnv in any precision
c
        i1=iseed(1)
        i2=iseed(2)
        i3=iseed(3)
        i4=iseed(4)
        it4=i4*2549
        it3=it4/4096
        it4=it4-4096*it3
        it3=it3+i3*2549+i4*2508
        it2=it3/4096
        it3=it3-4096*it2
        it2=it2+i2*2549+i3*2508+i4*322
        it1=it2/4096
        it2=it2-4096*it1
        it1=it1+i1*2549+i2*2508+i3*322+i4*494
        it1=mod(it1,4096)
        iseed(1)=it1
        iseed(2)=it2
        iseed(3)=it3
        iseed(4)=it4
        r=1.0d0/4096
        u=r*(dble(it1)+r*(dble(it2)+r*(dble(it3)+r*dble(it4))))
        return
        end

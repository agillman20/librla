        subroutine rla_dqrpk(m,n,a,lda,kmax,atol,rtol,jp,tau,vn1,vn2,
     1      work,k,rmaxk,rmax0)
        implicit real *8 (a-h,o-z)
        real *8 a(lda,*),tau(*),work(*),aii,d,ctau
        real *8 jp(*),vn1(*),vn2(*)
c
c       Householder QR with column pivoting and early exit (LAPACK
c       dlaqp2 steps with the stopping rules of dgeqp3rk): before step
c       i the largest partial column norm rmax of the trailing block
c       is compared with the tolerances, and the factorization stops
c       with k = i-1 columns when
c
c         i-1 = kmax, or rmax <= atol (atol >= 0), or
c         rmax <= rtol*rmax0 (rtol >= 0), rmax0 the largest column
c         norm of a; a negative tolerance disables its test.
c
c       On exit a(:,jp) = Q(:,1:k) R(1:k,:) + [0 R22]: R in the upper
c       triangle of the first k rows, reflectors below it, the
c       updated residual R22 in a(k+1:m,k+1:n), tau(k+1:) = 0.
c       rmaxk = largest column norm of R22 (0 if k = min(m,n)).
c       jp: 1-based pivots as real numbers; vn1, vn2, work (n) scratch
c
        tol3z=sqrt(rla_eps())
        rmax0=0
        do 1400 j=1,n
        jp(j)=j
        s=0
        do 1200 i=1,m
        s=s+(a(i,j))**2
 1200 continue
        vn1(j)=sqrt(s)
        vn2(j)=vn1(j)
        rmax0=max(rmax0,sqrt(s))
 1400 continue
c
        kk=min(m,n)
        do 1500 i=1,kk
        tau(i)=0
 1500 continue
        k=0
        rmaxk=0
        do 3000 i=1,kk
c
c       . . . pivot: the remaining column of largest partial norm,
c       then the stopping tests
c
        ipvt=i
        vmax=vn1(i)
        do 1600 j=i+1,n
        if( vn1(j) .gt. vmax ) then
        ipvt=j
        vmax=vn1(j)
        endif
 1600 continue
        rmaxk=vmax
        if( i-1 .ge. kmax ) return
        if( atol .ge. 0 .and. vmax .le. atol ) return
        if( rtol .ge. 0 .and. vmax .le. rtol*rmax0 ) return
        if( ipvt .ne. i ) then
        do 1800 l=1,m
        d=a(l,ipvt)
        a(l,ipvt)=a(l,i)
        a(l,i)=d
 1800 continue
        tmp=jp(ipvt)
        jp(ipvt)=jp(i)
        jp(i)=tmp
        vn1(ipvt)=vn1(i)
        vn2(ipvt)=vn2(i)
        endif
c
c       . . . reflector for column i, applied to the trailing columns
c
        if( i .lt. m ) then
        call rla_dlarfg(m-i+1,a(i,i),a(i+1,i),tau(i))
        else
        call rla_dlarfg(1,a(m,m),a(m,m),tau(m))
        endif
        if( i .lt. n ) then
        aii=a(i,i)
        a(i,i)=1
        ctau=tau(i)
        call rla_dlarfl(m-i+1,n-i,a(i,i),ctau,a(i,i+1),lda,work)
        a(i,i)=aii
        endif
        k=i
c
c       . . . downdate the partial column norms
c
        do 2400 j=i+1,n
        v1=vn1(j)
        if( v1 .le. 0 ) goto 2400
        temp=1-(abs(a(i,j))/v1)**2
        if( temp .lt. 0 ) temp=0
        temp2=temp*(v1/vn2(j))**2
        if( temp2 .le. tol3z ) then
        if( i .lt. m ) then
        s=0
        do 2200 l=i+1,m
        s=s+(a(l,j))**2
 2200 continue
        vn1(j)=sqrt(s)
        vn2(j)=vn1(j)
        else
        vn1(j)=0
        vn2(j)=0
        endif
        else
        vn1(j)=v1*sqrt(temp)
        endif
 2400 continue
 3000 continue
        rmaxk=0
        return
        end

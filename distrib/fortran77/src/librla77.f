        subroutine rla_dqrfac(m,n,a,lda,jp,tau,vn1,vn2,work,
     1      r,ldr,wantq)
        implicit real *8 (a-h,o-z)
        real *8 a(lda,*),tau(*),work(*),r(ldr,*)
        real *8 jp(*),vn1(*),vn2(*)
        logical wantq
c
c       pivoted QR of a (m x n) in place: r (kk x n, kk = min(m,n))
c       gets R with its lower part zeroed; when wantq, a(:,1:kk) is
c       overwritten with Q
c
        kk=min(m,n)
        call rla_dqrp(m,n,a,lda,jp,tau,vn1,vn2,work)
        do 1400 j=1,n
        do 1200 i=1,kk
        r(i,j)=0
        if( i .le. j ) r(i,j)=a(i,j)
 1200 continue
 1400 continue
        if( wantq ) call rla_dorgqr(m,kk,a,lda,tau,work)
        return
        end

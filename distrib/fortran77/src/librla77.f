        subroutine rla_zqrf(m,n,a,lda,tau,work)
        implicit real *8 (a-h,o-z)
        complex *16 a(lda,*),tau(*),work(*),aii,ctau
c
c       Householder QR without pivoting, LAPACK zgeqr2: a (m x n) =
c       Q R with R in the upper triangle and the reflectors
c       H(i) = I - tau(i) v v^H below it (v(i) = 1 implicit).
c       tau (min(m,n)) and work (n) are scratch. Q (m x k) is formed
c       from the reflectors in place by rla_zorgqr(m,k,a,lda,tau,work)
c
        k=min(m,n)
        do 2000 i=1,k
        if( i .lt. m ) then
        call rla_zlarfg(m-i+1,a(i,i),a(i+1,i),tau(i))
        else
        call rla_zlarfg(1,a(m,m),a(m,m),tau(m))
        endif
        if( i .lt. n ) then
        aii=a(i,i)
        a(i,i)=1
        ctau=dconjg(tau(i))
        call rla_zlarfl(m-i+1,n-i,a(i,i),ctau,a(i,i+1),lda,work)
        a(i,i)=aii
        endif
 2000 continue
        return
        end

c
c
        subroutine rla_dqrcore(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,
     1      rtol,nb,npow,nextra,iseed,w,
     1      ioff,wantq,kr,iq,ldqq,irc,ldrc,ipv,info)
        implicit real *8 (a-h,o-z)
        real *8 a(lda,*)
        dimension ipar(*),rpar(*)
        complex *16 zpar(*)
        external mv
        real *8 w(*)
        dimension iseed(4),ioff(*)
        logical wantq,fallbk
        integer rla_drankd
c
c       qr_sketch up to the final product, in the workspace laid out
c       by rla_dqrlay. On exit: rank kr, R = w(irc) (ld ldrc), the
c       pivots as real numbers w(ipv:ipv+n-1), and (when wantq) the
c       factor w(iq) (ld ldqq). Fallback: w(iq) is Q itself and
c       ioff(18)=0; sketch path: Q = Qs * w(iq)(:,1:kr) with
c       Qs = w(ioff(3)) (m x kq) and ioff(18)=kq
c
        mn=min(m,n)
        info=0
        call rla_dorthc(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,rtol,nb,
     1      npow,nextra,iseed,w(ioff(1)),
     1      w(ioff(2)),w(ioff(3)),w(ioff(4)),w(ioff(5)),w(ioff(6)),
     2      w(ioff(7)),w(ioff(8)),w(ioff(9)),kq,iflag,info)
        if( info .ne. 0 ) return
        k=mn
        if( iflag .eq. 0 ) k=kq
        fallbk=(iflag .ne. 0 .or. k .ge. mn) .and. rtol .lt. 1
c
        if( fallbk ) then
c
c       . . . deterministic pivoted QR of the materialized operator
c
        iam=ioff(16)
        call rla_dgetmat(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,w(iam),
     1      w(iam),w(ioff(17)))
        ldrc=max(1,mn)
        call rla_dqrfac(m,n,w(iam),m,w(ioff(10)),w(ioff(11)),
     1      w(ioff(12)),w(ioff(13)),w(ioff(14)),w(ioff(15)),ldrc,
     2      wantq)
        kk=mn
        iq=iam
        ldqq=m
        else
c
c       . . . pivoted QR of B = Q^T A (kq x n), Q2 into B
c
        ib=ioff(2)
        call rla_dqhta(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,kq,
     1      w(ioff(3)),w(ib),w(ioff(1)))
        kk=min(kq,n)
        ldrc=max(1,kk)
        call rla_dqrfac(kq,n,w(ib),max(1,kq),w(ioff(10)),
     1      w(ioff(11)),w(ioff(12)),w(ioff(13)),w(ioff(14)),
     2      w(ioff(15)),ldrc,wantq)
        iq=ib
        ldqq=max(1,kq)
        endif
c
        if( rtol .ge. 1 ) then
        kr=min(int(rtol),kk)
        else
        kr=rla_drankd(kk,w(ioff(15)),ldrc,rtol)
        endif
        irc=ioff(15)
        ipv=ioff(10)
        ioff(18)=kq
        if( fallbk ) ioff(18)=0
        return
        end
c
c
c
c
c
        subroutine rla_dqrlay(m,n,rtol,nb,nextra,lres,ioff,lneed)
        implicit real *8 (a-h,o-z)
        dimension ioff(*)
c
c       workspace layout of rla_dqrcore (worst case, fixed before the
c       data-dependent run). From 1: the sketch (1-9: x z y tau vn1
c       vn2 jp hw d, ending at ioff(19)), overlaid by the fallback A
c       and e (16-17) and by lres scalars for the caller's next stage.
c       After them: the QR of B (10-15: jp tau vn1 vn2 hw R)
c
        mn=min(m,n)
        call rla_lmax(m,n,rtol,nb,nextra,l)
        ioff(1)=1
        ioff(2)=ioff(1)+n*l
        ioff(3)=ioff(2)+n*l
        ioff(4)=ioff(3)+m*l
        do 1200 i=5,10
        ioff(i)=ioff(i-1)+l
 1200 continue
        ioff(19)=ioff(10)
        ioff(16)=1
        ioff(17)=1+m*n
        iend=max(ioff(10),1+lres)
        if( rtol .lt. 1 ) iend=max(iend,ioff(17)+64*max(m,n))
        ioff(10)=iend
        do 1400 i=11,15
        ioff(i)=ioff(i-1)+n
 1400 continue
c
c       R has min(kq,n) <= min(l,mn) rows, or mn after a fallback
c
        krow=mn
        if( rtol .ge. 1 ) krow=min(l,mn)
        lneed=ioff(15)+krow*n
        return
        end
c
c
c
c
c
        subroutine rla_dsvdlay(m,n,rtol,nb,nextra,ladj,ioff,lneed)
        implicit real *8 (a-h,o-z)
        dimension ioff(*)
c
c       workspace layout of rla_dsvdd on the tall operator (m >= n):
c       1-9 sketch, 10-13 small in-place SVD (v s tmp, Ut if the user
c       matrix is wide, ladj=1); the fallback (15-20: A, adjoint
c       scratch, e, v, s, tmp) overlays the sketch from 1
c
        call rla_lmax(m,n,rtol,nb,nextra,l)
        kqm=min(m,l)
        iq=min(kqm,n)
        ioff(1)=1
        ioff(2)=ioff(1)+n*l
        ioff(3)=ioff(2)+n*l
        ioff(4)=ioff(3)+m*l
        do 1200 i=5,10
        ioff(i)=ioff(i-1)+l
 1200 continue
        ioff(11)=ioff(10)+iq*iq
        ioff(12)=ioff(11)+iq
        ioff(13)=ioff(12)+iq*iq+5*iq+max(m,n,kqm)+1
        ioff(14)=ioff(13)
        if( ladj .eq. 1 ) ioff(14)=ioff(13)+m*iq
        lneed=ioff(14)
        if( rtol .ge. 1 ) return
        ioff(15)=1
        ioff(16)=ioff(15)+m*n
        ioff(17)=ioff(16)
        if( ladj .eq. 1 ) ioff(17)=ioff(16)+m*n
        ioff(18)=ioff(17)+64*max(m,n)
        ioff(19)=ioff(18)+n*n
        ioff(20)=ioff(19)+n
        ioff(21)=ioff(20)+n*n+5*n+m+1
        lneed=max(lneed,ioff(21))
        return
        end
c
c
c
c
c
        subroutine rla_dorthd(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,
     1      rtol,nb,npow,nextra,iseed,kcap,k,
     1      q,ldq,diagr,iflag,w,lw,ier)
        implicit real *8 (a-h,o-z)
        real *8 a(lda,*)
        dimension ipar(*),rpar(*)
        complex *16 zpar(*)
        external mv
        real *8 q(ldq,*),w(*)
        dimension iseed(4),jseed(4),ioff(24),diagr(*)
c
        k=0
        iflag=1
        call rla_chkarg(idense,m,n,lda,rtol,nb,npow,nextra,iseed,
     1      kcap,ier)
        if( ier .eq. 0 .and. ldq .lt. max(1,m) ) ier=2
        if( ier .ne. 0 ) return
        call rla_dqrlay(m,n,rtol,nb,nextra,0,ioff,lneed)
        lneed=ioff(19)
        call rla_dlwchk(lw,lneed,w,ier)
        if( ier .ne. 0 .or. lw .lt. 0 ) return
c
        do 1100 i=1,4
        jseed(i)=iseed(i)
 1100 continue
        call rla_dorthc(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,rtol,nb,
     1      npow,nextra,jseed,w(ioff(1)),
     1      w(ioff(2)),w(ioff(3)),w(ioff(4)),w(ioff(5)),w(ioff(6)),
     2      w(ioff(7)),w(ioff(8)),w(ioff(9)),kq,iflag,info)
        if( info .ne. 0 ) then
        ier=3
        iflag=1
        return
        endif
        k=kq
        if( k .gt. kcap ) then
        ier=4
        return
        endif
        iy=ioff(3)
        do 1400 j=1,k
        diagr(j)=w(ioff(9)+j-1)
        do 1200 i=1,m
        q(i,j)=w(iy+(i-1)+(j-1)*m)
 1200 continue
 1400 continue
        do 1600 i=1,4
        iseed(i)=jseed(i)
 1600 continue
        return
        end
c
c
c
c
c
        subroutine rla_dqrd(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,
     1      rtol,nb,npow,nextra,iseed,kcap,k,
     1      q,ldq,r,ldr,ipiv,w,lw,ier)
        implicit real *8 (a-h,o-z)
        real *8 a(lda,*)
        dimension ipar(*),rpar(*)
        complex *16 zpar(*)
        external mv
        real *8 q(ldq,*),r(ldr,*),w(*)
        dimension iseed(4),jseed(4),ioff(24),ipiv(*)
c
        k=0
        call rla_chkarg(idense,m,n,lda,rtol,nb,npow,nextra,iseed,
     1      kcap,ier)
        if( ier .eq. 0 .and. (ldq .lt. max(1,m) .or.
     1      ldr .lt. max(1,kcap)) ) ier=2
        if( ier .ne. 0 ) return
        call rla_dqrlay(m,n,rtol,nb,nextra,0,ioff,lneed)
        call rla_dlwchk(lw,lneed,w,ier)
        if( ier .ne. 0 .or. lw .lt. 0 ) return
c
        do 1100 i=1,4
        jseed(i)=iseed(i)
 1100 continue
        call rla_dqrcore(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,rtol,
     1      nb,npow,nextra,jseed,w,ioff,
     1      .true.,kr,iq,ldqq,irc,ldrc,ipv,info)
        if( info .ne. 0 ) then
        ier=3
        return
        endif
        k=kr
        if( k .gt. kcap ) then
        ier=4
        return
        endif
        kq=ioff(18)
        if( kq .eq. 0 ) then
        do 1400 j=1,k
        do 1200 i=1,m
        q(i,j)=w(iq+(i-1)+(j-1)*ldqq)
 1200 continue
 1400 continue
        else
        call rla_dgemm(0,m,k,kq,w(ioff(3)),m,w(iq),ldqq,q,ldq)
        endif
        do 1800 j=1,n
        ipiv(j)=nint(w(ipv+j-1))
        do 1600 i=1,k
        r(i,j)=w(irc+(i-1)+(j-1)*ldrc)
 1600 continue
 1800 continue
        do 2000 i=1,4
        iseed(i)=jseed(i)
 2000 continue
        return
        end
c
c
c
c
c
        subroutine rla_dsvdd(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,
     1      rtol,nb,npow,nextra,
     1      iseed,kcap,k,u,ldu,s,vt,ldvt,w,lw,ier)
        implicit real *8 (a-h,o-z)
        real *8 a(lda,*)
        dimension ipar(*),rpar(*)
        complex *16 zpar(*)
        external mv
        real *8 u(ldu,*),vt(ldvt,*),w(*)
        dimension iseed(4),jseed(4),ioff(24),s(*)
        logical fallbk
        integer rla_dranks
c
        k=0
        call rla_chkarg(idense,m,n,lda,rtol,nb,npow,nextra,iseed,
     1      kcap,ier)
        if( ier .eq. 0 .and. (ldu .lt. max(1,m) .or.
     1      ldvt .lt. max(1,kcap)) ) ier=2
        if( ier .ne. 0 ) return
c
c       the algorithm runs on the tall operator: A, or A^T if m < n
c
        jadj=iadj
        mt=m
        nt=n
        ladj=0
        if( m .lt. n ) then
        jadj=1-iadj
        mt=n
        nt=m
        ladj=1
        endif
        call rla_dsvdlay(mt,nt,rtol,nb,nextra,ladj,ioff,lneed)
        call rla_dlwchk(lw,lneed,w,ier)
        if( ier .ne. 0 .or. lw .lt. 0 ) return
c
        do 1100 i=1,4
        jseed(i)=iseed(i)
 1100 continue
        call rla_dorthc(idense,jadj,mt,nt,a,lda,mv,ipar,rpar,zpar,
     1      rtol,nb,npow,nextra,jseed,w(ioff(1)),w(ioff(2)),
     2      w(ioff(3)),w(ioff(4)),w(ioff(5)),w(ioff(6)),w(ioff(7)),
     3      w(ioff(8)),w(ioff(9)),kq,iflag,info)
        if( info .ne. 0 ) then
        ier=3
        return
        endif
        kk=nt
        if( iflag .eq. 0 ) kk=kq
        fallbk=(iflag .ne. 0 .or. kk .ge. nt) .and. rtol .lt. 1
c
c       op = L diag(s) R^T with L = w(il) (ld ldl) and R = w(ir)
c       (nt x iq, ld ldr), both from in-place Jacobi SVDs
c
        if( fallbk ) then
        il=ioff(15)
        call rla_dgetmat(idense,jadj,mt,nt,a,lda,mv,ipar,rpar,zpar,
     1      w(il),w(ioff(16)),w(ioff(17)))
        ir=ioff(18)
        is=ioff(19)
        call rla_dsvdip(mt,nt,w(il),mt,-1.0d0,-1.0d0,kqd,w(is),w(ir),
     1      nt,w(ioff(20)),info)
        iq=nt
        ldl=mt
        ldr=nt
        else
c
c       . . . B = Qs^T op (kq x nt), op = Qs B; the SVD of B or B^T
c
        ib=ioff(2)
        call rla_dqhta(idense,jadj,mt,nt,a,lda,mv,ipar,rpar,zpar,
     1      kq,w(ioff(3)),w(ib),w(ioff(1)))
        iv=ioff(10)
        is=ioff(11)
        if( kq .ge. nt ) then
        call rla_dsvdip(kq,nt,w(ib),max(1,kq),-1.0d0,-1.0d0,kqd,
     1      w(is),w(iv),max(1,nt),w(ioff(12)),info)
        iq=nt
        il=ib
        ldl=max(1,kq)
        ir=iv
        ldr=max(1,nt)
        else
        ig=ioff(1)
        do 1300 j=1,kq
        do 1200 i=1,nt
        w(ig+(i-1)+(j-1)*nt)=w(ib+(j-1)+(i-1)*kq)
 1200 continue
 1300 continue
        call rla_dsvdip(nt,kq,w(ig),max(1,nt),-1.0d0,-1.0d0,kqd,
     1      w(is),w(iv),max(1,kq),w(ioff(12)),info)
        iq=kq
        il=iv
        ldl=max(1,kq)
        ir=ig
        ldr=max(1,nt)
        endif
        endif
        if( info .ne. 0 ) then
        ier=3
        return
        endif
c
        if( rtol .ge. 1 ) then
        k=min(int(rtol),iq)
        else
        k=rla_dranks(iq,w(is),rtol)
        endif
        if( k .gt. kcap ) then
        ier=4
        return
        endif
c
c       Ut (mt x k), the left factor of the tall operator: L itself
c       (fallback), Qs L straight into u (tall), or into w(ioff(13))
c
        iut=1
        ldut=1
        if( fallbk ) then
        iut=il
        ldut=ldl
        else if( m .ge. n ) then
        call rla_dgemm(0,mt,k,kq,w(ioff(3)),mt,w(il),ldl,u,ldu)
        else
        iut=ioff(13)
        ldut=mt
        call rla_dgemm(0,mt,k,kq,w(ioff(3)),mt,w(il),ldl,w(iut),
     1      ldut)
        endif
c
c       tall: u = Ut, vt = R^T; wide: u = R, vt = Ut^T
c
        do 2400 j=1,k
        s(j)=w(is+j-1)
        if( m .ge. n .and. fallbk ) then
        do 1900 i=1,mt
        u(i,j)=w(iut+(i-1)+(j-1)*ldut)
 1900 continue
        endif
        if( m .lt. n ) then
        do 2000 i=1,mt
        vt(j,i)=w(iut+(i-1)+(j-1)*ldut)
 2000 continue
        endif
        do 2200 i=1,nt
        if( m .ge. n ) then
        vt(j,i)=w(ir+(i-1)+(j-1)*ldr)
        else
        u(i,j)=w(ir+(i-1)+(j-1)*ldr)
        endif
 2200 continue
 2400 continue
        do 2600 i=1,4
        iseed(i)=jseed(i)
 2600 continue
        return
        end

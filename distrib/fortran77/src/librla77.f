        complex *16 jp(*),vn1(*),vn2(*)
c
c       full Householder QR with column pivoting (rla_zqrpk without
c       early exit): a(:,jp) = Q R, R in the upper triangle,
c       reflectors below it, jp the 1-based pivots as real numbers

        subroutine rla_dorgqr(m,k,a,lda,tau,work)
        implicit real *8 (a-h,o-z)
        real *8 a(lda,*),tau(*),work(*)
c
c       overwrite the reflectors in a(:,1:k) (from rla_dqrp) with
c       Q(:,1:k) = H(1) ... H(k) I(:,1:k), LAPACK dorg2r / dung2r
c
        do 2000 i=k,1,-1
        if( i .lt. k ) then
        a(i,i)=1
        call rla_dlarfl(m-i+1,k-i,a(i,i),tau(i),a(i,i+1),lda,work)
        endif
        do 1200 l=i+1,m
        a(l,i)=-tau(i)*a(l,i)
 1200 continue
        a(i,i)=1-tau(i)
        do 1400 l=1,i-1
        a(l,i)=0
 1400 continue
 2000 continue
        return
        end

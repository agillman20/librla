        subroutine rla_zgetmatp(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,
     1      ipiv,am,e)
        implicit real *8 (a-h,o-z)
        complex *16 a(lda,*)
        dimension ipar(*),rpar(*)
        complex *16 zpar(*)
        external mv
        complex *16 am(m,n),e(n,*)
        dimension ipiv(*)
c
c       am(:,j) = A(:,ipiv(j)): the (non-adjoint) operator materialized
c       in pivot order; e (64*n) is scratch for a matrix-free operator
c
        if( iadj .ne. 0 .or. m .eq. 0 .or. n .eq. 0 ) return
        if( idense .eq. 1 ) then
        do 1400 j=1,n
        do 1200 i=1,m
        am(i,j)=a(i,ipiv(j))
 1200 continue
 1400 continue
        return
        endif
        do 2000 j0=1,n,64
        jb=min(64,n-j0+1)
        do 1700 jj=1,jb
        do 1600 i=1,n
        e(i,jj)=0
 1600 continue
        e(ipiv(j0+jj-1),jj)=1
 1700 continue
        call mv(0,m,n,jb,e,am(1,j0),ipar,rpar,zpar)
 2000 continue
        return
        end

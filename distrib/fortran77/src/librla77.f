        subroutine rla_zlarfg(n,alpha,x,tau)
        implicit real *8 (a-h,o-z)
        complex *16 alpha,x(*),tau
        complex *16 ascal
c
c       elementary reflector H = I - tau v v^H, v = (1, x), such that
c       H^H (alpha, x) = (beta, 0) with beta real (LAPACK zlarfg)
c
        if( n .le. 0 ) then
        tau=0
        return
        endif
        xnorm=0
        do 1200 i=1,n-1
        xnorm=xnorm+(dble(x(i))**2+dimag(x(i))**2)
 1200 continue
        xnorm=sqrt(xnorm)
        alphr=dble(alpha)
        alphi=dimag(alpha)
        if( xnorm .le. 0 .and. abs(alphi) .le. 0 ) then
        tau=0
        return
        endif
        beta=-sign(sqrt(alphr**2+alphi**2+xnorm**2),alphr)
        tau=dcmplx((beta-alphr)/beta,-alphi/beta)
        ascal=1/(alpha-beta)
        do 1400 i=1,n-1
        x(i)=x(i)*ascal
 1400 continue
        alpha=beta
        return
        end

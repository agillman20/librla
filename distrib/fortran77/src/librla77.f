        subroutine rla_dapply(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,
     1      itrans,k,x,y)
        implicit real *8 (a-h,o-z)
        real *8 a(lda,*)
        dimension ipar(*),rpar(*)
        complex *16 zpar(*)
        external mv
        real *8 x(*),y(*)
c
c       y = op(A) x for k columns: itrans=0: y(m,k) = A x(n,k);
c       itrans=1: y(n,k) = A^T x(m,k). (m,n) is the shape seen by the
c       algorithms; iadj=1 means the operator is the adjoint of the
c       stored or user-applied base
c
        if( iadj .eq. 1 ) then
        mb=n
        nb=m
        ib=1-itrans
        else
        mb=m
        nb=n
        ib=itrans

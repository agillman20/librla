c
c
c
c
        subroutine rla_zqrd(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,
     1      rtol,nb,npow,nextra,iseed,kcap,k,
     1      q,ldq,r,ldr,ipiv,w,lw,ier)
        implicit real *8 (a-h,o-z)
        complex *16 a(lda,*)
        dimension ipar(*),rpar(*)
        complex *16 zpar(*)
        external mv
        complex *16 q(ldq,*),r(ldr,*),w(*)
        dimension iseed(4),jseed(4),ioff(24),ipiv(*)
c
        k=0
        call rla_chkarg(idense,m,n,lda,rtol,nb,npow,nextra,iseed,
     1      kcap,ier)
        if( ier .eq. 0 .and. (ldq .lt. max(1,m) .or.
     1      ldr .lt. max(1,kcap)) ) ier=2
        if( ier .ne. 0 ) return
        call rla_zqrlay(m,n,rtol,nb,nextra,0,ioff,lneed)
        call rla_zlwchk(lw,lneed,w,ier)
        if( ier .ne. 0 .or. lw .lt. 0 ) return
c
        do 1100 i=1,4
        jseed(i)=iseed(i)
 1100 continue
        call rla_zqrcore(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,rtol,
     1      nb,npow,nextra,jseed,w,ioff,
     1      .true.,kr,iq,ldqq,irc,ldrc,ipv,info)
        if( info .ne. 0 ) then
        ier=3
        return
        endif
        k=kr
        if( k .gt. kcap ) then
        ier=4
        return
        endif
        kq=ioff(18)
        if( kq .eq. 0 ) then
        do 1400 j=1,k
        do 1200 i=1,m
        q(i,j)=w(iq+(i-1)+(j-1)*ldqq)
 1200 continue
 1400 continue
        else
        call rla_zgemm(0,m,k,kq,w(ioff(3)),m,w(iq),ldqq,q,ldq)
        endif
        do 1800 j=1,n
        ipiv(j)=nint(dble(w(ipv+j-1)))
        do 1600 i=1,k
        r(i,j)=w(irc+(i-1)+(j-1)*ldrc)
 1600 continue
 1800 continue
        do 2000 i=1,4
        iseed(i)=jseed(i)
 2000 continue
        return
        end

        rla_zrankd=0
        if( kk .eq. 0 ) return
        d1=abs(r(1,1))
        if( d1 .le. 0 ) return
        do 1200 i=1,kk
        if( abs(r(i,i)) .ge. rtol*d1 ) rla_zrankd=rla_zrankd+1

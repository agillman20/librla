        rla_dranks=0
        if( kk .eq. 0 ) return
        s1=s(1)
        if( s1 .le. 0 ) return
        do 1200 i=1,kk
        if( s(i) .ge. rtol*s1 ) rla_dranks=rla_dranks+1
 1200 continue
        return
        end

        subroutine rla_dsvdip(p,q,g,ldg,qatol,qrtol,kq,s,v,ldv,w,info)
        implicit real *8 (a-h,o-z)
        integer p,q
        real *8 g(ldg,*),v(ldv,*),w(*),d
        real *8 s(*)
c
c       in-place SVD of g (p x q, p >= q) by preconditioned one-sided
c       Jacobi (Drmac, as in LAPACK dgejsv): pivoted QR g P = Q R, then
c       Jacobi on X = R^T = Ux S Vx^T, so that g = (Q Vx) S (P Ux)^T.
c       The QR may stop early (rla_dqrpk with atol = qatol, rtol =
c       qrtol; negative values disable): with kq rows of R kept, the
c       dropped trailing block R22 perturbs g by ||R22||. On exit
c       g(:,1:kq) = U, s(1:kq) descending, v (q x kq) = V. With no
c       early exit kq = q (zero singular values get orthonormal
c       completions). w: q*q+5*q+max(p,q) scalars. info=1: no
c       convergence
c
        info=0
        kq=0
        if( q .eq. 0 ) return
        ix=1
        ijp=ix+q*q
        itau=ijp+q
        iv1=itau+q
        iv2=iv1+q
        iwk=iv2+q
        itm=iwk+q
c
        call rla_dqrpk(p,q,g,ldg,q,qatol,qrtol,w(ijp),w(itau),w(iv1),
     1      w(iv2),w(iwk),kq,rmaxk,rmax0)
        if( qatol .lt. 0 .and. qrtol .lt. 0 ) kq=q
        if( kq .eq. 0 ) return
c
c       X (q x kq) = R(1:kq,:)^T
c
        do 1400 j=1,kq
        do 1200 i=1,q
        d=0
        if( j .le. i ) d=g(j,i)
        w(ix+(i-1)+(j-1)*q)=d
 1200 continue
 1400 continue
        call rla_djacobi(q,kq,w(ix),q,v,ldv,s,info)
        call rla_dsvsort(q,kq,w(ix),q,v,ldv,s,w(itm))
c
c       left vectors Q(:,1:kq) Vx, formed row by row in g
c
        call rla_dorgqr(p,kq,g,ldg,w(itau),w(iwk))
        do 2000 i=1,p
        do 1600 l=1,kq
        w(itm+l-1)=g(i,l)
 1600 continue
        do 1800 j=1,kq
        d=0
        do 1700 l=1,kq
        d=d+w(itm+l-1)*v(l,j)
 1700 continue
        g(i,j)=d
 1800 continue
 2000 continue
c
c       right vectors P Ux (q x kq): row jp(i) of v = row i of Ux
c
        do 2400 j=1,kq
        do 2200 i=1,q
        ir=nint(w(ijp+i-1))
        v(ir,j)=w(ix+(i-1)+(j-1)*q)
 2200 continue
 2400 continue
        return
        end

        subroutine rla_dsketch(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,
     1      l,npow,iseed,x,z,y,tau,vn1,vn2,
     1      jp,hw,d,kq,info)
        implicit real *8 (a-h,o-z)
        real *8 a(lda,*)
        dimension ipar(*),rpar(*)
        complex *16 zpar(*)
        external mv
        real *8 x(n,*),z(n,*),y(m,*),tau(*),hw(*)
        real *8 vn1(*),vn2(*),jp(*),d(*)
        dimension iseed(4)
c
c       one sketch: x = Omega (n x l), npow power iterations
c       x <- orth(A^T A x), y = A x, then the pivoted QR of y.
c       On exit y(:,1:kq) = Q, d(1:kq) = |diag R|
c
        info=0
        call rla_drandn(iseed,n*l,x)
        lx=l
        do 1600 it=1,npow
        call rla_dapply(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,0,lx,x,
     1      y)
        call rla_dapply(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,1,lx,y,
     1      z)
        call rla_dqrp(n,lx,z,n,jp,tau,vn1,vn2,hw)
        kz=min(n,lx)
        call rla_dorgqr(n,kz,z,n,tau,hw)
        do 1400 j=1,kz
        do 1200 i=1,n
        x(i,j)=z(i,j)
 1200 continue
 1400 continue
        lx=kz
 1600 continue
        call rla_dapply(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,0,lx,x,
     1      y)
        call rla_dqrp(m,lx,y,m,jp,tau,vn1,vn2,hw)
        kq=min(m,lx)
        do 1800 i=1,kq
        d(i)=abs(y(i,i))
 1800 continue
        call rla_dorgqr(m,kq,y,m,tau,hw)
        return
        end

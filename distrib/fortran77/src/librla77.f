        subroutine rla_zorthc(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,
     1      rtol,nb,npow,nextra,iseed,x,z,y,
     1      tau,vn1,vn2,jp,hw,d,kq,iflag,info)
        implicit real *8 (a-h,o-z)
        complex *16 a(lda,*)
        dimension ipar(*),rpar(*)
        complex *16 zpar(*)
        external mv
        complex *16 x(*),z(*),y(*),tau(*),hw(*)
        complex *16 vn1(*),vn2(*),jp(*),d(*)
        dimension iseed(4)
c
c       orth_sketch: y(:,1:kq) = Q, d(1:kq) = |diag R|. Rank mode: one
c       sketch of floor(rtol)+nextra columns. Tolerance mode: a fresh
c       sketch per pass, nb growing 4x, accepted when
c       d(kq-nextra) <= rtol*d(1); iflag=1 (kq=0) when rtol < eps or
c       the sketch would reach min(m,n)
c
        mn=min(m,n)
        iflag=0
        kq=0
        info=0
        if( rtol .ge. 1 ) then
        l=int(rtol)+nextra
        call rla_zsketch(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,l,npow,
     1      iseed,x,z,y,tau,vn1,vn2,jp,hw,
     1      d,kq,info)
        return
        endif
c
        if( rtol .lt. rla_eps() .or. nb .ge. mn ) then
        iflag=1
        return
        endif
        l=nb
 1000 continue
        call rla_zsketch(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,l,npow,
     1      iseed,x,z,y,tau,vn1,vn2,jp,hw,
     1      d,kq,info)
        if( info .ne. 0 .or. kq .eq. 0 ) return
        if( kq .gt. nextra ) then
        if( dble(d(kq-nextra)) .le. rtol*dble(d(1)) ) return
        endif
        l=min(4*l,mn)
        if( l .ge. mn ) then
        iflag=1
        kq=0
        return
        endif
        goto 1000
        end

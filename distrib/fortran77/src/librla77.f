        subroutine rla_dlarfg(n,alpha,x,tau)
        implicit real *8 (a-h,o-z)
        real *8 alpha,x(*),tau
c
c       elementary reflector H = I - tau v v^T, v = (1, x), such that
c       H^T (alpha, x) = (beta, 0) with beta real (LAPACK dlarfg)
c
        if( n .le. 0 ) then
        tau=0
        return
        endif
        xnorm=0
        do 1200 i=1,n-1
        xnorm=xnorm+(x(i))**2
 1200 continue
        xnorm=sqrt(xnorm)
        alphr=alpha
        alphi=0
        if( xnorm .le. 0 .and. abs(alphi) .le. 0 ) then
        tau=0
        return
        endif
        beta=-sign(sqrt(alphr**2+alphi**2+xnorm**2),alphr)
        tau=(beta-alphr)/beta
        ascal=1/(alphr-beta)
        do 1400 i=1,n-1
        x(i)=x(i)*ascal
 1400 continue
        alpha=beta
        return
        end

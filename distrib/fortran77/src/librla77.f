        nout=mb
        nin=nb
        else
        nout=nb
        nin=mb
        endif
        if( nout .eq. 0 .or. k .eq. 0 ) return
        if( nin .eq. 0 ) then
        do 1200 i=1,nout*k
        y(i)=0
 1200 continue
        return
        endif
        if( idense .eq. 1 ) then
        call rla_dgemm(ib,nout,k,nin,a,lda,x,nin,y,nout)
        else
        call mv(ib,mb,nb,k,x,y,ipar,rpar,zpar)
        endif
        return
        end

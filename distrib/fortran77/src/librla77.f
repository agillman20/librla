        subroutine rla_dsvsort(p,q,g,ldg,v,ldv,s,tmp)
        implicit real *8 (a-h,o-z)
        integer p,q
        real *8 g(ldg,*),v(ldv,*),tmp(*),d
        real *8 s(*)
c
c       sort the Jacobi output by decreasing s, normalize the columns
c       of g to unit length, and replace columns with s = 0 by unit
c       vectors orthogonal to the others (so g is orthonormal)
c
        do 1800 j=1,q-1
        jmax=j
        do 1200 l=j+1,q
        if( s(l) .gt. s(jmax) ) jmax=l
 1200 continue
        if( jmax .eq. j ) goto 1800
        d=s(j)
        s(j)=s(jmax)
        s(jmax)=d
        do 1400 i=1,p
        d=g(i,j)
        g(i,j)=g(i,jmax)
        g(i,jmax)=d
 1400 continue
        do 1600 i=1,q
        d=v(i,j)
        v(i,j)=v(i,jmax)
        v(i,jmax)=d
 1600 continue
 1800 continue
c
        do 3000 j=1,q
        sj=s(j)
        if( sj .gt. 0 ) then
        do 2000 i=1,p
        g(i,j)=g(i,j)/sj
 2000 continue
        goto 3000
        endif
c
c       . . . s(j) = 0: try e_1, e_2, ... orthogonalized (twice)
c       against the other columns, until one survives
c
        do 2800 ie=1,p
        do 2100 i=1,p
        tmp(i)=0
 2100 continue
        tmp(ie)=1
        do 2500 ipass=1,2
        do 2400 l=1,q
        if( l .eq. j ) goto 2400
        if( l .gt. j .and. s(l) .le. 0 ) goto 2400
        d=0
        do 2200 i=1,p
        d=d+g(i,l)*tmp(i)
 2200 continue
        do 2300 i=1,p
        tmp(i)=tmp(i)-d*g(i,l)
 2300 continue
 2400 continue
 2500 continue
        d=0
        do 2600 i=1,p
        d=d+(tmp(i))**2
 2600 continue
        rn=sqrt(d)
        if( rn .gt. 0.5d0 ) then
        do 2700 i=1,p
        g(i,j)=tmp(i)/rn
 2700 continue
        goto 3000
        endif
 2800 continue
 3000 continue
        return
        end

        subroutine rla_zqhta(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,kq,
     1      q,b,zt)
        implicit real *8 (a-h,o-z)
        complex *16 a(lda,*)
        dimension ipar(*),rpar(*)
        complex *16 zpar(*)
        external mv
        complex *16 q(m,*),b(kq,*),zt(n,*)
c
c       b (kq x n) = Q^H A; for anything but a stored matrix,
c       (A^H Q)^H via zt (n x kq)
c
        if( idense .eq. 1 .and. iadj .eq. 0 ) then
        call rla_zgemm(1,kq,n,m,q,m,a,lda,b,kq)
        return
        endif
        call rla_zapply(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,1,kq,q,
     1      zt)
        do 1400 j=1,n
        do 1200 i=1,kq
        b(i,j)=dconjg(zt(j,i))
 1200 continue
 1400 continue
        return
        end

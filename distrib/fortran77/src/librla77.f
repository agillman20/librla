c
        subroutine rla_dtcomp(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,r,
     1      ldr,ipiv,k,method,rts,t,ldt,w,
     1      info)
        implicit real *8 (a-h,o-z)
        real *8 a(lda,*)
        dimension ipar(*),rpar(*)
        complex *16 zpar(*)
        external mv
        real *8 r(ldr,*),t(ldt,*),w(*),d
        dimension ipiv(*)
c
c       ID interpolation matrix t (k x (n-k)) from R (rows 1:k):
c       method 1 fast (back substitution, svd if R11 is near-singular),
c       2 svd (pseudoinverse of R11 dropping s < max(rts,eps)*smax),
c       3 lstsq (least squares on the columns of A)
c
        info=0
        nk=n-k
        if( k .eq. 0 .or. nk .eq. 0 ) return
        eps=rla_eps()
c
        if( method .eq. 3 ) then
c
c       . . . A in pivot order: A1 = columns 1:k, B = columns k+1:n
c
        iam=1
        ie=iam+m*n
        isw=ie+64*max(m,n)
        call rla_dgetmatp(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,ipiv,
     1      w(iam),w(ie))
        call rla_dlsqip(m,k,w(iam),nk,w(iam+m*k),m,t,ldt,w(isw),info)
        return
        endif
c
        if( method .eq. 1 ) then
        dmin=abs(r(1,1))
        dmax=dmin
        do 1600 i=2,k
        dmin=min(dmin,abs(r(i,i)))
        dmax=max(dmax,abs(r(i,i)))
 1600 continue
        if( dmin .gt. eps*dmax ) then
c
c       . . . t = R11 \ R12 by back substitution
c
        do 2000 j=1,nk
        do 1700 i=1,k
        t(i,j)=r(i,k+j)
 1700 continue
        do 1900 i=k,1,-1
        t(i,j)=t(i,j)/r(i,i)
        d=t(i,j)
        do 1800 l=1,i-1
        t(l,j)=t(l,j)-d*r(l,i)
 1800 continue
 1900 continue
 2000 continue
        return
        endif
        endif
c
c       . . . t = pinv(R11) R12 through the SVD of R11
c
        iu=1
        iv=iu+k*k
        is=iv+k*k
        itm=is+k
        do 2050 j=1,k
        do 2040 i=1,k
        w(iu+(i-1)+(j-1)*k)=r(i,j)
 2040 continue
 2050 continue
        call rla_dsvdip(k,k,w(iu),k,-1.0d0,-1.0d0,kqd,w(is),w(iv),k,
     1      w(itm),info)
        do 2200 j=1,nk
        do 2100 i=1,k
        t(i,j)=0
 2100 continue
 2200 continue
        if( info .ne. 0 ) return
        smax=w(is)
        if( smax .le. 0 ) return
        cut=max(rts,eps)*smax
        do 2800 j=1,nk
        do 2700 l=1,k
        sl=w(is+l-1)
        if( sl .lt. cut ) goto 2700
        d=0
        do 2500 i=1,k
        d=d+w(iu+(i-1)+(l-1)*k)*r(i,k+j)
 2500 continue
        d=d/sl
        do 2600 i=1,k
        t(i,j)=t(i,j)+w(iv+(i-1)+(l-1)*k)*d
 2600 continue
 2700 continue
 2800 continue
        return
        end

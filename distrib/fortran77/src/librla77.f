c
c
c
        subroutine rla_didsd(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,
     1      rtol,nb,npow,nextra,method,iseed,
     1      kcap,k,ipiv,t,ldt,w,lw,ier)
        implicit real *8 (a-h,o-z)
        real *8 a(lda,*)
        dimension ipar(*),rpar(*)
        complex *16 zpar(*)
        external mv
        real *8 t(ldt,*),w(*)
        dimension iseed(4),jseed(4),ioff(24),ipiv(*)
c
        k=0
        call rla_chkmet(method,ier)
        if( ier .eq. 0 ) call rla_chkarg(idense,m,n,lda,rtol,nb,npow,
     1      nextra,iseed,kcap,ier)
        if( ier .eq. 0 .and. ldt .lt. max(1,kcap) ) ier=2
        if( ier .ne. 0 ) return
        kt=min(m,n)
        if( rtol .ge. 1 ) kt=min(int(rtol),kt)
        call rla_dtlay(m,n,kt,method,ltn)
        call rla_dqrlay(m,n,rtol,nb,nextra,ltn,ioff,lneed)
        call rla_dlwchk(lw,lneed,w,ier)
        if( ier .ne. 0 .or. lw .lt. 0 ) return
c
        do 1100 i=1,4
        jseed(i)=iseed(i)
 1100 continue
        call rla_dqrcore(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,rtol,
     1      nb,npow,nextra,jseed,w,ioff,
     1      .false.,kr,iq,ldqq,irc,ldrc,ipv,info)
        if( info .ne. 0 ) then
        ier=3
        return
        endif
        k=kr
        if( k .gt. kcap ) then
        ier=4
        return
        endif
        rts=rtol
        if( rtol .ge. 1 ) rts=0
        do 1200 j=1,n
        ipiv(j)=nint(w(ipv+j-1))
 1200 continue
        call rla_dtcomp(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,w(irc),
     1      ldrc,ipiv,k,method,rts,t,ldt,
     1      w(1),info)
        if( info .ne. 0 ) then
        ier=3
        return
        endif
        do 1600 i=1,4
        iseed(i)=jseed(i)
 1600 continue
        return
        end

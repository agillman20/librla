c
c
        subroutine rla_zjacobi(p,q,g,ldg,v,ldv,s,info)
        implicit real *8 (a-h,o-z)
        integer p,q
        complex *16 g(ldg,*),v(ldv,*),gamma,e,gp,gq,ce
        complex *16 s(*)
c
c       one-sided (Hestenes) Jacobi on the columns of g (p x q, p >= q):
c       on exit g = U diag(s) with orthogonal columns, v (q x q) the
c       accumulated rotations, so that g(in) = g(out) v^H. s holds the
c       column norms, unsorted. info=1 if 60 sweeps did not converge
c
        info=0
        eps=rla_eps()
        tol=sqrt(dble(p))*eps
        do 1400 j=1,q
        do 1200 i=1,q
        v(i,j)=0
 1200 continue
        v(j,j)=1
 1400 continue
c
        do 3000 isweep=1,60
        nrot=0
        do 2800 jp=1,q-1
        do 2600 jq=jp+1,q
        alpha=0
        beta=0
        gamma=0
        do 2000 i=1,p
        alpha=alpha+(dble(g(i,jp))**2+dimag(g(i,jp))**2)
        beta=beta+(dble(g(i,jq))**2+dimag(g(i,jq))**2)
        gamma=gamma+dconjg(g(i,jp))*g(i,jq)
 2000 continue
        ag=abs(gamma)
        if( ag .le. 0 ) goto 2600
        if( ag .le. tol*sqrt(alpha)*sqrt(beta) ) goto 2600
        nrot=nrot+1
c
c       . . . rotation [c, sn*e; -sn*conj(e), c] zeroing gamma
c
        zeta=(beta-alpha)/(2*ag)
        if( abs(zeta) .gt. 1.0d100 ) then
        t=0.5d0/zeta
        else
        t=sign(1.0d0,zeta)/(abs(zeta)+sqrt(1+zeta**2))
        endif
        c=1/sqrt(1+t**2)
        sn=c*t
        e=gamma/ag
        ce=dconjg(e)
        do 2200 i=1,p
        gp=g(i,jp)
        gq=g(i,jq)
        g(i,jp)=c*gp-sn*ce*gq
        g(i,jq)=sn*e*gp+c*gq
 2200 continue
        do 2400 i=1,q
        gp=v(i,jp)
        gq=v(i,jq)
        v(i,jp)=c*gp-sn*ce*gq
        v(i,jq)=sn*e*gp+c*gq
 2400 continue
 2600 continue
 2800 continue
        if( nrot .eq. 0 ) goto 3200
 3000 continue
        info=1
 3200 continue
c
        do 3600 j=1,q
        d=0
        do 3400 i=1,p
        d=d+(dble(g(i,j))**2+dimag(g(i,j))**2)
 3400 continue
        s(j)=sqrt(d)
 3600 continue
        return
        end

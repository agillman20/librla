c
c
c
c
        subroutine rla_zqrlay(m,n,rtol,nb,nextra,lres,ioff,lneed)
        implicit real *8 (a-h,o-z)
        dimension ioff(*)
c
c       workspace layout of rla_zqrcore (worst case, fixed before the
c       data-dependent run). From 1: the sketch (1-9: x z y tau vn1
c       vn2 jp hw d, ending at ioff(19)), overlaid by the fallback A
c       and e (16-17) and by lres scalars for the caller's next stage.
c       After them: the QR of B (10-15: jp tau vn1 vn2 hw R)
c
        mn=min(m,n)
        call rla_lmax(m,n,rtol,nb,nextra,l)
        ioff(1)=1
        ioff(2)=ioff(1)+n*l
        ioff(3)=ioff(2)+n*l
        ioff(4)=ioff(3)+m*l
        do 1200 i=5,10
        ioff(i)=ioff(i-1)+l
 1200 continue
        ioff(19)=ioff(10)
        ioff(16)=1
        ioff(17)=1+m*n
        iend=max(ioff(10),1+lres)
        if( rtol .lt. 1 ) iend=max(iend,ioff(17)+64*max(m,n))
        ioff(10)=iend
        do 1400 i=11,15
        ioff(i)=ioff(i-1)+n
 1400 continue
c
c       R has min(kq,n) <= min(l,mn) rows, or mn after a fallback
c
        krow=mn
        if( rtol .ge. 1 ) krow=min(l,mn)
        lneed=ioff(15)+krow*n
        return
        end
c
c
c
c
c
        subroutine rla_zsvdlay(m,n,rtol,nb,nextra,ladj,ioff,lneed)
        implicit real *8 (a-h,o-z)
        dimension ioff(*)
c
c       workspace layout of rla_zsvdd on the tall operator (m >= n):
c       1-9 sketch, 10-13 small in-place SVD (v s tmp, Ut if the user
c       matrix is wide, ladj=1); the fallback (15-20: A, adjoint
c       scratch, e, v, s, tmp) overlays the sketch from 1
c
        call rla_lmax(m,n,rtol,nb,nextra,l)
        kqm=min(m,l)
        iq=min(kqm,n)
        ioff(1)=1
        ioff(2)=ioff(1)+n*l
        ioff(3)=ioff(2)+n*l
        ioff(4)=ioff(3)+m*l
        do 1200 i=5,10
        ioff(i)=ioff(i-1)+l
 1200 continue
        ioff(11)=ioff(10)+iq*iq
        ioff(12)=ioff(11)+iq
        ioff(13)=ioff(12)+iq*iq+5*iq+max(m,n,kqm)+1
        ioff(14)=ioff(13)
        if( ladj .eq. 1 ) ioff(14)=ioff(13)+m*iq
        lneed=ioff(14)
        if( rtol .ge. 1 ) return
        ioff(15)=1
        ioff(16)=ioff(15)+m*n
        ioff(17)=ioff(16)
        if( ladj .eq. 1 ) ioff(17)=ioff(16)+m*n
        ioff(18)=ioff(17)+64*max(m,n)
        ioff(19)=ioff(18)+n*n
        ioff(20)=ioff(19)+n
        ioff(21)=ioff(20)+n*n+5*n+m+1
        lneed=max(lneed,ioff(21))
        return
        end
c
c
c
c
c
        subroutine rla_zorthd(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,
     1      rtol,nb,npow,nextra,iseed,kcap,k,
     1      q,ldq,diagr,iflag,w,lw,ier)
        implicit real *8 (a-h,o-z)
        complex *16 a(lda,*)
        dimension ipar(*),rpar(*)
        complex *16 zpar(*)
        external mv
        complex *16 q(ldq,*),w(*)
        dimension iseed(4),jseed(4),ioff(24),diagr(*)
c
        k=0
        iflag=1
        call rla_chkarg(idense,m,n,lda,rtol,nb,npow,nextra,iseed,
     1      kcap,ier)
        if( ier .eq. 0 .and. ldq .lt. max(1,m) ) ier=2
        if( ier .ne. 0 ) return
        call rla_zqrlay(m,n,rtol,nb,nextra,0,ioff,lneed)
        lneed=ioff(19)
        call rla_zlwchk(lw,lneed,w,ier)
        if( ier .ne. 0 .or. lw .lt. 0 ) return
c
        do 1100 i=1,4
        jseed(i)=iseed(i)
 1100 continue
        call rla_zorthc(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,rtol,nb,
     1      npow,nextra,jseed,w(ioff(1)),
     1      w(ioff(2)),w(ioff(3)),w(ioff(4)),w(ioff(5)),w(ioff(6)),
     2      w(ioff(7)),w(ioff(8)),w(ioff(9)),kq,iflag,info)
        if( info .ne. 0 ) then
        ier=3
        iflag=1
        return
        endif
        k=kq
        if( k .gt. kcap ) then
        ier=4
        return
        endif
        iy=ioff(3)
        do 1400 j=1,k
        diagr(j)=dble(w(ioff(9)+j-1))
        do 1200 i=1,m
        q(i,j)=w(iy+(i-1)+(j-1)*m)
 1200 continue
 1400 continue
        do 1600 i=1,4
        iseed(i)=jseed(i)
 1600 continue
        return
        end

        subroutine rla_dsvd(m,n,a,lda,rtol,atol,kmax,iexit,k,s,u,ldu,
     1      vt,ldvt,w,lw,ier)
        implicit real *8 (a-h,o-z)
        real *8 a(lda,*),u(ldu,*),vt(ldvt,*),w(*)
        dimension s(*)
c
c       truncated SVD of the dense m x n matrix a (not modified), any
c       shape: a ~ u (m x k) diag(s) vt (k x n), keeping the singular
c       values s_j >= max(rtol*s_1, atol), at most kmax of them
c       (rtol = atol = 0, kmax = min(m,n), iexit = 0: the full SVD).
c       Preconditioned one-sided Jacobi (rla_dsvdip) on a or a^T,
c       whichever is tall; its pivoted QR may stop early (iexit):
c
c         0  no early exit (all min(m,n) values, zeros included)
c         1  stop when the residual columns are rounding noise,
c            ||R22||_F <= 10*sqrt(min(m,n))*eps*||A|| (the size of
c            Jacobi's own backward error): as accurate as the full
c            SVD, fast when a is low-rank to working precision
c         2  stop when ||R22||_F <= 0.01*max(rtol*s_1, atol): the
c            cost follows the rank at the requested tolerance; kept
c            values move by at most that much (absolute)
c         3  LAPACK dgeqp3rk's rule: stop when the largest residual
c            column norm is <= max(rtol*(largest column norm of a),
c            atol). Fastest; values near the threshold may move by up
c            to about sqrt(min(m,n)) times it, so the count there is
c            approximate
c
c       kmax only caps the output. w(lw): lw = -1 returns the size
c       needed in w(1). ier: 0 success, 2 invalid argument, 3 no
c       convergence, 5 lw too small (w(1) = size needed)
c
        ier=0
        k=0
        kk=min(m,n)
        ip=max(m,n)
        if( m .lt. 0 .or. n .lt. 0 .or. lda .lt. max(1,m) .or.
     1      kmax .lt. 0 .or. iexit .lt. 0 .or. iexit .gt. 3 .or.
     2      ldu .lt. max(1,m) .or. ldvt .lt. max(1,min(kmax,kk)) )
     3      ier=2
        if( .not. (rtol .ge. 0 .and. atol .ge. 0) ) ier=2
        if( ier .ne. 0 ) return
        ig=1
        iv=ig+ip*kk
        is=iv+kk*kk
        iwk=is+kk
        lneed=iwk+kk*kk+5*kk+ip+1
        call rla_dlwchk(lw,lneed,w,ier)
        if( ier .ne. 0 .or. lw .lt. 0 .or. kk .eq. 0 ) return
c
c       g = a (m >= n) or a^T (m < n), tall ip x kk
c
        do 1400 j=1,kk
        do 1200 i=1,ip
        if( m .ge. n ) then
        w(ig+(i-1)+(j-1)*ip)=a(i,j)
        else
        w(ig+(i-1)+(j-1)*ip)=a(j,i)
        endif
 1200 continue
 1400 continue
c
c       early-exit tolerances for the largest residual column norm,
c       which bounds ||R22||_F/sqrt(kk)
c
        eps=rla_eps()
        qatol=-1
        qrtol=-1
        if( iexit .eq. 1 ) qrtol=10*eps
        if( iexit .eq. 2 ) then
        qrtol=max(10*eps,0.01d0*rtol/sqrt(dble(kk)))
        if( atol .gt. 0 ) qatol=0.01d0*atol/sqrt(dble(kk))
        endif
        if( iexit .eq. 3 ) then
        qrtol=max(eps,rtol)
        if( atol .gt. 0 ) qatol=atol
        endif
        call rla_dsvdip(ip,kk,w(ig),ip,qatol,qrtol,kq,w(is),w(iv),kk,
     1      w(iwk),info)
        if( info .ne. 0 ) then
        ier=3
        return
        endif
        if( kq .eq. 0 ) return
c
        cut=max(rtol*w(is),atol)
        do 1600 j=1,min(kq,kmax)
        if( w(is+j-1) .lt. cut ) goto 1700
        k=j
 1600 continue
 1700 continue
c
c       a = g v^T: u = g, vt = v^T; a^T = g v^T: u = v, vt = g^T
c
        do 2400 j=1,k
        s(j)=w(is+j-1)
        do 2000 i=1,ip
        if( m .ge. n ) then
        u(i,j)=w(ig+(i-1)+(j-1)*ip)
        else
        vt(j,i)=w(ig+(i-1)+(j-1)*ip)
        endif
 2000 continue
        do 2200 i=1,kk
        if( m .ge. n ) then
        vt(j,i)=w(iv+(i-1)+(j-1)*kk)
        else
        u(i,j)=w(iv+(i-1)+(j-1)*kk)
        endif
 2200 continue
 2400 continue
        return
        end

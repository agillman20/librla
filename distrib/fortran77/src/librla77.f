c
c
        subroutine rla_didqd(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,
     1      rtol,method,kcap,k,ipiv,t,ldt,w,lw,
     1      ier)
        implicit real *8 (a-h,o-z)
        real *8 a(lda,*)
        dimension ipar(*),rpar(*)
        complex *16 zpar(*)
        external mv
        real *8 t(ldt,*),w(*)
        dimension ipiv(*),iseed(4)
        integer rla_drankd
c
        k=0
        iseed(1)=0
        iseed(2)=0
        iseed(3)=0
        iseed(4)=1
        call rla_chkmet(method,ier)
        if( ier .eq. 0 ) call rla_chkarg(idense,m,n,lda,rtol,0,0,0,
     1      iseed,kcap,ier)
        if( ier .eq. 0 .and. ldt .lt. max(1,kcap) ) ier=2
        if( ier .ne. 0 ) return
c
c       layout: A and e from 1, later overlaid by the T stage; then
c       jp tau vn1 vn2 hw (n each) and R (mn*n)
c
        mn=min(m,n)
        kt=mn
        if( rtol .ge. 1 ) kt=min(int(rtol),mn)
        call rla_dtlay(m,n,kt,method,ltn)
        iam=1
        ie=iam+m*n
        ijp=1+max(m*n+64*max(m,n),ltn)
        itau=ijp+n
        iv1=itau+n
        iv2=iv1+n
        ihw=iv2+n
        irc=ihw+n
        lneed=irc+mn*n
        call rla_dlwchk(lw,lneed,w,ier)
        if( ier .ne. 0 .or. lw .lt. 0 ) return
c
        call rla_dgetmat(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,w(iam),
     1      w(iam),w(ie))
        ldrc=max(1,mn)
        call rla_dqrfac(m,n,w(iam),max(1,m),w(ijp),w(itau),w(iv1),
     1      w(iv2),w(ihw),w(irc),ldrc,.false.)
        if( rtol .ge. 1 ) then
        k=min(int(rtol),mn)
        rts=0
        else
        k=rla_drankd(mn,w(irc),ldrc,rtol)
        rts=rtol
        endif
        if( k .gt. kcap ) then
        ier=4
        return
        endif
        do 1200 j=1,n
        ipiv(j)=nint(w(ijp+j-1))
 1200 continue
        call rla_dtcomp(idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar,w(irc),
     1      ldrc,ipiv,k,method,rts,t,ldt,
     1      w(1),info)
        if( info .ne. 0 ) ier=3
        return
        end

c
c
c
c
        subroutine rla_zqrcp(m,n,kmax,abstol,reltol,a,lda,k,rmaxk,
     1      relmaxk,ipiv,tau,w,ier)
        implicit real *8 (a-h,o-z)
        complex *16 a(lda,*),tau(*),w(*)
        dimension ipiv(*)
c
c       truncated Householder QR with column pivoting and early exit,
c       after LAPACK 3.12 zgeqp3rk (without its right-hand sides):
c       the factorization stops with k columns when k = kmax, or the
c       largest column norm of the residual R22 is <= abstol, or is
c       <= reltol times the largest column norm of a (a negative
c       tolerance disables its test; kmax >= min(m,n) for no limit).
c
c       On exit a(:,ipiv) = Q(:,1:k) R(1:k,:) + [0 R22]: R in the upper
c       triangle of rows 1:k, the reflectors H(i) = I - tau(i) v v^H
c       below it (rla_zorgqr forms Q), and R22 in a(k+1:m,k+1:n).
c       rmaxk = largest column norm of R22 (0 if k = min(m,n)),
c       relmaxk = rmaxk / (largest column norm of a). ipiv (n), tau
c       (min(m,n)), w (4*n) scratch. ier: 0, or 2 invalid argument
c
        ier=0
        k=0
        rmaxk=0
        relmaxk=0
        if( m .lt. 0 .or. n .lt. 0 .or. lda .lt. max(1,m) .or.
     1      kmax .lt. 0 ) ier=2
        if( .not. (abstol .ge. 0 .or. abstol .lt. 0) ) ier=2
        if( .not. (reltol .ge. 0 .or. reltol .lt. 0) ) ier=2
        if( ier .ne. 0 ) return
        call rla_zqrpk(m,n,a,lda,kmax,abstol,reltol,w(1),tau,w(n+1),
     1      w(2*n+1),w(3*n+1),k,rmaxk,rmax0)
        do 1200 j=1,n
        ipiv(j)=nint(dble(w(j)))
 1200 continue
        if( rmax0 .gt. 0 ) relmaxk=rmaxk/rmax0
        return
        end

        integer function rla_zrankd(kk,r,ldr,rtol)
        implicit real *8 (a-h,o-z)
        complex *16 r(ldr,*)
c
c       number of |r(i,i)| >= rtol*|r(1,1)|, i <= kk (pivoted R)

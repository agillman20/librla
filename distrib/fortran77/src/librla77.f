        subroutine rla_dqrp(m,n,a,lda,jp,tau,vn1,vn2,work)
        implicit real *8 (a-h,o-z)
        real *8 a(lda,*),tau(*),work(*)
        real *8 jp(*),vn1(*),vn2(*)
c
c       full Householder QR with column pivoting (rla_dqrpk without
c       early exit): a(:,jp) = Q R, R in the upper triangle,
c       reflectors below it, jp the 1-based pivots as real numbers
c
        call rla_dqrpk(m,n,a,lda,min(m,n),-1.0d0,-1.0d0,jp,tau,vn1,
     1      vn2,work,k,rmaxk,rmax0)
        return
        end

        subroutine rla_zlsqip(m,k,a1,nrhs,b,ldb,x,ldx,w,info)
        implicit real *8 (a-h,o-z)
        complex *16 a1(m,k),b(ldb,*),x(ldx,*),w(*),d
c
c       minimum-norm least squares x (k x nrhs) = pinv(a1) b, m >= k,
c       dropping singular values <= eps*smax (LAPACK zgelsd with
c       rcond = eps). a1 is overwritten; w: 2*k*k + 6*k + m
c
        info=0
        do 1200 j=1,nrhs
        do 1100 i=1,k
        x(i,j)=0
 1100 continue
 1200 continue
        if( m .eq. 0 .or. k .eq. 0 .or. nrhs .eq. 0 ) return
        iv=1
        is=iv+k*k
        it=is+k
        call rla_zsvdip(m,k,a1,m,-1.0d0,-1.0d0,kqd,w(is),w(iv),k,
     1      w(it),info)
        if( info .ne. 0 ) return
        smax=dble(w(is))
        nk=0
        do 1300 l=1,k
        if( dble(w(is+l-1)) .gt. rla_eps()*smax ) nk=l
 1300 continue
c
c       x = v diag(1/s) U^H b over the nk kept singular values
c
        do 2000 j=1,nrhs
        do 1800 l=1,nk
        d=0
        do 1600 i=1,m
        d=d+dconjg(a1(i,l))*b(i,j)
 1600 continue
        d=d/dble(w(is+l-1))
        do 1700 i=1,k
        x(i,j)=x(i,j)+w(iv+(i-1)+(l-1)*k)*d
 1700 continue
 1800 continue
 2000 continue
        return
        end

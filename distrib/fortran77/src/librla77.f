        subroutine rla_zlarfl(m,n,v,tau,c,ldc,work)
        implicit real *8 (a-h,o-z)
        complex *16 v(*),tau,c(ldc,*),work(*),d
c
c       c (m x n) := (I - tau v v^H) c
c
        if( abs(tau) .le. 0 ) return
        do 1400 j=1,n
        d=0
        do 1200 i=1,m
        d=d+dconjg(v(i))*c(i,j)
 1200 continue
        work(j)=d
 1400 continue
        do 1800 j=1,n
        d=tau*work(j)
        do 1600 i=1,m
        c(i,j)=c(i,j)-v(i)*d
 1600 continue
 1800 continue
        return
        end

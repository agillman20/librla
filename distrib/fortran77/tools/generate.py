#!/usr/bin/env python3
"""Generate the real and complex halves of the librla77 sources.

Fortran 77 has no generics, so each routine exists twice: rla_d* (real *8)
and rla_z* (complex *16). They are written once, as templates in this
directory, and expanded here:

    kernels.f.in, drivers.f.in   -> src/librla77.f (with the public
                                    wrappers and shared routines below)
    test_kind.f.in               -> test/test_all.f (with the harness below)

Template tokens: @T (d or z), @S (real *8 or complex *16), @RV (the type of
real-valued scratch arrays, which live in the work array: real *8 or
complex *16), @RE(x) and @IM(x) (real and imaginary part), @CJ(x)
(conjugate), @ABS2(x) (|x|**2), @H (T or H, in comments), @OP/@OPDECL (the
operator arguments), @NAME. Lines starting with @D (@Z) are kept only in
the real (complex) half; lines starting with !! are template comments.

Usage, from distrib/fortran77:
    python3 tools/generate.py           # rewrite the generated files
    python3 tools/generate.py --check   # exit 1 if any is out of date

Author: Adrianna Gillman, Zydrunas Gimbutas
SPDX-License-Identifier: MIT
Assisted by: Claude Code (Anthropic)
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent
CHECK = "--check" in sys.argv[1:]
GENERATED = {}

AUTHOR = """c
c       Author: Adrianna Gillman, Zydrunas Gimbutas
c       SPDX-License-Identifier: MIT
c       Assisted by: Claude Code (Anthropic)
c
c       Generated by tools/generate.py: edit the templates in tools/
c       (or the script) and regenerate, not this file.
"""

OP = "idense,iadj,m,n,a,lda,mv,ipar,rpar,zpar"
OPDECL = """        @S a(lda,*)
        dimension ipar(*),rpar(*)
        complex *16 zpar(*)
        external mv"""

KINDS = {
    "d": dict(S="real *8", RV="real *8", H="T", NAME="real", L="real",
              PARGS="ipar,pdat,zdum", PDAT="rpar",
              RE="{}", IM="0", CJ="{}", ABS2="({})**2"),
    "z": dict(S="complex *16", RV="complex *16", H="H", NAME="complex",
              L="cplx", PARGS="ipar,rdum,pdat", PDAT="zpar",
              RE="dble({})", IM="dimag({})", CJ="dconjg({})",
              ABS2="(dble({0})**2+dimag({0})**2)"),
}


def subst_calls(text, name, fmt):
    """Replace @NAME(arg) (balanced parentheses) by fmt.format(arg)."""
    tok = "@" + name + "("
    while tok in text:
        i = text.index(tok)
        j, depth = i + len(tok), 1
        while depth:
            depth += {"(": 1, ")": -1}.get(text[j], 0)
            j += 1
        text = text[:i] + fmt.format(text[i + len(tok):j - 1]) + text[j:]
    return text


def expand(text, t):
    p = KINDS[t]
    lines = []
    for line in text.splitlines():
        if line.startswith("!!"):
            continue
        if line.startswith("@D") or line.startswith("@Z"):
            if line[1].lower() != t:
                continue
            line = "  " + line[2:]
        lines.append(line)
    text = "\n".join(lines) + "\n"
    text = text.replace("@OPDECL", OPDECL).replace("@OP", OP)
    for name in ("RE", "IM", "CJ", "ABS2"):
        text = subst_calls(text, name, p[name])
    for key in ("NAME", "PARGS", "PDAT", "RV", "L", "S", "H"):
        text = text.replace("@" + key, p[key])
    text = text.replace("@T", t)
    assert "@" not in text, re.findall(r"@\w+", text)[:5]
    return wrap72(text)


def wrap72(text):
    """Break statement lines longer than 72 columns at commas onto
    continuation lines (column 6 = '1')."""
    out = []
    for line in text.splitlines():
        while len(line) > 72 and not line.startswith(("c", "C", "!")):
            quoted, cut = False, -1
            for i, ch in enumerate(line[:72]):
                if ch == "'":
                    quoted = not quoted
                elif ch == "," and not quoted:
                    cut = i
            assert cut > 12, line
            out.append(line[:cut + 1])
            line = "     1      " + line[cut + 1:].lstrip()
        out.append(line)
    return "\n".join(out) + "\n"


def check_columns(name, text):
    bad = [i + 1 for i, l in enumerate(text.splitlines())
           if len(l) > 72 and not l.startswith(("c", "C", "!"))]
    if bad:
        sys.exit(f"{name}: lines longer than 72 columns: {bad[:10]}")
    bad = [i + 1 for i, l in enumerate(text.splitlines())
           if l.startswith(("c", "C")) and len(l) > 72]
    if bad:
        sys.exit(f"{name}: comment lines longer than 72 columns: {bad[:10]}")


def fcall(head, args, indent="        "):
    """A fixed-form statement `head(args)` wrapped at 72 columns."""
    out, line = [], indent + head + "("
    for i, a in enumerate(args):
        piece = a + ("," if i < len(args) - 1 else ")")
        if len(line) + len(piece) > 72:
            out.append(line)
            line = "     1      "
        line += piece
    out.append(line)
    return "\n".join(out)



# name, driver, argument list after the operator, declarations
FUNCS = [
    ("orth_sketch", "orthd",
     "rtol,nb,npow,nextra,iseed,kcap,k,q,ldq,diagr,flag,w,lw,ier",
     """        @S q(ldq,*),w(*)
        dimension iseed(4),diagr(*)
        integer flag""",
     "orthonormal basis q (m x k) of the range of A"),
    ("qr_sketch", "qrd",
     "rtol,nb,npow,nextra,iseed,kcap,k,q,ldq,r,ldr,ipiv,w,lw,ier",
     """        @S q(ldq,*),r(ldr,*),w(*)
        dimension iseed(4),ipiv(*)""",
     "truncated pivoted QR, A(:,ipiv) ~ q (m x k) r (k x n)"),
    ("svd_sketch", "svdd",
     "rtol,nb,npow,nextra,iseed,kcap,k,u,ldu,s,vt,ldvt,w,lw,ier",
     """        @S u(ldu,*),vt(ldvt,*),w(*)
        dimension iseed(4),s(*)""",
     "truncated SVD, A ~ u (m x k) diag(s) vt (k x n)"),
    ("id_sketch", "idsd",
     "rtol,nb,npow,nextra,method,iseed,kcap,k,ipiv,t,ldt,w,lw,ier",
     """        @S t(ldt,*),w(*)
        dimension iseed(4),ipiv(*)""",
     "interpolative decomposition by sketching"),
    ("id_qrpiv", "idqd",
     "rtol,method,kcap,k,ipiv,t,ldt,w,lw,ier",
     """        @S t(ldt,*),w(*)
        dimension ipiv(*)""",
     "interpolative decomposition by deterministic pivoted QR"),
]


def wrappers(t):
    out = []
    for name, drv, args, decl, desc in FUNCS:
        rest = args.split(",")
        call_rest = [("iflag" if a == "flag" else a) for a in rest]
        for free in (False, True):
            rname = f"rla_{t}{name}{'f' if free else ''}"
            if free:
                head = ["m", "n", "matvec", "ipar", "rpar", "zpar"] + rest
                opdecl = """        external matvec
        dimension ipar(*),rpar(*)
        complex *16 zpar(*)
        @S adum(1)"""
                setup = "        adum(1)=0"
                ops = ["0", "0", "m", "n", "adum", "1", "matvec", "ipar",
                       "rpar", "zpar"]
                kind = "matrix-free"
            else:
                head = ["m", "n", "a", "lda"] + rest
                opdecl = """        @S a(lda,*)
        dimension idum(1),rdum(1)
        complex *16 zdum(1)
        external rla_@Tnomv"""
                setup = """        idum(1)=0
        rdum(1)=0
        zdum(1)=0"""
                ops = ["1", "0", "m", "n", "a", "lda", "rla_@Tnomv", "idum",
                       "rdum", "zdum"]
                kind = "dense"
            fix = ""
            if "flag" in rest:
                fix = "\n        flag=iflag"
            text = f"""c
c
c
c
c
{fcall("subroutine " + rname, head)}
        implicit real *8 (a-h,o-z)
{opdecl}
{decl}
c
c       {desc}
c       (@NAME, {kind}; see README.md for the arguments)
c
{setup}
{fcall("call rla_@T" + drv, ops + call_rest)}{fix}
        return
        end
"""
            out.append(expand(text, t))
    return "".join(out)


SHARED = r"""c
c
c
c
c
        subroutine rla77_version(version)
        character *(*) version
c
c       library version (the single place it is defined for this port)
c
        version='0.1.0'
        return
        end
c
c
c
c
c
        real *8 function rla_eps()
        implicit real *8 (a-h,o-z)
        save e
        data e/0.0d0/
c
c       machine epsilon of the working precision (2**-52 in real *8,
c       2**-112 when promoted to real *16), computed once
c
        if( e .le. 0 ) then
        e=1
 1100 continue
        s=1+e/2
        if( s .gt. 1 ) then
        e=e/2
        goto 1100
        endif
        endif
        rla_eps=e
        return
        end
c
c
c
c
c
        subroutine rla_lcg(iseed,u)
        implicit real *8 (a-h,o-z)
        dimension iseed(4)
c
c       one step of the LAPACK dlaruv generator: iseed := a*iseed
c       mod 2**48 in base-4096 digits, a = (494,322,2508,2549), and
c       u = iseed/2**48 in (0,1). Integer arithmetic below 2**27,
c       so the stream equals LAPACK dlarnv in any precision
c
        i1=iseed(1)
        i2=iseed(2)
        i3=iseed(3)
        i4=iseed(4)
        it4=i4*2549
        it3=it4/4096
        it4=it4-4096*it3
        it3=it3+i3*2549+i4*2508
        it2=it3/4096
        it3=it3-4096*it2
        it2=it2+i2*2549+i3*2508+i4*322
        it1=it2/4096
        it2=it2-4096*it1
        it1=it1+i1*2549+i2*2508+i3*322+i4*494
        it1=mod(it1,4096)
        iseed(1)=it1
        iseed(2)=it2
        iseed(3)=it3
        iseed(4)=it4
        r=1.0d0/4096
        u=r*(dble(it1)+r*(dble(it2)+r*(dble(it3)+r*dble(it4))))
        return
        end
c
c
c
c
c
        subroutine rla_drandn(iseed,n,x)
        implicit real *8 (a-h,o-z)
        dimension iseed(4),x(*)
c
c       x(1:n) uniform(-1,1), the LAPACK dlarnv(2, iseed, n, x) stream
c
        do 1200 i=1,n
        call rla_lcg(iseed,u)
        x(i)=2*u-1
 1200 continue
        return
        end
c
c
c
c
c
        subroutine rla_zrandn(iseed,n,x)
        implicit real *8 (a-h,o-z)
        dimension iseed(4)
        complex *16 x(*)
c
c       x(1:n) with real and imaginary parts uniform(-1,1), the LAPACK
c       zlarnv(2, iseed, n, x) stream
c
        do 1200 i=1,n
        call rla_lcg(iseed,u1)
        call rla_lcg(iseed,u2)
        x(i)=dcmplx(2*u1-1,2*u2-1)
 1200 continue
        return
        end
c
c
c
c
c
        subroutine rla_lmax(m,n,rtol,nb,nextra,l)
        implicit real *8 (a-h,o-z)
c
c       largest sketch size used by orth_sketch: floor(rtol)+nextra in
c       rank mode; in tolerance mode the largest of nb, 4 nb, 16 nb,
c       ... below min(m,n), or 0 when no sketch is drawn
c
        mn=min(m,n)
        if( rtol .ge. 1 ) then
        l=int(rtol)+nextra
        return
        endif
        l=0
        if( rtol .lt. rla_eps() .or. nb .ge. mn .or. nb .le. 0 ) return
        l=nb
 1100 continue
        if( 4*l .lt. mn ) then
        l=4*l
        goto 1100
        endif
        return
        end
c
c
c
c
c
        subroutine rla_chkarg(idense,m,n,lda,rtol,nb,npow,nextra,
     1      iseed,kcap,ier)
        implicit real *8 (a-h,o-z)
        dimension iseed(4)
c
c       ier = 2 for an invalid argument: negative size or option, lda
c       too small, NaN rtol, a rank above 2.1e9, or an invalid iseed
c
        ier=0
        if( m .lt. 0 .or. n .lt. 0 .or. kcap .lt. 0 ) ier=2
        if( nb .lt. 0 .or. npow .lt. 0 .or. nextra .lt. 0 ) ier=2
        if( idense .eq. 1 .and. lda .lt. max(1,m) ) ier=2
        if( .not. (rtol .ge. 0 .or. rtol .lt. 0) ) then
        ier=2
        else if( rtol .ge. 2.1d9-nextra ) then
        ier=2
        endif
        do 1200 i=1,4
        if( iseed(i) .lt. 0 .or. iseed(i) .gt. 4095 ) ier=2
 1200 continue
        if( mod(iseed(4),2) .ne. 1 ) ier=2
        return
        end
c
c
c
c
c
        subroutine rla_chkmet(method,ier)
c
c       ier = 1 unless method is 1 (fast), 2 (svd) or 3 (lstsq)
c
        ier=0
        if( method .lt. 1 .or. method .gt. 3 ) ier=1
        return
        end
"""

HEADER = """c
c       librla77: randomized low-rank factorizations (Fortran 77 port)
c
c       Self-contained: no BLAS or LAPACK. Pivoted Householder QR,
c       one-sided Jacobi SVD and the LAPACK dlarnv random stream are
c       included, so the file can be compiled in any precision, e.g.
c       with gfortran -freal-8-real-16 -fdefault-integer-8 for quad.
c
c       Public routines (real *8: rla_d..., complex *16: rla_z...):
c
c         rla_dorth_sketch  orthonormal basis for the range of A
c         rla_dqr_sketch    truncated QR with column pivoting
c         rla_dsvd_sketch   truncated SVD
c         rla_did_sketch    interpolative decomposition by sketching
c         rla_did_qrpiv     interpolative decomposition by pivoted QR
c
c       and matrix-free variants with a trailing f (rla_dsvd_sketchf
c       ...). The calling sequences are those of the Fortran 95 port
c       (distrib/fortran95) plus a work array w(lw); lw = -1 returns
c       the size needed in w(1). Dense utilities:
c
c         rla_dsvd          truncated SVD of any shape (a is kept)
c         rla_dqrcp         pivoted QR with early exit (dgeqp3rk)
c         rla_dqrf          Householder QR without pivoting
c         rla_dorgqr        form Q from the reflectors
c
c       See README.md.
""" + AUTHOR

lib = HEADER + SHARED
for t in "dz":
    lib += wrappers(t)
for t in "dz":
    for name in ("drivers.f.in", "kernels.f.in"):
        lib += expand((HERE / name).read_text(), t)
lib = re.sub(r"[ \t]+\n", "\n", lib)
check_columns("src/librla77.f", lib)
GENERATED["src/librla77.f"] = lib

test_t = HERE / "test_kind.f.in"
test_h = HERE / "test_harness.f"
if test_t.exists() and test_h.exists():
    test = test_h.read_text()
    for t in "dz":
        test += expand(test_t.read_text(), t)
    test = re.sub(r"[ \t]+\n", "\n", test)
    check_columns("test/test_all.f", test)
    GENERATED["test/test_all.f"] = test

# ----------------------------------------------------------------------
# write, or compare with what is on disk
# ----------------------------------------------------------------------
stale = []
for rel, text in GENERATED.items():
    path = OUT / rel
    if CHECK:
        if not path.exists() or path.read_text() != text:
            stale.append(rel)
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
if stale:
    print("out of date (run python3 tools/generate.py):", ", ".join(stale))
    sys.exit(1)
print(("up to date: " if CHECK else "generated: ") + ", ".join(GENERATED))

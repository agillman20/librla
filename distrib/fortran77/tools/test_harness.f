        subroutine crossport()
        implicit real *8 (a-h,o-z)
        parameter (lw=400000)
        dimension ar(300,200),q(50,30),d(30),t(200,200),s(80)
        dimension iseed(4),jseed(4),ipiv(200)
        complex *16 ac(120,80),qc(50,30),u(120,80),vt(80,80),wz(lw)
        dimension w(lw)
        character *512 line
        character *24 fmte
        character *12 itoa
        integer flag
        save
c
c       the same five lines in every experimental port
c
        write(*,'(a)') '--- crossport ---'
        call hilbr(50,30,ar,50)
        iseed(1)=1
        iseed(2)=2
        iseed(3)=3
        iseed(4)=5
        call rla_dorth_sketch(50,30,ar,50,5.0d0,42,0,3,iseed,30,k,q,
     1      50,d,flag,w,lw,ier)
        do 1100 i=1,4
        jseed(i)=iseed(i)
 1100 continue
        line='CROSSPORT orth_real'
        ip=19
        do 1200 i=1,k
        call tappend(line,ip,fmte(d(i)))
 1200 continue
        write(*,'(a)') line(1:ip)
c
        call hilbc(50,30,ac,120)
        iseed(1)=1
        iseed(2)=2
        iseed(3)=3
        iseed(4)=5
        call rla_zorth_sketch(50,30,ac,120,5.0d0,42,0,3,iseed,30,k,qc,
     1      50,d,flag,wz,lw,ier)
        line='CROSSPORT orth_cplx'
        ip=19
        do 1300 i=1,k
        call tappend(line,ip,fmte(d(i)))
 1300 continue
        write(*,'(a)') line(1:ip)
c
        line='CROSSPORT seed_after'
        ip=20
        do 1350 i=1,4
        call tappend(line,ip,itoa(jseed(i)))
 1350 continue
        write(*,'(a)') line(1:ip)
c
        call hilbr(300,200,ar,300)
        iseed(1)=1
        iseed(2)=2
        iseed(3)=3
        iseed(4)=5
        call rla_did_sketch(300,200,ar,300,1.0d-10,42,0,12,1,iseed,
     1      200,k,ipiv,t,200,w,lw,ier)
        line='CROSSPORT id_real'
        ip=17
        call tappend(line,ip,itoa(k))
        do 1360 i=1,10
        call tappend(line,ip,itoa(ipiv(i)-1))
 1360 continue
        write(*,'(a)') line(1:ip)
c
        call hilbc(120,80,ac,120)
        iseed(1)=1
        iseed(2)=2
        iseed(3)=3
        iseed(4)=5
        call rla_zsvd_sketch(120,80,ac,120,10.0d0,42,1,12,iseed,80,k,
     1      u,120,s,vt,80,wz,lw,ier)
        line='CROSSPORT svd_cplx'
        ip=18
        call tappend(line,ip,itoa(k))
        do 1400 i=1,5
        call tappend(line,ip,fmte(s(i)))
 1400 continue
        write(*,'(a)') line(1:ip)
        return
        end

        subroutine tappend(line,ip,s)
        character *(*) line,s
        integer lentrm
c
c       append ' '//s (without trailing blanks) at position ip of line
c
        n=lentrm(s)
        line(ip+1:ip+1)=' '
        line(ip+2:ip+1+n)=s(1:n)
        ip=ip+1+n
        return
        end

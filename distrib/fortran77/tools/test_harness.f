        character *24 function fmte(x)
        implicit real *8 (a-h,o-z)
        character *40 buf
c
c       C printf("%.15e") formatting
c
        write(buf,'(1p,e24.15e3)') x
        do 1100 j=1,40
        if( buf(j:j) .ne. ' ' ) goto 1200
 1100 continue
 1200 continue
        ie=index(buf,'E')
        read(buf(ie+1:),*) iex
        if( iex .lt. 0 ) then
        write(fmte,'(a,a,i2.2)') buf(j:ie-1),'e-',-iex
        else
        write(fmte,'(a,a,i2.2)') buf(j:ie-1),'e+',iex
        endif
        return
        end

        character *12 function itoa(i)
        character *12 buf
c
c       i as a left-justified string
c
        write(buf,'(i12)') i
        do 1100 j=1,12
        if( buf(j:j) .ne. ' ' ) goto 1200
 1100 continue
        j=12
 1200 continue
        itoa=buf(j:12)
        return
        end

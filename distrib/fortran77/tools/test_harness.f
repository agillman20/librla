        logical function isperm(n,ipiv)
        dimension ipiv(*),iseen(4000)
c
        isperm=.false.
        do 1100 i=1,n
        iseen(i)=0
 1100 continue
        do 1200 i=1,n
        if( ipiv(i) .lt. 1 .or. ipiv(i) .gt. n ) return
        if( iseen(ipiv(i)) .ne. 0 ) return
        iseen(ipiv(i))=1
 1200 continue
        isperm=.true.
        return
        end

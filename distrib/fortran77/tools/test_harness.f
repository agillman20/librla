        subroutine hilbr(m,n,a,lda)
        implicit real *8 (a-h,o-z)
        dimension a(lda,*)
c
c       a(i,j) = 1/(i+j-1), 1-based (1/(i+j+1) 0-based)
c
        do 1200 j=1,n
        do 1100 i=1,m
        a(i,j)=1.0d0/(i+j-1)
 1100 continue
 1200 continue
        return
        end
c
c
c
c
c
        subroutine hilbc(m,n,a,lda)
        implicit real *8 (a-h,o-z)
        complex *16 a(lda,*)
c
c       a(i,j) = (1 + 1i*(i-j)/80)/(i+j-1), 1-based
c
        do 1200 j=1,n
        do 1100 i=1,m
        a(i,j)=dcmplx(1.0d0,(i-j)/80.0d0)/(i+j-1)
 1100 continue
 1200 continue
        return
        end

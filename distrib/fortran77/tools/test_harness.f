        subroutine test_rng()
        implicit real *8 (a-h,o-z)
        dimension iseed(4),x(6),ref(6),iref(4)
        complex *16 z(3)
        data ref/3.7327920546847082d-01,8.2093410748050388d-01,
     1      5.5866811353917711d-01,6.4291221902741569d-01,
     2      6.8760847451716955d-01,1.6449965895444763d-01/
        data iref/2384,3667,635,1229/
c
c       the built-in generator reproduces LAPACK dlarnv/zlarnv
c
        write(*,'(a)') '--- rng ---'
        iseed(1)=1
        iseed(2)=2
        iseed(3)=3
        iseed(4)=5
        call rla_drandn(iseed,6,x)
        e=0
        do 1100 i=1,6
        e=max(e,abs(x(i)-ref(i)))
 1100 continue
        call checkle('rng dlarnv reference values',e,1.0d-15)
        call check('rng dlarnv iseed after',iseed(1) .eq. iref(1)
     1      .and. iseed(2) .eq. iref(2) .and. iseed(3) .eq. iref(3)
     2      .and. iseed(4) .eq. iref(4))
        iseed(1)=1
        iseed(2)=2
        iseed(3)=3
        iseed(4)=5
        call rla_zrandn(iseed,3,z)
        e=0
        do 1200 i=1,3
        e=max(e,abs(dble(z(i))-ref(2*i-1)),abs(dimag(z(i))-ref(2*i)))
 1200 continue
        call checkle('rng zlarnv reference values',e,1.0d-15)
        call check('rng zlarnv iseed after',iseed(1) .eq. iref(1)
     1      .and. iseed(4) .eq. iref(4))
        return
        end

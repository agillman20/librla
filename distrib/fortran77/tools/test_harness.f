        integer function lentrm(s)
        character *(*) s
c
c       length of s without trailing blanks
c
        do 1100 i=len(s),1,-1
        if( s(i:i) .ne. ' ' ) goto 1200
 1100 continue
        i=0
 1200 continue
        lentrm=i
        return
        end
c

c
c       ---------------- complex helpers ----------------
c
        real *8 function tfro_z(m,n,a,lda)
        implicit real *8 (a-h,o-z)
        complex *16 a(lda,*)
c
        s=0
        do 1200 j=1,n
        do 1100 i=1,m
        s=s+(dble(a(i,j))**2+dimag(a(i,j))**2)
 1100 continue
 1200 continue
        tfro_z=sqrt(s)
        return
        end
c
c
c
c
c
        real *8 function tspan_z(m,n,a,lda,k,q,ldq,w)
        implicit real *8 (a-h,o-z)
        complex *16 a(lda,*),q(ldq,*),w(*)
c
c       ||A - Q Q^H A|| / ||A||
c
        ib=1
        ic=ib+k*n
        call rla_zgemm(1,k,n,m,q,ldq,a,lda,w(ib),max(1,k))
        call rla_zgemm(0,m,n,k,q,ldq,w(ib),max(1,k),w(ic),m)
        s=0
        do 1200 j=1,n
        do 1100 i=1,m
        s=s+(dble(a(i,j)-w(ic+(i-1)+(j-1)*m))**2+dimag(a(i,
     1      j)-w(ic+(i-1)+(j-1)*m))**2)
 1100 continue
 1200 continue
        tspan_z=sqrt(s)/tfro_z(m,n,a,lda)
        return
        end
c
c
c
c
c
        real *8 function tortc_z(m,k,q,ldq)
        implicit real *8 (a-h,o-z)
        complex *16 q(ldq,*),d
c
c       max |Q^H Q - I| over the k columns of q
c
        e=0
        do 1300 j=1,k
        do 1200 i=1,k
        d=0
        do 1100 l=1,m
        d=d+dconjg(q(l,i))*q(l,j)
 1100 continue
        if( i .eq. j ) d=d-1
        e=max(e,abs(d))
 1200 continue
 1300 continue
        tortc_z=e
        return
        end
c
c
c
c
c
        real *8 function tortr_z(k,n,v,ldv)
        implicit real *8 (a-h,o-z)
        complex *16 v(ldv,*),d
c
c       max |V V^H - I| over the k rows of v
c
        e=0
        do 1300 j=1,k
        do 1200 i=1,k
        d=0
        do 1100 l=1,n
        d=d+v(i,l)*dconjg(v(j,l))
 1100 continue
        if( i .eq. j ) d=d-1
        e=max(e,abs(d))
 1200 continue
 1300 continue
        tortr_z=e
        return
        end
c
c
c
c
c
        real *8 function tqrerr_z(m,n,a,lda,k,q,ldq,r,ldr,ipiv,w)
        implicit real *8 (a-h,o-z)
        complex *16 a(lda,*),q(ldq,*),r(ldr,*),w(*)
        dimension ipiv(*)
c
c       ||A(:,ipiv) - Q R|| / ||A||
c
        call rla_zgemm(0,m,n,k,q,ldq,r,ldr,w,m)
        s=0
        do 1200 j=1,n
        do 1100 i=1,m
        s=s+(dble(a(i,ipiv(j))-w(i+(j-1)*m))**2+dimag(a(i,
     1      ipiv(j))-w(i+(j-1)*m))**2)
 1100 continue
 1200 continue
        tqrerr_z=sqrt(s)/tfro_z(m,n,a,lda)
        return
        end
c
c
c
c
c
        real *8 function tsverr_z(m,n,a,lda,k,u,ldu,s,vt,ldvt,w)
        implicit real *8 (a-h,o-z)
        complex *16 a(lda,*),u(ldu,*),vt(ldvt,*),w(*)
        dimension s(*)
c
c       ||A - U diag(s) Vt|| / ||A||
c
        ic=1+m*k
        do 1200 j=1,k
        do 1100 i=1,m
        w(i+(j-1)*m)=u(i,j)*s(j)
 1100 continue
 1200 continue
        call rla_zgemm(0,m,n,k,w,m,vt,ldvt,w(ic),m)
        e=0
        do 1400 j=1,n
        do 1300 i=1,m
        e=e+(dble(a(i,j)-w(ic+(i-1)+(j-1)*m))**2+dimag(a(i,
     1      j)-w(ic+(i-1)+(j-1)*m))**2)
 1300 continue
 1400 continue
        tsverr_z=sqrt(e)/tfro_z(m,n,a,lda)
        return
        end
c
c
c
c
c
        real *8 function tiderr_z(m,n,a,lda,k,ipiv,t,ldt,w)
        implicit real *8 (a-h,o-z)
        complex *16 a(lda,*),t(ldt,*),w(*)
        dimension ipiv(*)
c
c       ||A(:,ipiv(k+1:n)) - A(:,ipiv(1:k)) T|| / ||A|| (absolute for
c       A = 0)
c
        tiderr_z=0
        nk=n-k
        if( nk .le. 0 ) return
        ic=1+m*k
        do 1200 j=1,k
        do 1100 i=1,m
        w(i+(j-1)*m)=a(i,ipiv(j))
 1100 continue
 1200 continue
        call rla_zgemm(0,m,nk,k,w,m,t,ldt,w(ic),m)
        e=0
        do 1400 j=1,nk
        do 1300 i=1,m
        e=e+(dble(a(i,ipiv(k+j))-w(ic+(i-1)+(j-1)*m))**2+dimag(a(i,
     1      ipiv(k+j))-w(ic+(i-1)+(j-1)*m))**2)
 1300 continue
 1400 continue
        tiderr_z=sqrt(e)/max(tfro_z(m,n,a,lda),1.0d-300)
        return
        end
c
c
c
c
c
        real *8 function tlower_z(k,n,r,ldr)
        implicit real *8 (a-h,o-z)
        complex *16 r(ldr,*)
c
c       max |r(i,j)| below the diagonal
c
        e=0
        do 1200 j=1,n
        do 1100 i=j+1,k
        e=max(e,abs(r(i,j)))
 1100 continue
 1200 continue
        tlower_z=e
        return
        end

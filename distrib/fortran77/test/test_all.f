        call rla_zsvd_sketch(n,m,aw,n,1.0d-6,42,0,12,ig1,kc,k,u,m,s,
     1      vt,kc,w,lwmax,ier)
        call checkle('cplx svd wide tol: reconstruction',
     1      tsverr_z(n,m,aw,n,k,u,m,s,vt,kc,wt),1.0d-5)
        call checkle('cplx svd wide tol: V orthonormal',
     1      tortr_z(k,m,vt,kc),1.0d-13)
        call rla_zsvd_sketch(n,m,aw,n,20.0d0,42,0,12,ig1,kc,k,u,m,s,
     1      vt,kc,w,lwmax,ier)
        call checkle('cplx svd wide rank: error / optimal',
     1      tsverr_z(n,m,aw,n,k,u,m,s,vt,kc,wt)/tail,4.0d0)
        call rla_zsvd_sketch(100,80,gm,100,1.0d-6,42,0,12,ig1,kc,k,u,
     1      m,s,vt,kc,w,lwmax,ier)
        call check('cplx svd fallback: k = 80',
     1      ier .eq. 0 .and. k .eq. 80)
        call checkle('cplx svd fallback: full SVD',
     1      tsverr_z(100,80,gm,100,k,u,m,s,vt,kc,wt),1.0d-13)

        real *8 function tiderr_d(m,n,a,lda,k,ipiv,t,ldt,w)
        implicit real *8 (a-h,o-z)
        real *8 a(lda,*),t(ldt,*),w(*)
        dimension ipiv(*)
c
c       ||A(:,ipiv(k+1:n)) - A(:,ipiv(1:k)) T|| / ||A|| (absolute for
c       A = 0)
c
        tiderr_d=0
        nk=n-k
        if( nk .le. 0 ) return
        ic=1+m*k
        do 1200 j=1,k
        do 1100 i=1,m
        w(i+(j-1)*m)=a(i,ipiv(j))
 1100 continue
 1200 continue
        call rla_dgemm(0,m,nk,k,w,m,t,ldt,w(ic),m)
        e=0
        do 1400 j=1,nk
        do 1300 i=1,m
        e=e+(a(i,ipiv(k+j))-w(ic+(i-1)+(j-1)*m))**2
 1300 continue
 1400 continue
        tiderr_d=sqrt(e)/max(tfro_d(m,n,a,lda),1.0d-300)
        return
        end

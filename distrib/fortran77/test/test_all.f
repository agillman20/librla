        call rla_dgemm(0,m,n,k,w,m,vt,ldvt,w(ic),m)
        e=0
        do 1400 j=1,n
        do 1300 i=1,m
        e=e+(a(i,j)-w(ic+(i-1)+(j-1)*m))**2
 1300 continue
 1400 continue

        external tmv_z
        save
c
        write(*,'(a)') '--- complex ---'
        rdum(1)=0
        zdum(1)=0
        eps=rla_eps()
        do 1100 j=1,n
        sv(j)=10.0d0**(-(j-1)/4.0d0)
 1100 continue
        ig(1)=11
        ig(2)=22
        ig(3)=33
        ig(4)=45
        call tsvals_z(ig,m,n,sv,a,m,wt)
        do 1300 j=1,n
        do 1200 i=1,m
        aw(j,i)=dconjg(a(i,j))
 1200 continue
 1300 continue
        call rla_zrandn(ig,100*80,gm)
c
c       ---------------- workspace query ----------------
c
        call rla_zid_sketch(m,n,a,m,1.0d-6,42,0,12,3,ig,kc,k,ipiv,t,
     1      kc,w,-1,ier)

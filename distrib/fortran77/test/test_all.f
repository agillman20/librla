     1      12,ig1,
     1      kc,k,u,m,s,vt,kc,w,lwmax,ier)
        call checkle('real low-rank operator svd rank 8: error',
     1      tsverr_d(300,200,b,300,k,u,m,s,vt,kc,wt),1.0d-12)
        call check('real low-rank operator svd: no materialization',
     1      ipar(3) .lt. 200)
        call rla_did_sketchf(300,200,tmv_d,ipar,pdat,zdum,8.0d0,42,0,12,
     1      1,
     1      ig1,kc,k,ipiv,t,kc,w,lwmax,ier)
        call checkle('real low-rank operator id_sketch rank 8: error',
     1      tiderr_d(300,200,b,300,k,ipiv,t,kc,wt),1.0d-12)
        call rla_dqr_sketchf(300,200,tmv_d,ipar,pdat,zdum,8.0d0,42,0,12,
     1      ig1,
     1      kc,k,q,m,r,kc,ipiv,w,lwmax,ier)
        call checkle('real low-rank operator qr_sketch rank 8: error',
     1      tqrerr_d(300,200,b,300,k,q,m,r,kc,ipiv,wt),1.0d-12)
c
c       ---------------- dense utilities ----------------
c
        call tcopy_d(m,n,a,m,q)
        call rla_dqrf(m,n,q,m,wt,wt(n+1))
        do 5100 j=1,n
        ipiv(j)=j
        do 5050 i=1,n
        r(i,j)=0
        if( i .le. j ) r(i,j)=q(i,j)
 5050 continue
 5100 continue
        call rla_dorgqr(m,n,q,m,wt,wt(n+1))
        call checkle('real qrf (unpivoted): ||A - QR||/||A||',
     1      tqrerr_d(m,n,a,m,n,q,m,r,kc,ipiv,wt),1.0d-14)
        call checkle('real qrf: orthonormality',tortc_d(m,n,q,m),
     1      1.0d-13)
        call tcopy_d(m,n,a,m,pdat)
        call rla_dsvd(m,n,a,m,0.0d0,0.0d0,kc,0,k,s,u,m,vt,kc,w,-1,ier)
        lneed=nint(w(1))
        call rla_dsvd(m,n,a,m,0.0d0,0.0d0,kc,0,k,s,u,m,vt,kc,w,
     1      lneed-1,ier)
        call check('real svd: query, lw one short gives ier 5',
     1      ier .eq. 5)
        call rla_dsvd(m,n,a,m,0.0d0,0.0d0,kc,0,k,s,u,m,vt,kc,w,
     1      lneed,ier)
        same=ier .eq. 0 .and. k .eq. n
        do 5200 j=1,n
        do 5150 i=1,m
        if( abs(a(i,j)-pdat(i+(j-1)*m)) .gt. 0 ) same=.false.
 5150 continue
 5200 continue
        call check('real svd: ier 0, a not modified',same)
        call checkle('real svd tall: reconstruction',
     1      tsverr_d(m,n,a,m,n,u,m,s,vt,kc,wt),1.0d-13)
        call checkle('real svd tall: U orthonormal',tortc_d(m,n,u,m),
     1      1.0d-13)
        call checkle('real svd tall: V orthonormal',tortr_d(n,n,vt,kc),
     1      1.0d-13)
        e(1)=0
        do 5300 i=1,n
        e(1)=max(e(1),abs(s(i)-sv(i))/sv(1))
 5300 continue
        call checkle('real svd tall: singular values',e(1),1.0d-13)
        call rla_dsvd(n,m,aw,n,0.0d0,0.0d0,kc,0,k,s,u,m,vt,kc,w,lwmax,
     1      ier)
        call checkle('real svd wide: reconstruction',
     1      tsverr_d(n,m,aw,n,n,u,m,s,vt,kc,wt),1.0d-13)
        call checkle('real svd wide: U, V orthonormal',max(
     1      tortc_d(n,n,u,m),tortr_d(n,m,vt,kc)),1.0d-13)
        call rla_dsvd(60,40,alr,60,0.0d0,0.0d0,kc,0,k,s,u,m,vt,kc,w,
     1      lwmax,ier)
        call checkle('real svd rank 5 of 40: reconstruction',
     1      tsverr_d(60,40,alr,60,40,u,m,s,vt,kc,wt),1.0d-13)
        call checkle('real svd rank 5 of 40: U, V orthonormal',max(
     1      tortc_d(60,40,u,m),tortr_d(40,40,vt,kc)),1.0d-13)
c
c       ---------------- early exits (qrcp, svd) ----------------
c
c       no limits: the full pivoted QR, bitwise
        call tcopy_d(m,n,a,m,q)
        call rla_dqrcp(m,n,n,-1.0d0,-1.0d0,q,m,k,rk,rrel,ipiv,wt,
     1      wt(n+1),
     1      ier)
        call tcopy_d(m,n,a,m,q2)
        call rla_dqrp(m,n,q2,m,wt(5*n+1),wt(6*n+1),wt(7*n+1),wt(8*n+1),
     1      wt(9*n+1))
        same=ier .eq. 0 .and. k .eq. n .and. abs(rk) .le. 0
        do 5500 j=1,n
        if( ipiv(j) .ne. nint(wt(5*n+j)) ) same=.false.
        do 5450 i=1,m
        if( abs(q(i,j)-q2(i,j)) .gt. 0 ) same=.false.
 5450 continue
 5500 continue
        call check('real qrcp without limits = full QR (bitwise)',
     1      same)
c       kmax = 25: the same first 25 steps, bitwise
        call tcopy_d(m,n,a,m,q)
        call rla_dqrcp(m,n,25,-1.0d0,-1.0d0,q,m,k,rk,rrel,ipiv,wt,
     1      wt(n+1),ier)
        same=ier .eq. 0 .and. k .eq. 25
        do 5600 j=1,25
        if( ipiv(j) .ne. nint(wt(5*n+j)) ) same=.false.
        do 5550 i=1,25
        if( i .le. j .and. abs(q(i,j)-q2(i,j)) .gt. 0 ) same=.false.
 5550 continue
 5600 continue
        call check('real qrcp kmax 25: same pivots, R (bitwise)',
     1      same)
c       abstol 1e-6, reltol 1e-8: residual as small as promised
        do 5800 it=1,2
        call tcopy_d(m,n,a,m,q)
        if( it .eq. 1 ) call rla_dqrcp(m,n,n,1.0d-6,-1.0d0,q,m,k,rk,
     1      rrel,ipiv,wt,wt(n+1),ier)
        if( it .eq. 2 ) call rla_dqrcp(m,n,n,-1.0d0,1.0d-8,q,m,k,rk,
     1      rrel,ipiv,wt,wt(n+1),ier)
        do 5700 j=1,n
        do 5650 i=1,k
        r(i,j)=0
        if( i .le. j ) r(i,j)=q(i,j)
 5650 continue
 5700 continue
        call rla_dorgqr(m,k,q,m,wt,wt(n+1))
        err=tqrerr_d(m,n,a,m,k,q,m,r,kc,ipiv,wt)*tfro_d(m,n,a,m)
        if( it .eq. 1 ) call check('real qrcp abstol 1e-6: stops, '//
     1      'residual norms <= abstol',ier .eq. 0 .and. k .lt. n .and.
     2      rk .le. 1.0d-6 .and. err .le. sqrt(dble(n-k))*rk*1.01d0)
        if( it .eq. 2 ) call check('real qrcp reltol 1e-8: stops, '//
     1      'relmaxk <= reltol',ier .eq. 0 .and. k .lt. n .and.
     2      rrel .le. 1.0d-8 .and. err .le. sqrt(dble(n-k))*rk*1.01d0)
 5800 continue
c       svd, iexit 1: the exact rank of a rank-5 matrix
        call rla_dsvd(60,40,alr,60,0.0d0,0.0d0,kc,1,k,s,u,m,vt,kc,w,
     1      lwmax,ier)
        call check('real svd iexit 1 on rank 5 of 40: k = 5',ier .eq. 0
     1      .and. k .eq. 5)
        call checkle('real svd iexit 1 on rank 5 of 40: reconstruction',
     1      tsverr_d(60,40,alr,60,k,u,m,s,vt,kc,wt),1.0d-13)
c       svd, iexit 2, rtol 1.3e-8 (between sv(32) and sv(33)): keeps
c       j <= 32, values to 1% of the threshold
        call rla_dsvd(m,n,a,m,1.3d-8,0.0d0,kc,2,k,s,u,m,vt,kc,w,
     1      lwmax,ier)
        e(1)=0
        do 5900 i=1,k
        e(1)=max(e(1),abs(s(i)-sv(i)))
 5900 continue
        call check('real svd iexit 2, rtol 1.3e-8: k = 32',ier .eq. 0
     1      .and. k .eq. 32)
        call checkle('real svd iexit 2, rtol 1.3e-8: |s - sv|',e(1),
     1      1.3d-10)
        call checkle('real svd iexit 2, rtol 1.3e-8: error / optimal',
     1      tsverr_d(m,n,a,m,k,u,m,s,vt,kc,wt)/
     2      sqrt(sum2(n-32,sv(33))/sum2(n,sv)),1.01d0)
        call checkle('real svd iexit 2: U, V orthonormal',max(
     1      tortc_d(m,k,u,m),tortr_d(k,n,vt,kc)),1.0d-13)
c       atol 1.3e-6 keeps j <= 24; kmax caps at 10
        call rla_dsvd(m,n,a,m,0.0d0,1.3d-6,kc,2,k,s,u,m,vt,kc,w,
     1      lwmax,ier)
        call check('real svd iexit 2, atol 1.3e-6: k = 24',ier .eq. 0
     1      .and. k .eq. 24)
        call rla_dsvd(m,n,a,m,0.0d0,0.0d0,10,1,k,s,u,m,vt,10,w,lwmax,
     1      ier)
        call check('real svd kmax 10: k = 10',
     1      ier .eq. 0 .and. k .eq. 10)
c       iexit 3 (LAPACK rule), rtol 1.3e-8: count within 2 of 32,
c       error close to optimal
        call rla_dsvd(m,n,a,m,1.3d-8,0.0d0,kc,3,k,s,u,m,vt,kc,w,
     1      lwmax,ier)
        call check('real svd iexit 3, rtol 1.3e-8: 30 <= k <= 32',
     1      ier .eq. 0 .and. k .ge. 30 .and. k .le. 32)
        call checkle('real svd iexit 3: error / optimal',
     1      tsverr_d(m,n,a,m,k,u,m,s,vt,kc,wt)/
     2      sqrt(sum2(n-k,sv(k+1))/sum2(n,sv)),2.0d0)
        call checkle('real svd iexit 3: U, V orthonormal',max(
     1      tortc_d(m,k,u,m),tortr_d(k,n,vt,kc)),1.0d-13)
c
c       ---------------- workspace layouts ----------------
c
        call tlay_d(m,n,a,aw,gm,pdat,w)
c
c       ---------------- power iteration, seeds ----------------
c
        do 4500 j=1,200
        sv(j)=1.0d0/j
 4500 continue
        call tsvals_d(ig,300,200,sv,a,m,wt)
        do 4600 j=1,3
        call seed(ig1,1,2,3,5)
        call rla_dsvd_sketch(300,200,a,m,10.0d0,42,j-1,12,ig1,kc,k,u,
     1      m,s,vt,kc,w,lwmax,ier)
        e(j)=tsverr_d(300,200,a,m,k,u,m,s,vt,kc,wt)
 4600 continue
        call check('real power_iter 0 -> 1 -> 2 does not hurt accuracy',
     1      e(2) .le. 1.01d0*e(1) .and. e(3) .le. 1.01d0*e(2))
        call seed(ig1,7,7,7,7)
        call seed(ig2,7,7,7,7)
        call rla_dsvd_sketch(300,200,a,m,10.0d0,42,0,12,ig1,kc,k,u,m,
     1      s,vt,kc,w,lwmax,ier)
        call rla_dsvd_sketch(300,200,a,m,10.0d0,42,0,12,ig2,kc,k2,u2,
     1      m,s2,vt2,kc,w,lwmax,ier)
        same=k .eq. k2 .and. ig1(1) .eq. ig2(1) .and. ig1(4) .eq. ig2(4)
        do 4700 i=1,k
        if( abs(s(i)-s2(i)) .gt. 0 ) same=.false.
 4700 continue
        call check('real same seed -> identical output',same)
        return
        end

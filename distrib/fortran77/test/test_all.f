c
        do 2400 j=1,20
        do 2300 i=1,30
        zm(i,j)=0
 2300 continue
 2400 continue
        call rla_zid_sketch(30,20,zm,30,1.0d-6,42,0,12,1,ig1,kc,k,
     1      ipiv,t,kc,w,lwmax,ier)
        call check('cplx id_sketch zero matrix: k = 0',ier .eq. 0 .and.
     1      k .eq. 0 .and. isperm(20,ipiv))
        call rla_zid_qrpiv(30,20,zm,30,1.0d-6,1,kc,k,ipiv,t,kc,w,
     1      lwmax,ier)
        call check('cplx id_qrpiv zero matrix: k = 0',ier .eq. 0 .and.
     1      k .eq. 0)

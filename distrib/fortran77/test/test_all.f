        call checkle('cplx id_sketch tol '//mname(im)//': error',
     1      tiderr_z(m,n,a,m,k,ipiv,t,kc,wt),1.0d-5)
        call rla_zid_sketch(m,n,a,m,20.0d0,42,0,12,im,ig1,kc,k,ipiv,
     1      t,kc,w,lwmax,ier)
        call checkle('cplx id_sketch rank '//mname(im)//': error',
     1      tiderr_z(m,n,a,m,k,ipiv,t,kc,wt),1.0d-3)

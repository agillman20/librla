        subroutine tcopy_z(m,n,a,lda,b)
        implicit real *8 (a-h,o-z)
        complex *16 a(lda,*),b(m,*)
c
c       b (m x n, contiguous) = a(1:m,1:n)
c
        do 1200 j=1,n
        do 1100 i=1,m
        b(i,j)=a(i,j)
 1100 continue
 1200 continue
        return
        end

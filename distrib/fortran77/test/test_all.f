        call rla_zsvd_sketch(m,n,a,m-1,20.0d0,42,0,12,ig1,kc,k,u,m,s,
     1      vt,kc,w,lwmax,ier)
        call check('cplx lda < m: ier 2',ier .eq. 2)
        call rla_zsvd_sketch(m,n,a,m,20.0d0,-1,0,12,ig1,kc,k,u,m,s,

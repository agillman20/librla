        subroutine checkle(name,val,tol)
        implicit real *8 (a-h,o-z)
        character *(*) name
        character *40 buf
        character *160 msg
c
        write(buf,'(a,e9.2,a,e8.1,a)') ' (',val,' <= ',tol,')'
        msg=name//buf
        call check(msg(1:len(name)+40),val .le. tol)
        return
        end

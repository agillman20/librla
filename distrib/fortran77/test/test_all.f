        subroutine check(name,ok)
        character *(*) name
        logical ok
        common /tstcnt/ npass,nfail
c
        if( ok ) then
        npass=npass+1
        write(*,'(2a)') 'PASS ',name
        else
        nfail=nfail+1
        write(*,'(2a)') 'FAIL ',name
        endif
        return
        end

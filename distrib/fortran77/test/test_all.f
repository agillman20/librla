        subroutine torth_d(iseed,m,n,q,w)
        implicit real *8 (a-h,o-z)
        real *8 q(m,*),w(*)
        dimension iseed(4)
c
c       q (m x n, m >= n): orthonormal columns from the pivoted QR of
c       a random matrix (library kernels)
c
        call rla_drandn(iseed,m*n,q)
        call rla_dqrp(m,n,q,m,w(1),w(n+1),w(2*n+1),w(3*n+1),w(4*n+1))
        call rla_dorgqr(m,n,q,m,w(n+1),w(4*n+1))
        return
        end

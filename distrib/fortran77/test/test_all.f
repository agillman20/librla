        subroutine tmv_d(itrans,m,n,k,x,y,ipar,rpar,zpar)
        implicit real *8 (a-h,o-z)
        real *8 x(*),y(*),wl(8*600)
        dimension ipar(*),rpar(*)
        complex *16 zpar(*)
        save wl
c
c       matrix-free test operator. ipar(1)=1: the m x n matrix stored
c       in rpar; ipar(1)=2: B C with B (m x r) then C (r x n) in
c       rpar, r = ipar(2). ipar(3) counts columns applied with
c       itrans=0. Products by rla_dgemm, as in the dense path
c
        if( itrans .eq. 0 ) ipar(3)=ipar(3)+k
        if( ipar(1) .eq. 1 ) then
        if( itrans .eq. 0 ) then
        call rla_dgemm(0,m,k,n,rpar,m,x,n,y,m)
        else
        call rla_dgemm(1,n,k,m,rpar,m,x,m,y,n)
        endif
        else
        ir=ipar(2)
        ic=1+m*ir
        if( itrans .eq. 0 ) then
        call rla_dgemm(0,ir,k,n,rpar(ic),ir,x,n,wl,ir)
        call rla_dgemm(0,m,k,ir,rpar,m,wl,ir,y,m)
        else
        call rla_dgemm(1,ir,k,m,rpar,m,x,m,wl,ir)
        call rla_dgemm(1,n,k,ir,rpar(ic),ir,wl,ir,y,n)
        endif
        endif
        if( abs(zpar(1)) .lt. 0 ) ipar(3)=-1
        return
        end

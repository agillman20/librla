     1      ier .eq. 0 .and. lneed .gt. 0 .and. lneed .le. lwmax)
        call rla_zid_sketch(m,n,a,m,1.0d-6,42,0,12,3,ig,kc,k,ipiv,t,
     1      kc,w,lneed-1,ier)
        call check('cplx lw one short: ier 5, w(1) = size needed',
     1      ier .eq. 5 .and. nint(dble(w(1))) .eq. lneed)
c
c       ---------------- orth_sketch ----------------
c
        call seed(ig1,1,2,3,5)
        call rla_zorth_sketch(m,n,a,m,1.0d-6,42,0,12,ig1,kc,k,q,m,d,
     1      flag,w,lwmax,ier)
        call check('cplx orth tol: ier 0, flag 0, accepted at block 42',
     1      ier .eq. 0 .and. flag .eq. 0 .and. k .eq. 42)
        call checkle('cplx orth tol: span error',
     1      tspan_z(m,n,a,m,k,q,m,wt),1.0d-6)
        call checkle('cplx orth tol: orthonormality',
     1      tortc_z(m,k,q,m),1.0d-13)
        same=.true.
        do 1400 i=1,k-1
        if( d(i) .lt. d(i+1) ) same=.false.
 1400 continue
        call check('cplx orth tol: diagr decreasing',same)
        call check('cplx orth: iseed advanced',ig1(4) .ne. 5)
        call rla_zorth_sketch(m,n,a,m,1.0d-10,42,0,12,ig1,kc,k,q,m,
     1      d,flag,w,lwmax,ier)
        call checkle('cplx orth tol 1e-10: span error',
     1      tspan_z(m,n,a,m,k,q,m,wt),1.0d-9)
        call rla_zorth_sketch(m,n,a,m,20.0d0,42,0,12,ig1,kc,k,q,m,d,
     1      flag,w,lwmax,ier)
        call check('cplx orth rank 20: k = 32',ier .eq. 0 .and.
     1      flag .eq. 0 .and. k .eq. 32)
        call rla_zorth_sketch(20,n,a,m,15.7d0,42,0,12,ig1,kc,k,q,m,
     1      d,flag,w,lwmax,ier)
        call check('cplx orth rank 15 on 20 x 300 (lda > m): k = 20',
     1      ier .eq. 0 .and. k .eq. 20)
        call checkle('cplx orth rank 15 on 20 x 300: orthonormality',
     1      tortc_z(20,k,q,m),1.0d-13)
        call rla_zorth_sketch(m,n,a,m,1.0d-6,42,0,0,ig1,kc,k,q,m,d,
     1      flag,w,lwmax,ier)
        call checkle('cplx orth tol, extra 0: span error',
     1      tspan_z(m,n,a,m,k,q,m,wt),1.0d-5)
        call rla_zorth_sketch(m,n,a,m,eps/10,42,0,12,ig1,kc,k,q,m,d,
     1      flag,w,lwmax,ier)
        call check('cplx orth rtol < eps: flag 1, k = 0',ier .eq. 0
     1      .and. flag .eq. 1 .and. k .eq. 0)
        call rla_zorth_sketch(100,80,gm,100,1.0d-6,42,0,12,ig1,kc,k,
     1      q,m,d,flag,w,lwmax,ier)
        call check('cplx orth full rank: flag 1, k = 0',ier .eq. 0
     1      .and. flag .eq. 1 .and. k .eq. 0)
        call seed(ig2,ig1(1),ig1(2),ig1(3),ig1(4))
        call rla_zorth_sketch(m,n,a,m,20.0d0,42,0,12,ig1,10,k,q,m,d,
     1      flag,w,lwmax,ier)
        call check('cplx orth kcap 10 < 32: ier 4, k = 32, iseed kept',
     1      ier .eq. 4 .and. k .eq. 32 .and. ig1(4) .eq. ig2(4))
c
c       ---------------- qr_sketch ----------------
c
        call rla_zqr_sketch(m,n,a,m,1.0d-6,42,0,12,ig1,kc,k,q,m,r,kc,
     1      ipiv,w,lwmax,ier)
        call check('cplx qr tol: ier 0, 20 < k < 42, permutation',
     1      ier .eq. 0 .and. k .gt. 20 .and. k .lt. 42 .and.
     2      isperm(n,ipiv))
        call checkle('cplx qr tol: ||A(:,p) - QR||/||A||',
     1      tqrerr_z(m,n,a,m,k,q,m,r,kc,ipiv,wt),1.0d-5)
        call check('cplx qr tol: R upper triangular',
     1      tlower_z(k,n,r,kc) .le. 0)
        call checkle('cplx qr tol: orthonormality',
     1      tortc_z(m,k,q,m),1.0d-13)
        call rla_zqr_sketch(m,n,a,m,25.0d0,42,0,12,ig1,kc,k,q,m,r,kc,
     1      ipiv,w,lwmax,ier)
        call check('cplx qr rank: k = 25',ier .eq. 0 .and. k .eq. 25)
        err=tqrerr_z(m,n,a,m,k,q,m,r,kc,ipiv,wt)
        call checkle('cplx qr rank: error / optimal tail',
     1      err/sqrt(sum2(n-25,sv(26))/sum2(n,sv)),4.0d0)
        call rla_zqr_sketch(n,m,aw,n,1.0d-6,42,0,12,ig1,kc,k,q,m,r,kc,
     1      ipiv,w,lwmax,ier)
        call checkle('cplx qr wide tol: error',
     1      tqrerr_z(n,m,aw,n,k,q,m,r,kc,ipiv,wt),1.0d-5)
        call check('cplx qr wide tol: R upper, permutation',
     1      tlower_z(k,m,r,kc) .le. 0 .and. isperm(m,ipiv))
        call rla_zqr_sketch(n,m,aw,n,25.0d0,42,0,12,ig1,kc,k,q,m,r,kc,
     1      ipiv,w,lwmax,ier)
        call checkle('cplx qr wide rank: error',
     1      tqrerr_z(n,m,aw,n,k,q,m,r,kc,ipiv,wt),1.0d-5)
c
c       fallback = the deterministic pivoted QR (library kernel)
c
        call rla_zqr_sketch(100,80,gm,100,1.0d-6,42,0,12,ig1,kc,k,q,m,
     1      r,kc,ipiv,w,lwmax,ier)
        call tcopy_z(100,80,gm,100,gp)
        call rla_zqrfac(100,80,gp,100,wt(1),wt(81),wt(161),wt(241),
     1      wt(321),r2,kc,.true.)
        same=k .eq. 80
        do 1700 j=1,80
        if( ipiv(j) .ne. nint(dble(wt(j))) ) same=.false.
        do 1600 i=1,100
        if( abs(q(i,j)-gp(i+(j-1)*100)) .gt. 0 ) same=.false.
        if( i .le. 80 ) then
        if( abs(r(i,j)-r2(i,j)) .gt. 0 ) same=.false.
        endif
 1600 continue
 1700 continue
        call check('cplx qr fallback = pivoted QR kernel (bitwise)',
     1      same)
c
c       ---------------- svd_sketch ----------------
c
        tail=sqrt(sum2(n-20,sv(21))/sum2(n,sv))
        call rla_zsvd_sketch(m,n,a,m,1.0d-6,42,0,12,ig1,kc,k,u,m,s,vt,

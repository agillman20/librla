        call checkle('cplx svd tol: reconstruction',
     1      tsverr_z(m,n,a,m,k,u,m,s,vt,kc,wt),1.0d-5)
        call checkle('cplx svd tol: U orthonormal',
     1      tortc_z(m,k,u,m),1.0d-13)
        call checkle('cplx svd tol: V orthonormal',
     1      tortr_z(k,n,vt,kc),1.0d-13)
        same=.true.
        do 1800 i=1,k-1
        if( s(i) .lt. s(i+1) ) same=.false.
 1800 continue
        call check('cplx svd tol: s decreasing',same)
        call rla_zsvd_sketch(m,n,a,m,20.0d0,42,0,12,ig1,kc,k,u,m,s,vt,
     1      kc,w,lwmax,ier)
        call check('cplx svd rank: k = 20',ier .eq. 0 .and. k .eq. 20)
        call checkle('cplx svd rank: error / optimal',
     1      tsverr_z(m,n,a,m,k,u,m,s,vt,kc,wt)/tail,4.0d0)

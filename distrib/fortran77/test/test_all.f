c
c       test_all: librla77 test suite
c
c       Prints one PASS/FAIL line per check and the CROSSPORT lines
c       shared with the other experimental ports; stops with status 1
c       on any failure. Also runs promoted to quad precision
c       (make test-quad).
c
c       Author: Adrianna Gillman, Zydrunas Gimbutas
c       SPDX-License-Identifier: MIT
c       Assisted by: Claude Code (Anthropic)
c
c       Generated by tools/generate.py from tools/test_harness.f and
c       tools/test_kind.f.in: edit those, not this file.
c
        program test_all
        implicit real *8 (a-h,o-z)
        common /tstcnt/ npass,nfail
c
        character *12 itoa,c1,c2
        integer lentrm
c
        npass=0
        nfail=0
        call test_rng()
        call test_d()
        call test_z()
        call crossport()
        c1=itoa(npass)
        c2=itoa(nfail)
        write(*,'(5a)') 'SUMMARY ',c1(1:lentrm(c1)),' passed, ',
     1      c2(1:lentrm(c2)),' failed'
        if( nfail .gt. 0 ) stop 1
        end
c
c

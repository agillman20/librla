c
c
        subroutine tlay_d(m,n,a,aw,gm,pdat,w)
        implicit real *8 (a-h,o-z)
        parameter (kc=300,nsent=2000)
        real *8 a(m,*),aw(n,*),gm(100,*),pdat(*),w(*),q(400,kc),
     1      r(kc,400),u(400,kc),vt(kc,400),t(kc,400),sent
        dimension s(kc),ipiv(400),ig(4),ipar(3),rdum(1),rtols(2)
        complex *16 zdum(1)
        integer flag
        external tmv_d
        save
        data rtols/1.0d-6,20.0d0/
c
c       every routine, dense and matrix-free, tolerance and rank mode,
c       tall (200 x 150 block of a), wide (its adjoint) and full-rank
c       (fallback) input: run with lw = the queried size and check
c       that w(lw+1:lw+nsent) is untouched
c
        rdum(1)=0
        zdum(1)=0
        sent=-12345
        nbad=0
        ncase=0
        do 2000 imat=1,3
        if( imat .eq. 1 ) then
        mm=200
        nn=150
        call tcopy_d(mm,nn,a,m,pdat)
        else if( imat .eq. 2 ) then
        mm=150
        nn=200
        call tcopy_d(mm,nn,aw,n,pdat)
        else
        mm=100
        nn=80
        call tcopy_d(mm,nn,gm,100,pdat)
        endif
        do 1900 itol=1,2
        rtol=rtols(itol)
        do 1800 idense=0,1
        do 1700 ir=1,9
        ipar(1)=1
        ipar(2)=0
        ipar(3)=0
        do 1600 iquery=1,2
        lw=-1
        if( iquery .eq. 2 ) then
        lw=nint(w(1))
        do 1100 i=lw+1,lw+nsent
        w(i)=sent
 1100 continue
        endif
        call seed(ig,1,2,3,5)
        im=ir-3
        if( ir .gt. 6 ) im=ir-6
        if( ir .eq. 1 .and. idense .eq. 1 ) call rla_dorth_sketch(mm,
     1      nn,pdat,mm,rtol,42,0,12,ig,kc,k,q,400,s,flag,w,lw,ier)
        if( ir .eq. 1 .and. idense .eq. 0 ) call rla_dorth_sketchf(mm,
     1      nn,tmv_d,ipar,pdat,zdum,rtol,42,0,12,ig,kc,k,q,400,s,flag,w,
     1      lw,
     2      ier)
        if( ir .eq. 2 .and. idense .eq. 1 ) call rla_dqr_sketch(mm,nn,
     1      pdat,mm,rtol,42,0,12,ig,kc,k,q,400,r,kc,ipiv,w,lw,ier)
        if( ir .eq. 2 .and. idense .eq. 0 ) call rla_dqr_sketchf(mm,
     1      nn,tmv_d,ipar,pdat,zdum,rtol,42,0,12,ig,kc,k,q,400,r,kc,
     1      ipiv,w,
     2      lw,ier)
        if( ir .eq. 3 .and. idense .eq. 1 ) call rla_dsvd_sketch(mm,
     1      nn,pdat,mm,rtol,42,1,12,ig,kc,k,u,400,s,vt,kc,w,lw,ier)
        if( ir .eq. 3 .and. idense .eq. 0 ) call rla_dsvd_sketchf(mm,
     1      nn,tmv_d,ipar,pdat,zdum,rtol,42,1,12,ig,kc,k,u,400,s,vt,kc,
     1      w,lw,
     2      ier)
        if( ir .ge. 4 .and. ir .le. 6 .and. idense .eq. 1 )
     1      call rla_did_sketch(mm,nn,pdat,mm,rtol,42,0,12,im,ig,kc,k,
     2      ipiv,t,kc,w,lw,ier)
        if( ir .ge. 4 .and. ir .le. 6 .and. idense .eq. 0 )
     1      call rla_did_sketchf(mm,nn,tmv_d,ipar,pdat,zdum,rtol,42,0,
     1      12,im,
     2      ig,kc,k,ipiv,t,kc,w,lw,ier)
        if( ir .ge. 7 .and. idense .eq. 1 ) call rla_did_qrpiv(mm,nn,
     1      pdat,mm,rtol,im,kc,k,ipiv,t,kc,w,lw,ier)
        if( ir .ge. 7 .and. idense .eq. 0 ) call rla_did_qrpivf(mm,
     1      nn,tmv_d,ipar,pdat,zdum,rtol,im,kc,k,ipiv,t,kc,w,lw,ier)
        if( ier .ne. 0 ) nbad=nbad+1
 1600 continue
        ncase=ncase+1
        do 1650 i=lw+1,lw+nsent
        if( abs(w(i)-sent) .gt. 0 ) then
        nbad=nbad+1
        write(*,'(a,4i4)') 'overrun: matrix, mode, dense, routine',
     1      imat,itol,idense,ir
        goto 1700
        endif
 1650 continue
 1700 continue
 1800 continue
 1900 continue
 2000 continue
        call check('real workspace: lw = query, no overrun',
     1      nbad .eq. 0 .and. ncase .eq. 108)
        return
        end

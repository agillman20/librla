        subroutine tmv_z(itrans,m,n,k,x,y,ipar,rpar,zpar)
        implicit real *8 (a-h,o-z)
        complex *16 x(*),y(*),wl(8*600)
        dimension ipar(*),rpar(*)
        complex *16 zpar(*)
        save wl
c
c       matrix-free test operator. ipar(1)=1: the m x n matrix stored
c       in zpar; ipar(1)=2: B C with B (m x r) then C (r x n) in
c       zpar, r = ipar(2). ipar(3) counts columns applied with
c       itrans=0. Products by rla_zgemm, as in the dense path
c
        if( itrans .eq. 0 ) ipar(3)=ipar(3)+k
        if( ipar(1) .eq. 1 ) then
        if( itrans .eq. 0 ) then
        call rla_zgemm(0,m,k,n,zpar,m,x,n,y,m)
        else
        call rla_zgemm(1,n,k,m,zpar,m,x,m,y,n)
        endif
        else
        ir=ipar(2)
        ic=1+m*ir
        if( itrans .eq. 0 ) then
        call rla_zgemm(0,ir,k,n,zpar(ic),ir,x,n,wl,ir)
        call rla_zgemm(0,m,k,ir,zpar,m,wl,ir,y,m)
        else
        call rla_zgemm(1,ir,k,m,zpar,m,x,m,wl,ir)
        call rla_zgemm(1,n,k,ir,zpar(ic),ir,wl,ir,y,n)
        endif
        endif
        if( rpar(1) .lt. 0 .and. rpar(1) .gt. 0 ) ipar(3)=-1
        return
        end

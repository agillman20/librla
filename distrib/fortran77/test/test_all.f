        subroutine test_z()
        implicit real *8 (a-h,o-z)
        parameter (m=400,n=300,kc=300,lwmax=2000000)
        complex *16 a(m,n),aw(n,m),gm(100,80),q(m,kc),r(kc,m),u(m,kc),

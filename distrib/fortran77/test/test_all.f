        call rla_zgemm(0,60,40,5,bb,60,cc,5,alr,60)
        do 2200 im=1,3
        call rla_zid_sketch(60,40,alr,60,10.0d0,42,0,12,im,ig1,kc,k,
     1      ipiv,t,kc,w,lwmax,ier)
        call check('cplx id_sketch rank-deficient '//mname(im)//
     1      ': k = 10',ier .eq. 0 .and. k .eq. 10)
        call checkle('cplx id_sketch rank-deficient '//mname(im)//
     1      ': error',tiderr_z(60,40,alr,60,k,ipiv,t,kc,wt),1.0d-10)
        call rla_zid_qrpiv(60,40,alr,60,10.0d0,im,kc,k,ipiv,t,kc,w,
     1      lwmax,ier)
        call checkle('cplx id_qrpiv rank-deficient '//mname(im)//
     1      ': error',tiderr_z(60,40,alr,60,k,ipiv,t,kc,wt),1.0d-10)
 2200 continue

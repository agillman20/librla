     2      t2(kc,m),w(lwmax),wt(lwmax),pdat(m*n),gp(100*80)
        complex *16 alr(60,40),bb(300,8),cc(8,200),b(300,200),zm(30,20)
        dimension sv(n),s(kc),s2(kc),d(kc),e(3),rdum(1)

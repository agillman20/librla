        subroutine test_d()
        implicit real *8 (a-h,o-z)
        parameter (m=400,n=300,kc=300,lwmax=2000000)
        real *8 a(m,n),aw(n,m),gm(100,80),q(m,kc),r(kc,m),u(m,kc),
     1      vt(kc,m),t(kc,m),q2(m,kc),r2(kc,m),u2(m,kc),vt2(kc,m),
     2      t2(kc,m),w(lwmax),wt(lwmax),pdat(m*n),gp(100*80)
        real *8 alr(60,40),bb(300,8),cc(8,200),b(300,200),zm(30,20)
        dimension sv(n),s(kc),s2(kc),d(kc),e(3),rdum(1)
        dimension ipiv(m),ipiv2(m),ig(4),ig1(4),ig2(4),ipar(3)
        complex *16 zdum(1)
        character *5 mname
        logical isperm,same
        integer flag,flag2
        external tmv_d
        save
c
        write(*,'(a)') '--- real ---'
        rdum(1)=0
        zdum(1)=0
        eps=rla_eps()
        do 1100 j=1,n
        sv(j)=10.0d0**(-(j-1)/4.0d0)
 1100 continue
        ig(1)=11
        ig(2)=22
        ig(3)=33
        ig(4)=45
        call tsvals_d(ig,m,n,sv,a,m,wt)
        do 1300 j=1,n
        do 1200 i=1,m
        aw(j,i)=a(i,j)
 1200 continue
 1300 continue
        call rla_drandn(ig,100*80,gm)
c
c       ---------------- workspace query ----------------
c
        call rla_did_sketch(m,n,a,m,1.0d-6,42,0,12,3,ig,kc,k,ipiv,t,
     1      kc,w,-1,ier)
        lneed=nint(w(1))
        call check('real workspace query: ier 0, fits the test array',
     1      ier .eq. 0 .and. lneed .gt. 0 .and. lneed .le. lwmax)
        call rla_did_sketch(m,n,a,m,1.0d-6,42,0,12,3,ig,kc,k,ipiv,t,
     1      kc,w,lneed-1,ier)
        call check('real lw one short: ier 5, w(1) = size needed',
     1      ier .eq. 5 .and. nint(w(1)) .eq. lneed)
c
c       ---------------- orth_sketch ----------------
c
        call seed(ig1,1,2,3,5)
        call rla_dorth_sketch(m,n,a,m,1.0d-6,42,0,12,ig1,kc,k,q,m,d,
     1      flag,w,lwmax,ier)
        call check('real orth tol: ier 0, flag 0, accepted at block 42',
     1      ier .eq. 0 .and. flag .eq. 0 .and. k .eq. 42)
        call checkle('real orth tol: span error',
     1      tspan_d(m,n,a,m,k,q,m,wt),1.0d-6)
        call checkle('real orth tol: orthonormality',
     1      tortc_d(m,k,q,m),1.0d-13)
        same=.true.
        do 1400 i=1,k-1
        if( d(i) .lt. d(i+1) ) same=.false.
 1400 continue

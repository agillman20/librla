        subroutine tsvals_z(iseed,m,n,sv,a,lda,w)
        implicit real *8 (a-h,o-z)
        complex *16 a(lda,*),w(*),d
        dimension iseed(4),sv(*)
c
c       a (m x n, m >= n) = U diag(sv) V^H, U and V random orthonormal
c
        iu=1
        iv=iu+m*n
        iw=iv+n*n
        call torth_z(iseed,m,n,w(iu),w(iw))
        call torth_z(iseed,n,n,w(iv),w(iw))
        do 1300 j=1,n
        do 1200 i=1,m
        d=0
        do 1100 l=1,n
        d=d+w(iu+(i-1)+(l-1)*m)*sv(l)*dconjg(w(iv+(j-1)+(l-1)*n))
 1100 continue
        a(i,j)=d
 1200 continue
 1300 continue
        return
        end

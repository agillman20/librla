        real *8 function tspan_d(m,n,a,lda,k,q,ldq,w)
        implicit real *8 (a-h,o-z)
        real *8 a(lda,*),q(ldq,*),w(*)
c
c       ||A - Q Q^T A|| / ||A||
c
        ib=1
        ic=ib+k*n
        call rla_dgemm(1,k,n,m,q,ldq,a,lda,w(ib),max(1,k))
        call rla_dgemm(0,m,n,k,q,ldq,w(ib),max(1,k),w(ic),m)
        s=0
        do 1200 j=1,n
        do 1100 i=1,m
        s=s+(a(i,j)-w(ic+(i-1)+(j-1)*m))**2
 1100 continue
 1200 continue
        tspan_d=sqrt(s)/tfro_d(m,n,a,lda)
        return
        end

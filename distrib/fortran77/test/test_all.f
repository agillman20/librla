        zero=tstzero()
        call rla_zsvd_sketch(m,n,a,m,zero/zero,42,0,12,ig1,kc,k,u,m,
     1      s,vt,kc,w,lwmax,ier)
        call check('cplx rtol NaN: ier 2',ier .eq. 2)

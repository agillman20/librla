        real *8 function tortc_d(m,k,q,ldq)
        implicit real *8 (a-h,o-z)
        real *8 q(ldq,*),d
c
c       max |Q^T Q - I| over the k columns of q
c
        e=0
        do 1300 j=1,k
        do 1200 i=1,k
        d=0
        do 1100 l=1,m
        d=d+q(l,i)*q(l,j)
 1100 continue
        if( i .eq. j ) d=d-1
        e=max(e,abs(d))
 1200 continue
 1300 continue
        tortc_d=e
        return
        end

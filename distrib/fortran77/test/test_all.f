     1      vt,10,w,lwmax,ier)
        call check('cplx ldvt < kcap: ier 2',ier .eq. 2)
        call check('cplx iseed unchanged after errors',
     1      ig1(1) .eq. ig2(1)
     1      .and. ig1(4) .eq. ig2(4))
        call seed(ig2,1,2,3,4)
        call rla_zsvd_sketch(m,n,a,m,20.0d0,42,0,12,ig2,kc,k,u,m,s,
     1      vt,kc,w,lwmax,ier)

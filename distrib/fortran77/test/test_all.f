        subroutine torth_z(iseed,m,n,q,w)
        implicit real *8 (a-h,o-z)
        complex *16 q(m,*),w(*)
        dimension iseed(4)
c
c       q (m x n, m >= n): orthonormal columns from the pivoted QR of
c       a random matrix (library kernels)
c
        call rla_zrandn(iseed,m*n,q)
        call rla_zqrp(m,n,q,m,w(1),w(n+1),w(2*n+1),w(3*n+1),w(4*n+1))
        call rla_zorgqr(m,n,q,m,w(n+1),w(4*n+1))
        return
        end

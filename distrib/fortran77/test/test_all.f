     1      lwmax,ier)
        call check('cplx id_qrpiv k = n',ier .eq. 0 .and. k .eq. 80
     1      .and. isperm(80,ipiv))
        call rla_zid_sketch(100,80,gm,100,80.0d0,42,0,12,3,ig1,kc,k,
     1      ipiv,t,kc,w,lwmax,ier)
        call check('cplx id_sketch k = n (lstsq)',ier .eq. 0 .and.
     1      k .eq. 80)
        call rla_zid_qrpiv(m,n,a,m,1.0d-6,4,kc,k,ipiv,t,kc,w,lwmax,

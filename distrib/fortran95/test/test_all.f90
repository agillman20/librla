module test_support
  implicit none
  integer, parameter :: dp = kind(1.0d0)
  integer, parameter :: i8 = selected_int_kind(18)
  complex(dp), parameter :: ZONE = (1.0_dp, 0.0_dp), ZZERO = (0.0_dp, 0.0_dp)
  integer :: npass = 0, nfail = 0
  external :: dlarnv, zlarnv, dgeqrf, zgeqrf, dorgqr, zungqr, dgeqp3, zgeqp3
  external :: dgemm, zgemm

contains

  subroutine check(name, ok)
    character(len=*), intent(in) :: name
    logical, intent(in) :: ok
    if (ok) then
       npass = npass + 1
       write(*, '(2a)') 'PASS ', name
    else
       nfail = nfail + 1
       write(*, '(2a)') 'FAIL ', name
    end if
  end subroutine check

  subroutine check_le(name, val, tol)
    character(len=*), intent(in) :: name
    real(dp), intent(in) :: val, tol
    character(len=64) :: buf
    write(buf, '(a, es9.2, a, es8.1, a)') ' (', val, ' <= ', tol, ')'
    call check(name // trim(buf), val <= tol)
  end subroutine check_le

  character(len=5) function mname(im)
    integer, intent(in) :: im
    select case (im)
    case (1)
       mname = 'fast'
    case (2)
       mname = 'svd'
    case default
       mname = 'lstsq'
    end select
  end function mname

  logical function is_perm(p, n)
    integer, intent(in) :: p(:), n
    logical :: seen(n)
    integer :: i
    is_perm = .false.
    if (size(p) /= n) return
    seen = .false.
    do i = 1, n
       if (p(i) < 1 .or. p(i) > n) return
       if (seen(p(i))) return
       seen(p(i)) = .true.
    end do
    is_perm = .true.
  end function is_perm

  ! C printf("%.15e") formatting
  character(len=24) function fmt_e(x)
    real(dp), intent(in) :: x
    character(len=40) :: buf
    character(len=8) :: ebuf
    integer :: ie, ex
    write(buf, '(es24.15e3)') x
    buf = adjustl(buf)
    ie = index(buf, 'E')
    read(buf(ie+1:), *) ex
    write(ebuf, '(sp, i0.2)') ex
    fmt_e = buf(1:ie-1) // 'e' // trim(ebuf)
  end function fmt_e

  character(len=12) function itoa(i)
    integer, intent(in) :: i
    character(len=12) :: buf
    write(buf, '(i0)') i
    itoa = adjustl(buf)
  end function itoa

  ! ---------------- Real helpers ----------------

  real(dp) function fro_d(a)
    real(dp), intent(in) :: a(:,:)
    fro_d = sqrt(sum(abs(a)**2))
  end function fro_d

  ! ||A - Q Q^T A|| / ||A||
  real(dp) function span_err_d(a, q)
    real(dp), intent(in) :: a(:,:), q(:,:)
    span_err_d = fro_d(a - matmul(q, matmul(transpose(q), a))) / fro_d(a)
  end function span_err_d

  ! max |Q^T Q - I|
  real(dp) function orth_err_d(q)
    real(dp), intent(in) :: q(:,:)
    real(dp) :: g(size(q, 2), size(q, 2))
    integer :: i
    orth_err_d = 0
    if (size(q, 2) == 0) return
    g = matmul(transpose(q), q)
    do i = 1, size(q, 2)
       g(i, i) = g(i, i) - 1
    end do
    orth_err_d = maxval(abs(g))
  end function orth_err_d

  ! ||A(:, piv) - Q R|| / ||A||
  real(dp) function qr_err_d(a, q, r, piv)
    real(dp), intent(in) :: a(:,:), q(:,:), r(:,:)
    integer, intent(in) :: piv(:)
    qr_err_d = fro_d(a(:, piv) - matmul(q, r)) / fro_d(a)
  end function qr_err_d

  ! ||A - U diag(s) Vt|| / ||A||
  real(dp) function svd_err_d(a, u, s, vt)
    real(dp), intent(in) :: a(:,:), u(:,:), vt(:,:)
    real(dp), intent(in) :: s(:)
    real(dp) :: us(size(u, 1), size(u, 2))
    integer :: j
    do j = 1, size(u, 2)
       us(:, j) = u(:, j) * s(j)
    end do
    svd_err_d = fro_d(a - matmul(us, vt)) / fro_d(a)
  end function svd_err_d

  ! ||A(:, piv(k+1:)) - A(:, piv(1:k)) T|| / ||A|| (absolute for A = 0)
  real(dp) function id_err_d(a, k, piv, t)
    real(dp), intent(in) :: a(:,:), t(:,:)
    integer, intent(in) :: k, piv(:)
    integer :: n
    n = size(a, 2)
    id_err_d = 0
    if (k >= n) return
    id_err_d = fro_d(a(:, piv(k+1:n)) - matmul(a(:, piv(1:k)), t)) &
         / max(fro_d(a), tiny(1.0_dp))
  end function id_err_d

  ! x (m x n) uniform(-1, 1) from dlarnv
  subroutine rand_d(iseed, m, n, x)
    integer, intent(inout) :: iseed(4)
    integer, intent(in) :: m, n
    real(dp), intent(out) :: x(m, n)
    call dlarnv(2, iseed, m*n, x)
  end subroutine rand_d

  ! q (m x n, m >= n) with orthonormal columns: Q factor of a random matrix
  subroutine rand_orth_d(iseed, m, n, q)
    integer, intent(inout) :: iseed(4)
    integer, intent(in) :: m, n
    real(dp), intent(out) :: q(m, n)
    real(dp) :: tau(n), wq(1)
    real(dp), allocatable :: work(:)
    integer :: info, lwork
    call rand_d(iseed, m, n, q)
    call dgeqrf(m, n, q, m, tau, wq, -1, info)
    lwork = int(real(wq(1)))
    allocate(work(lwork))
    call dgeqrf(m, n, q, m, tau, work, lwork, info)
    call dorgqr(m, n, n, q, m, tau, work, lwork, info)
    deallocate(work)
  end subroutine rand_orth_d

  ! a (m x n, m >= n) = U diag(s) V^T with random orthonormal U and V
  subroutine with_svals_d(iseed, m, n, s, a)
    integer, intent(inout) :: iseed(4)
    integer, intent(in) :: m, n
    real(dp), intent(in) :: s(n)
    real(dp), intent(out) :: a(m, n)
    real(dp) :: u(m, n), v(n, n)
    integer :: j
    call rand_orth_d(iseed, m, n, u)
    call rand_orth_d(iseed, n, n, v)
    do j = 1, n
       u(:, j) = u(:, j) * s(j)
    end do
    a = matmul(u, transpose(v))
  end subroutine with_svals_d

  ! Matrix-free test operator. ipar(1) = 1: dense m x n matrix stored in
  ! rpar; ipar(1) = 2: low-rank B C with B (m x r) then C (r x n) in
  ! rpar, r = ipar(2). ipar(3) counts the columns applied with itrans = 0.
  subroutine matvec_d(itrans, m, n, k, x, y, ipar, rpar, zpar)
    integer, intent(in) :: itrans, m, n, k
    real(dp), intent(in) :: x(*)
    real(dp), intent(inout) :: y(*)
    integer :: ipar(*)
    real(dp) :: rpar(*)
    complex(dp) :: zpar(*)
    if (itrans == 0) ipar(3) = ipar(3) + k
    if (ipar(1) == 1) then
       call dense_apply_d(itrans, m, n, k, x, y, rpar)
    else
       call lowrank_apply_d(itrans, m, n, ipar(2), k, x, y, rpar, rpar(m*ipar(2) + 1))
    end if
    if (abs(zpar(1)) < 0) ipar(3) = -1
  end subroutine matvec_d

  subroutine dense_apply_d(itrans, m, n, k, x, y, amat)
    integer, intent(in) :: itrans, m, n, k
    real(dp), intent(in) :: x(*), amat(m, n)
    real(dp), intent(inout) :: y(*)
    if (itrans == 0) then
       call dgemm('N', 'N', m, k, n, 1.0_dp, amat, m, x, n, 0.0_dp, y, m)
    else
       call dgemm('T', 'N', n, k, m, 1.0_dp, amat, m, x, m, 0.0_dp, y, n)
    end if
  end subroutine dense_apply_d

  ! y = B (C x) or C^T (B^T x)
  subroutine lowrank_apply_d(itrans, m, n, r, k, x, y, b, c)
    integer, intent(in) :: itrans, m, n, r, k
    real(dp), intent(in) :: x(*), b(m, r), c(r, n)
    real(dp), intent(inout) :: y(*)
    real(dp) :: w(r, k)
    if (itrans == 0) then
       call dgemm('N', 'N', r, k, n, 1.0_dp, c, r, x, n, 0.0_dp, w, r)
       call dgemm('N', 'N', m, k, r, 1.0_dp, b, m, w, r, 0.0_dp, y, m)
    else
       call dgemm('T', 'N', r, k, m, 1.0_dp, b, m, x, m, 0.0_dp, w, r)
       call dgemm('T', 'N', n, k, r, 1.0_dp, c, r, w, r, 0.0_dp, y, n)
    end if
  end subroutine lowrank_apply_d

  ! Deterministic pivoted QR straight from LAPACK, done the way the library
  ! does it: a(:, piv) = q (m x kk) r (kk x n), kk = min(m, n), written to
  ! q(1:m, 1:kk), r(1:kk, 1:n) and piv(1:n)
  subroutine pqr_d(m, n, a, q, r, piv)
    integer, intent(in) :: m, n
    real(dp), intent(in) :: a(m, n)
    real(dp), intent(inout) :: q(:,:), r(:,:)
    integer, intent(inout) :: piv(:)
    real(dp) :: w(m, n), tau(min(m, n)), wq(1)
    real(dp), allocatable :: work(:)
    ! (the real pivoted QR needs no rwork)
    integer :: info, lwork, kk, i, jp(n)
    kk = min(m, n)
    w = a
    jp = 0
    call dgeqp3(m, n, w, m, jp, tau, wq, -1, info)
    lwork = max(1, int(real(wq(1))))
    allocate(work(lwork))
    call dgeqp3(m, n, w, m, jp, tau, work, lwork, info)
    deallocate(work)
    piv(1:n) = jp
    r(1:kk, 1:n) = w(1:kk, :)
    do i = 1, kk
       r(i+1:kk, i) = 0
    end do
    call dorgqr(m, kk, kk, w, m, tau, wq, -1, info)
    lwork = max(1, int(real(wq(1))))
    allocate(work(lwork))
    call dorgqr(m, kk, kk, w, m, tau, work, lwork, info)
    deallocate(work)
    q(1:m, 1:kk) = w(:, 1:kk)
  end subroutine pqr_d

  ! max |V V^T - I| for V with orthonormal rows
  real(dp) function orth_rows_d(v)
    real(dp), intent(in) :: v(:,:)
    real(dp) :: g(size(v, 1), size(v, 1))
    integer :: i
    orth_rows_d = 0
    if (size(v, 1) == 0) return
    g = matmul(v, transpose(v))
    do i = 1, size(v, 1)
       g(i, i) = g(i, i) - 1
    end do
    orth_rows_d = maxval(abs(g))
  end function orth_rows_d

  ! max |r(i, j)| below the diagonal
  real(dp) function lower_max_d(r)
    real(dp), intent(in) :: r(:,:)
    integer :: i, j
    lower_max_d = 0
    do j = 1, size(r, 2)
       do i = j + 1, size(r, 1)
          lower_max_d = max(lower_max_d, abs(r(i, j)))
       end do
    end do
  end function lower_max_d

  ! ---------------- Complex helpers ----------------

  real(dp) function fro_z(a)
    complex(dp), intent(in) :: a(:,:)
    fro_z = sqrt(sum(abs(a)**2))
  end function fro_z

  ! ||A - Q Q^H A|| / ||A||
  real(dp) function span_err_z(a, q)
    complex(dp), intent(in) :: a(:,:), q(:,:)
    span_err_z = fro_z(a - matmul(q, matmul(conjg(transpose(q)), a))) / fro_z(a)
  end function span_err_z

  ! max |Q^H Q - I|
  real(dp) function orth_err_z(q)
    complex(dp), intent(in) :: q(:,:)
    complex(dp) :: g(size(q, 2), size(q, 2))
    integer :: i
    orth_err_z = 0
    if (size(q, 2) == 0) return
    g = matmul(conjg(transpose(q)), q)
    do i = 1, size(q, 2)
       g(i, i) = g(i, i) - 1
    end do
    orth_err_z = maxval(abs(g))
  end function orth_err_z

  ! ||A(:, piv) - Q R|| / ||A||
  real(dp) function qr_err_z(a, q, r, piv)
    complex(dp), intent(in) :: a(:,:), q(:,:), r(:,:)
    integer, intent(in) :: piv(:)
    qr_err_z = fro_z(a(:, piv) - matmul(q, r)) / fro_z(a)
  end function qr_err_z

  ! ||A - U diag(s) Vt|| / ||A||
  real(dp) function svd_err_z(a, u, s, vt)
    complex(dp), intent(in) :: a(:,:), u(:,:), vt(:,:)
    real(dp), intent(in) :: s(:)
    complex(dp) :: us(size(u, 1), size(u, 2))
    integer :: j
    do j = 1, size(u, 2)
       us(:, j) = u(:, j) * s(j)
    end do
    svd_err_z = fro_z(a - matmul(us, vt)) / fro_z(a)
  end function svd_err_z

  ! ||A(:, piv(k+1:)) - A(:, piv(1:k)) T|| / ||A|| (absolute for A = 0)
  real(dp) function id_err_z(a, k, piv, t)
    complex(dp), intent(in) :: a(:,:), t(:,:)
    integer, intent(in) :: k, piv(:)
    integer :: n
    n = size(a, 2)
    id_err_z = 0
    if (k >= n) return
    id_err_z = fro_z(a(:, piv(k+1:n)) - matmul(a(:, piv(1:k)), t)) &
         / max(fro_z(a), tiny(1.0_dp))
  end function id_err_z

  ! x (m x n) uniform(-1, 1) from zlarnv
  subroutine rand_z(iseed, m, n, x)
    integer, intent(inout) :: iseed(4)
    integer, intent(in) :: m, n
    complex(dp), intent(out) :: x(m, n)
    call zlarnv(2, iseed, m*n, x)
  end subroutine rand_z

  ! q (m x n, m >= n) with orthonormal columns: Q factor of a random matrix
  subroutine rand_orth_z(iseed, m, n, q)
    integer, intent(inout) :: iseed(4)
    integer, intent(in) :: m, n
    complex(dp), intent(out) :: q(m, n)
    complex(dp) :: tau(n), wq(1)
    complex(dp), allocatable :: work(:)
    integer :: info, lwork
    call rand_z(iseed, m, n, q)
    call zgeqrf(m, n, q, m, tau, wq, -1, info)
    lwork = int(real(wq(1)))
    allocate(work(lwork))
    call zgeqrf(m, n, q, m, tau, work, lwork, info)
    call zungqr(m, n, n, q, m, tau, work, lwork, info)
    deallocate(work)
  end subroutine rand_orth_z

  ! a (m x n, m >= n) = U diag(s) V^H with random orthonormal U and V
  subroutine with_svals_z(iseed, m, n, s, a)
    integer, intent(inout) :: iseed(4)
    integer, intent(in) :: m, n
    real(dp), intent(in) :: s(n)
    complex(dp), intent(out) :: a(m, n)
    complex(dp) :: u(m, n), v(n, n)
    integer :: j
    call rand_orth_z(iseed, m, n, u)
    call rand_orth_z(iseed, n, n, v)
    do j = 1, n
       u(:, j) = u(:, j) * s(j)
    end do
    a = matmul(u, conjg(transpose(v)))
  end subroutine with_svals_z

  ! Matrix-free test operator. ipar(1) = 1: dense m x n matrix stored in
  ! zpar; ipar(1) = 2: low-rank B C with B (m x r) then C (r x n) in
  ! zpar, r = ipar(2). ipar(3) counts the columns applied with itrans = 0.
  subroutine matvec_z(itrans, m, n, k, x, y, ipar, rpar, zpar)
    integer, intent(in) :: itrans, m, n, k
    complex(dp), intent(in) :: x(*)
    complex(dp), intent(inout) :: y(*)
    integer :: ipar(*)
    real(dp) :: rpar(*)
    complex(dp) :: zpar(*)
    if (itrans == 0) ipar(3) = ipar(3) + k
    if (ipar(1) == 1) then
       call dense_apply_z(itrans, m, n, k, x, y, zpar)
    else
       call lowrank_apply_z(itrans, m, n, ipar(2), k, x, y, zpar, zpar(m*ipar(2) + 1))
    end if
    if (rpar(1) < 0 .and. rpar(1) > 0) ipar(3) = -1
  end subroutine matvec_z

  subroutine dense_apply_z(itrans, m, n, k, x, y, amat)
    integer, intent(in) :: itrans, m, n, k
    complex(dp), intent(in) :: x(*), amat(m, n)
    complex(dp), intent(inout) :: y(*)
    if (itrans == 0) then
       call zgemm('N', 'N', m, k, n, ZONE, amat, m, x, n, ZZERO, y, m)
    else
       call zgemm('C', 'N', n, k, m, ZONE, amat, m, x, m, ZZERO, y, n)
    end if
  end subroutine dense_apply_z

  ! y = B (C x) or C^H (B^H x)
  subroutine lowrank_apply_z(itrans, m, n, r, k, x, y, b, c)
    integer, intent(in) :: itrans, m, n, r, k
    complex(dp), intent(in) :: x(*), b(m, r), c(r, n)
    complex(dp), intent(inout) :: y(*)
    complex(dp) :: w(r, k)
    if (itrans == 0) then
       call zgemm('N', 'N', r, k, n, ZONE, c, r, x, n, ZZERO, w, r)
       call zgemm('N', 'N', m, k, r, ZONE, b, m, w, r, ZZERO, y, m)
    else
       call zgemm('C', 'N', r, k, m, ZONE, b, m, x, m, ZZERO, w, r)
       call zgemm('C', 'N', n, k, r, ZONE, c, r, w, r, ZZERO, y, n)
    end if
  end subroutine lowrank_apply_z

  ! Deterministic pivoted QR straight from LAPACK, done the way the library
  ! does it: a(:, piv) = q (m x kk) r (kk x n), kk = min(m, n), written to
  ! q(1:m, 1:kk), r(1:kk, 1:n) and piv(1:n)
  subroutine pqr_z(m, n, a, q, r, piv)
    integer, intent(in) :: m, n
    complex(dp), intent(in) :: a(m, n)
    complex(dp), intent(inout) :: q(:,:), r(:,:)
    integer, intent(inout) :: piv(:)
    complex(dp) :: w(m, n), tau(min(m, n)), wq(1)
    complex(dp), allocatable :: work(:)
    real(dp) :: rwork(2*n)
    integer :: info, lwork, kk, i, jp(n)
    kk = min(m, n)
    w = a
    jp = 0
    call zgeqp3(m, n, w, m, jp, tau, wq, -1, rwork, info)
    lwork = max(1, int(real(wq(1))))
    allocate(work(lwork))
    call zgeqp3(m, n, w, m, jp, tau, work, lwork, rwork, info)
    deallocate(work)
    piv(1:n) = jp
    r(1:kk, 1:n) = w(1:kk, :)
    do i = 1, kk
       r(i+1:kk, i) = 0
    end do
    call zungqr(m, kk, kk, w, m, tau, wq, -1, info)
    lwork = max(1, int(real(wq(1))))
    allocate(work(lwork))
    call zungqr(m, kk, kk, w, m, tau, work, lwork, info)
    deallocate(work)
    q(1:m, 1:kk) = w(:, 1:kk)
  end subroutine pqr_z

  ! max |V V^H - I| for V with orthonormal rows
  real(dp) function orth_rows_z(v)
    complex(dp), intent(in) :: v(:,:)
    complex(dp) :: g(size(v, 1), size(v, 1))
    integer :: i
    orth_rows_z = 0
    if (size(v, 1) == 0) return
    g = matmul(v, conjg(transpose(v)))
    do i = 1, size(v, 1)
       g(i, i) = g(i, i) - 1
    end do
    orth_rows_z = maxval(abs(g))
  end function orth_rows_z

  ! max |r(i, j)| below the diagonal
  real(dp) function lower_max_z(r)
    complex(dp), intent(in) :: r(:,:)
    integer :: i, j
    lower_max_z = 0
    do j = 1, size(r, 2)
       do i = j + 1, size(r, 1)
          lower_max_z = max(lower_max_z, abs(r(i, j)))
       end do
    end do
  end function lower_max_z

end module test_support


program test_all
  use librla95
  use test_support
  implicit none

  call test_lapack_rng()
  call test_d()
  call test_z()
  call crossport()
  write(*, '(a, i0, a, i0, a)') 'SUMMARY ', npass, ' passed, ', nfail, ' failed'
  if (nfail > 0) stop 1

contains

  ! The shared RNG: LAPACK dlarnv/zlarnv reference values for iseed {1,2,3,5}
  subroutine test_lapack_rng()
    real(dp), parameter :: ref(6) = (/ &
         3.7327920546847082e-01_dp, 8.2093410748050388e-01_dp, &
         5.5866811353917711e-01_dp, 6.4291221902741569e-01_dp, &
         6.8760847451716955e-01_dp, 1.6449965895444763e-01_dp /)
    integer, parameter :: ref_seed(4) = (/ 2384, 3667, 635, 1229 /)
    real(dp) :: x(6)
    complex(dp) :: z(3)
    integer :: g(4)
    write(*, '(a)') '--- rng ---'
    g = (/ 1, 2, 3, 5 /)
    call dlarnv(2, g, 6, x)
    call check_le('rng dlarnv reference values', maxval(abs(x - ref)), 1e-15_dp)
    call check('rng dlarnv iseed after', all(g == ref_seed))
    g = (/ 1, 2, 3, 5 /)
    call zlarnv(2, g, 3, z)
    call check_le('rng zlarnv reference values', &
         max(maxval(abs(real(z) - ref(1:5:2))), maxval(abs(aimag(z) - ref(2:6:2)))), &
         1e-15_dp)
    call check('rng zlarnv iseed after', all(g == ref_seed))
  end subroutine test_lapack_rng

  subroutine test_d()
    integer, parameter :: m = 400, n = 300, kc = 300
    real(dp), allocatable :: a(:,:), aw(:,:), gm(:,:), lr(:,:), zm(:,:), b(:,:)
    real(dp), allocatable :: q(:,:), r(:,:), u(:,:), vt(:,:), t(:,:)
    real(dp), allocatable :: q2(:,:), r2(:,:), u2(:,:), vt2(:,:), t2(:,:)
    real(dp), allocatable :: pdat(:), bb(:,:), cc(:,:)
    real(dp), allocatable :: sv(:), d(:), s(:), s2(:)
    integer, allocatable :: piv(:), piv2(:)
    real(dp) :: rdum(1), tail, e(3), nan
    complex(dp) :: zdum(1)
    integer :: g(4), g1(4), g2(4), ipar(3), k, k2, flag, ier, im, j

    write(*, '(a)') '--- Real ---'
    rdum = 0
    zdum = 0
    nan = transfer(9221120237041090560_i8, 1.0_dp)
    allocate(sv(n), a(m, n), aw(n, m), gm(100, 80))
    do j = 1, n
       sv(j) = 10.0_dp**(-real(j - 1, dp)/4)
    end do
    g = (/ 11, 22, 33, 45 /)
    call with_svals_d(g, m, n, sv, a)
    aw = transpose(a)
    call rand_d(g, 100, 80, gm)
    ! Output buffers sized for every call below (leading dimensions m, kc)
    allocate(q(m, kc), r(kc, m), u(m, kc), vt(kc, m), t(kc, m), s(kc), d(kc))
    allocate(q2(m, kc), r2(kc, m), u2(m, kc), vt2(kc, m), t2(kc, m), s2(kc))
    allocate(piv(m), piv2(m))

    ! ---------------- orth_sketch ----------------
    g1 = (/ 1, 2, 3, 5 /)
    call rla_dorth_sketch(m, n, a, m, 1e-6_dp, 42, 0, 12, g1, kc, k, q, m, &
         d, flag, ier)
    call check('real orth tol: ier 0, flag 0, accepted at block 42', &
         ier == 0 .and. flag == 0 .and. k == 42)
    call check_le('real orth tol: span error', span_err_d(a, q(:, 1:k)), 1e-6_dp)
    call check_le('real orth tol: orthonormality', orth_err_d(q(:, 1:k)), 1e-13_dp)
    call check('real orth tol: diagr decreasing', all(d(1:k-1) >= d(2:k)))
    call check('real orth: iseed advanced', any(g1 /= (/ 1, 2, 3, 5 /)))
    call rla_dorth_sketch(m, n, a, m, 1e-10_dp, 42, 0, 12, g1, kc, k, q, m, &
         d, flag, ier)
    call check_le('real orth tol 1e-10: span error', span_err_d(a, q(:, 1:k)), &
         1e-9_dp)
    call rla_dorth_sketch(m, n, a, m, 20.0_dp, 42, 0, 12, g1, kc, k, q, m, &
         d, flag, ier)
    call check('real orth rank 20: k = 32', ier == 0 .and. flag == 0 .and. k == 32)
    ! first 20 rows only, through lda > m
    call rla_dorth_sketch(20, n, a, m, 15.7_dp, 42, 0, 12, g1, kc, k, q, m, &
         d, flag, ier)
    call check('real orth rank 15 on 20 x 300 (lda > m): k = 20', &
         ier == 0 .and. k == 20)
    call check_le('real orth rank 15 on 20 x 300: orthonormality', &
         orth_err_d(q(1:20, 1:k)), 1e-13_dp)
    call rla_dorth_sketch(m, n, a, m, 1e-6_dp, 42, 0, 0, g1, kc, k, q, m, &
         d, flag, ier)
    call check_le('real orth tol, extra 0: span error', &
         span_err_d(a, q(:, 1:k)), 1e-5_dp)
    call rla_dorth_sketch(m, n, a, m, 1e-17_dp, 42, 0, 12, g1, kc, k, q, m, &
         d, flag, ier)
    call check('real orth rtol < eps: flag 1, k = 0', &
         ier == 0 .and. flag == 1 .and. k == 0)
    call rla_dorth_sketch(100, 80, gm, 100, 1e-6_dp, 42, 0, 12, g1, kc, k, q, &
         m, d, flag, ier)
    call check('real orth full rank: flag 1, k = 0', &
         ier == 0 .and. flag == 1 .and. k == 0)
    g2 = g1
    call rla_dorth_sketch(m, n, a, m, 20.0_dp, 42, 0, 12, g1, 10, k, q, m, &
         d, flag, ier)
    call check('real orth kcap 10 < 32: ier 4, k = 32, iseed unchanged', &
         ier == RLA_ERR_KCAP .and. k == 32 .and. all(g1 == g2))

    ! ---------------- qr_sketch ----------------
    call rla_dqr_sketch(m, n, a, m, 1e-6_dp, 42, 0, 12, g1, kc, k, q, m, r, &
         kc, piv, ier)
    call check('real qr tol: ier 0, 20 < k < 42, permutation', &
         ier == 0 .and. k > 20 .and. k < 42 .and. is_perm(piv(1:n), n))
    call check_le('real qr tol: ||A(:,p) - QR||/||A||', &
         qr_err_d(a, q(:, 1:k), r(1:k, 1:n), piv(1:n)), 1e-5_dp)
    call check('real qr tol: R upper triangular', lower_max_d(r(1:k, 1:n)) <= 0)
    call check_le('real qr tol: orthonormality', orth_err_d(q(:, 1:k)), 1e-13_dp)
    call rla_dqr_sketch(m, n, a, m, 25.0_dp, 42, 0, 12, g1, kc, k, q, m, r, &
         kc, piv, ier)
    call pqr_d(m, n, a, q2, r2, piv2)
    call check('real qr rank: k = 25', ier == 0 .and. k == 25)
    call check_le('real qr rank: error / pivoted-QR error', &
         qr_err_d(a, q(:, 1:25), r(1:25, 1:n), piv(1:n)) / &
         qr_err_d(a, q2(:, 1:25), r2(1:25, 1:n), piv2(1:n)), 4.0_dp)
    call rla_dqr_sketch(n, m, aw, n, 1e-6_dp, 42, 0, 12, g1, kc, k, q, m, r, &
         kc, piv, ier)
    call check_le('real qr wide tol: error', &
         qr_err_d(aw, q(1:n, 1:k), r(1:k, 1:m), piv(1:m)), 1e-5_dp)
    call check('real qr wide tol: R upper, permutation', &
         lower_max_d(r(1:k, 1:m)) <= 0 .and. is_perm(piv(1:m), m))
    call rla_dqr_sketch(n, m, aw, n, 25.0_dp, 42, 0, 12, g1, kc, k, q, m, r, &
         kc, piv, ier)
    call check_le('real qr wide rank: error', &
         qr_err_d(aw, q(1:n, 1:k), r(1:k, 1:m), piv(1:m)), 1e-5_dp)
    call rla_dqr_sketch(100, 80, gm, 100, 1e-6_dp, 42, 0, 12, g1, kc, k, q, &
         m, r, kc, piv, ier)
    call pqr_d(100, 80, gm, q2, r2, piv2)
    call check('real qr fallback = deterministic pivoted QR', ier == 0 .and. &
         k == 80 .and. all(piv(1:80) == piv2(1:80)) .and. &
         maxval(abs(q(1:100, 1:80) - q2(1:100, 1:80))) <= 0 .and. &
         maxval(abs(r(1:80, 1:80) - r2(1:80, 1:80))) <= 0)

    ! ---------------- svd_sketch ----------------
    tail = sqrt(sum(sv(21:n)**2) / sum(sv**2))
    call rla_dsvd_sketch(m, n, a, m, 1e-6_dp, 42, 0, 12, g1, kc, k, u, m, s, &
         vt, kc, ier)
    call check_le('real svd tol: reconstruction', &
         svd_err_d(a, u(:, 1:k), s(1:k), vt(1:k, 1:n)), 1e-5_dp)
    call check_le('real svd tol: U orthonormal', orth_err_d(u(:, 1:k)), 1e-13_dp)
    call check_le('real svd tol: V orthonormal', &
         orth_rows_d(vt(1:k, 1:n)), 1e-13_dp)
    call check('real svd tol: s decreasing', all(s(1:k-1) >= s(2:k)))
    call rla_dsvd_sketch(m, n, a, m, 20.0_dp, 42, 0, 12, g1, kc, k, u, m, s, &
         vt, kc, ier)
    call check('real svd rank: k = 20', ier == 0 .and. k == 20)
    call check_le('real svd rank: error / optimal', &
         svd_err_d(a, u(:, 1:k), s(1:k), vt(1:k, 1:n)) / tail, 4.0_dp)
    call check_le('real svd rank: singular values', &
         maxval(abs(s(1:20) - sv(1:20))) / sv(1), 1e-4_dp)
    call rla_dsvd_sketch(n, m, aw, n, 1e-6_dp, 42, 0, 12, g1, kc, k, u, m, s, &
         vt, kc, ier)
    call check_le('real svd wide tol: reconstruction', &
         svd_err_d(aw, u(1:n, 1:k), s(1:k), vt(1:k, 1:m)), 1e-5_dp)
    call check_le('real svd wide tol: V orthonormal', &
         orth_rows_d(vt(1:k, 1:m)), 1e-13_dp)
    call rla_dsvd_sketch(n, m, aw, n, 20.0_dp, 42, 0, 12, g1, kc, k, u, m, s, &
         vt, kc, ier)
    call check_le('real svd wide rank: error / optimal', &
         svd_err_d(aw, u(1:n, 1:k), s(1:k), vt(1:k, 1:m)) / tail, 4.0_dp)
    call rla_dsvd_sketch(100, 80, gm, 100, 1e-6_dp, 42, 0, 12, g1, kc, k, u, &
         m, s, vt, kc, ier)
    call check_le('real svd fallback: full SVD, k = 80', &
         svd_err_d(gm, u(1:100, 1:k), s(1:k), vt(1:k, 1:80)), 1e-13_dp)
    call check('real svd fallback: k = 80', ier == 0 .and. k == 80)

    ! ---------------- id_sketch / id_qrpiv ----------------
    do im = 1, 3
       call rla_did_sketch(m, n, a, m, 1e-6_dp, 42, 0, 12, im, g1, kc, k, &
            piv, t, kc, ier)
       call check_le('real id_sketch tol ' // trim(mname(im)) // ': error', &
            id_err_d(a, k, piv(1:n), t(1:k, 1:n-k)), 1e-5_dp)
       call rla_did_sketch(m, n, a, m, 20.0_dp, 42, 0, 12, im, g1, kc, k, &
            piv, t, kc, ier)
       call check_le('real id_sketch rank ' // trim(mname(im)) // ': error', &
            id_err_d(a, k, piv(1:n), t(1:k, 1:n-k)), 1e-3_dp)
       call check('real id_sketch rank ' // trim(mname(im)) // ': k = 20', k == 20)
       call rla_did_qrpiv(m, n, a, m, 1e-6_dp, im, kc, k, piv, t, kc, ier)
       call check_le('real id_qrpiv tol ' // trim(mname(im)) // ': error', &
            id_err_d(a, k, piv(1:n), t(1:k, 1:n-k)), 1e-5_dp)
       call rla_did_qrpiv(m, n, a, m, 20.0_dp, im, kc, k, piv, t, kc, ier)
       call check_le('real id_qrpiv rank ' // trim(mname(im)) // ': error', &
            id_err_d(a, k, piv(1:n), t(1:k, 1:n-k)), 1e-3_dp)
       call rla_did_sketch(n, m, aw, n, 1e-6_dp, 42, 0, 12, im, g1, kc, k, &
            piv, t, kc, ier)
       call check_le('real id_sketch wide tol ' // trim(mname(im)) // ': error', &
            id_err_d(aw, k, piv(1:m), t(1:k, 1:m-k)), 1e-5_dp)
    end do

    ! rank-deficient: requested rank 10 > true rank 5
    allocate(lr(60, 40), bb(60, 5), cc(5, 40))
    call rand_d(g, 60, 5, bb)
    call rand_d(g, 5, 40, cc)
    lr = matmul(bb, cc)
    deallocate(bb, cc)
    do im = 1, 3
       call rla_did_sketch(60, 40, lr, 60, 10.0_dp, 42, 0, 12, im, g1, kc, k, &
            piv, t, kc, ier)
       call check('real id_sketch rank-deficient ' // trim(mname(im)) // ': k = 10, T finite', &
            ier == 0 .and. k == 10 .and. maxval(abs(t(1:k, 1:40-k))) < huge(1.0_dp))
       call check_le('real id_sketch rank-deficient ' // trim(mname(im)) // ': error', &
            id_err_d(lr, k, piv(1:40), t(1:k, 1:40-k)), 1e-10_dp)
       call rla_did_qrpiv(60, 40, lr, 60, 10.0_dp, im, kc, k, piv, t, kc, ier)
       call check_le('real id_qrpiv rank-deficient ' // trim(mname(im)) // ': error', &
            id_err_d(lr, k, piv(1:40), t(1:k, 1:40-k)), 1e-10_dp)
    end do

    ! zero matrix: k = 0; full rank requested: k = n, T empty
    allocate(zm(30, 20))
    zm = 0
    call rla_did_sketch(30, 20, zm, 30, 1e-6_dp, 42, 0, 12, 1, g1, kc, k, piv, &
         t, kc, ier)
    call check('real id_sketch zero matrix: k = 0', ier == 0 .and. k == 0 .and. &
         is_perm(piv(1:20), 20))
    call rla_did_qrpiv(30, 20, zm, 30, 1e-6_dp, 1, kc, k, piv, t, kc, ier)
    call check('real id_qrpiv zero matrix: k = 0', ier == 0 .and. k == 0)
    call rla_did_qrpiv(100, 80, gm, 100, 80.0_dp, 1, kc, k, piv, t, kc, ier)
    call check('real id_qrpiv k = n', ier == 0 .and. k == 80 .and. is_perm(piv(1:80), 80))
    call rla_did_sketch(100, 80, gm, 100, 80.0_dp, 42, 0, 12, 3, g1, kc, k, &
         piv, t, kc, ier)
    call check('real id_sketch k = n (lstsq)', ier == 0 .and. k == 80)
    call rla_did_qrpiv(m, n, a, m, 1e-6_dp, 4, kc, k, piv, t, kc, ier)
    call check('real id_qrpiv invalid method: ier 1', ier == RLA_ERR_METHOD .and. k == 0)

    ! ---------------- argument checks ----------------
    g2 = g1
    call rla_dsvd_sketch(m, n, a, m - 1, 20.0_dp, 42, 0, 12, g1, kc, k, u, m, &
         s, vt, kc, ier)
    call check('real lda < m: ier 2', ier == RLA_ERR_ARG)
    call rla_dsvd_sketch(m, n, a, m, 20.0_dp, -1, 0, 12, g1, kc, k, u, m, s, &
         vt, kc, ier)
    call check('real block size < 0: ier 2', ier == RLA_ERR_ARG)
    call rla_dsvd_sketch(m, n, a, m, nan, 42, 0, 12, g1, kc, k, u, m, s, vt, &
         kc, ier)
    call check('real rtol NaN: ier 2', ier == RLA_ERR_ARG)
    call rla_dsvd_sketch(m, n, a, m, 1e30_dp, 42, 0, 12, g1, kc, k, u, m, s, &
         vt, kc, ier)
    call check('real rtol 1e30: ier 2', ier == RLA_ERR_ARG)
    call rla_dsvd_sketch(m, n, a, m, 20.0_dp, 42, 0, 12, g1, kc, k, u, m, s, &
         vt, 10, ier)
    call check('real ldvt < kcap: ier 2', ier == RLA_ERR_ARG)
    call check('real iseed unchanged after errors', all(g1 == g2))
    g2 = (/ 1, 2, 3, 4 /)
    call rla_dsvd_sketch(m, n, a, m, 20.0_dp, 42, 0, 12, g2, kc, k, u, m, s, &
         vt, kc, ier)
    call check('real even iseed(4): ier 2', ier == RLA_ERR_ARG)
    g2 = (/ 4096, 2, 3, 5 /)
    call rla_dsvd_sketch(m, n, a, m, 20.0_dp, 42, 0, 12, g2, kc, k, u, m, s, &
         vt, kc, ier)
    call check('real iseed entry > 4095: ier 2', ier == RLA_ERR_ARG)

    ! ---------------- matrix-free ----------------
    ! the dense matrix behind a callback (dgemm, as in the dense path). The
    ! tolerance-mode comparisons use rtol = 1.3e-6, between singular values
    ! 24 and 25: at 1e-6 = sv(25) rounding decides the rank.
    allocate(pdat(m*n))
    pdat = reshape(a, (/ m*n /))
    ipar = (/ 1, 0, 0 /)
    g1 = (/ 1, 2, 3, 5 /); g2 = g1
    call rla_dorth_sketch(m, n, a, m, 10.0_dp, 42, 0, 12, g1, kc, k, q, m, d, &
         flag, ier)
    call rla_dorth_sketchf(m, n, matvec_d, ipar, pdat, zdum, 10.0_dp, 42, 0, 12, g2, &
         kc, k2, q2, m, s, flag, ier)
    call check('real operator orth rank = dense (bitwise), same iseed after', &
         k == k2 .and. maxval(abs(q(:, 1:k) - q2(:, 1:k))) <= 0 .and. all(g1 == g2))
    call rla_dqr_sketch(m, n, a, m, 20.0_dp, 42, 0, 12, g1, kc, k, q, m, r, &
         kc, piv, ier)
    call rla_dqr_sketchf(m, n, matvec_d, ipar, pdat, zdum, 20.0_dp, 42, 0, 12, g2, &
         kc, k2, q2, m, r2, kc, piv2, ier)
    call check('real operator qr rank = dense: k, piv', &
         k == k2 .and. all(piv(1:n) == piv2(1:n)))
    call check_le('real operator qr rank = dense: R', &
         maxval(abs(r(1:k, 1:n) - r2(1:k, 1:n))) / abs(r(1, 1)), 1e-12_dp)
    call rla_dsvd_sketch(m, n, a, m, 1.3e-6_dp, 42, 1, 12, g1, kc, k, u, m, s, &
         vt, kc, ier)
    call rla_dsvd_sketchf(m, n, matvec_d, ipar, pdat, zdum, 1.3e-6_dp, 42, 1, 12, g2, &
         kc, k2, u2, m, s2, vt2, kc, ier)
    call check_le('real operator svd tol (power_iter=1) = dense', &
         maxval(abs(s(1:k) - s2(1:k))) / s(1), 1e-12_dp)
    call rla_did_sketch(m, n, a, m, 1.3e-6_dp, 42, 0, 12, 3, g1, kc, k, piv, t, &
         kc, ier)
    call rla_did_sketchf(m, n, matvec_d, ipar, pdat, zdum, 1.3e-6_dp, 42, 0, 12, 3, g2, &
         kc, k2, piv2, t2, kc, ier)
    call check('real operator id_sketch lstsq = dense: k, piv', &
         k == k2 .and. all(piv(1:n) == piv2(1:n)))
    call check_le('real operator id_sketch lstsq = dense: T', &
         maxval(abs(t(1:k, 1:n-k) - t2(1:k, 1:n-k))), 1e-9_dp)
    deallocate(pdat)

    ! wide operator: svd_sketch goes through the adjoint
    allocate(pdat(n*m))
    pdat = reshape(aw, (/ n*m /))
    call rla_dsvd_sketch(n, m, aw, n, 15.0_dp, 42, 0, 12, g1, kc, k, u, m, s, &
         vt, kc, ier)
    call rla_dsvd_sketchf(n, m, matvec_d, ipar, pdat, zdum, 15.0_dp, 42, 0, 12, g2, &
         kc, k2, u2, m, s2, vt2, kc, ier)
    call check_le('real operator svd wide rank = dense', &
         maxval(abs(s(1:k) - s2(1:k))) / s(1), 1e-12_dp)
    call check_le('real operator svd wide rank: reconstruction', &
         svd_err_d(aw, u2(1:n, 1:k2), s2(1:k2), vt2(1:k2, 1:m)) / &
         sqrt(sum(sv(16:n)**2) / sum(sv**2)), 4.0_dp)
    deallocate(pdat)

    ! tolerance-mode fallback materializes the operator
    allocate(pdat(100*80))
    pdat = reshape(gm, (/ 100*80 /))
    call rla_dqr_sketch(100, 80, gm, 100, 1e-6_dp, 42, 0, 12, g1, kc, k, q, &
         m, r, kc, piv, ier)
    ipar(3) = 0
    call rla_dqr_sketchf(100, 80, matvec_d, ipar, pdat, zdum, 1e-6_dp, 42, 0, 12, g2, &
         kc, k2, q2, m, r2, kc, piv2, ier)
    call check('real operator qr fallback = dense (materialized)', &
         k == k2 .and. all(piv(1:80) == piv2(1:80)) .and. &
         maxval(abs(q(1:100, 1:k) - q2(1:100, 1:k))) <= 1e-12_dp .and. &
         maxval(abs(r(1:k, 1:80) - r2(1:k, 1:80))) <= 1e-12_dp)
    call check('real operator qr fallback applied >= n columns', ipar(3) >= 80)
    call rla_dsvd_sketch(100, 80, gm, 100, 1e-6_dp, 42, 0, 12, g1, kc, k, u, &
         m, s, vt, kc, ier)
    call rla_dsvd_sketchf(100, 80, matvec_d, ipar, pdat, zdum, 1e-6_dp, 42, 0, 12, g2, &
         kc, k2, u2, m, s2, vt2, kc, ier)
    call check_le('real operator svd fallback = dense', &
         maxval(abs(s(1:k) - s2(1:k))), 1e-12_dp)
    call rla_did_qrpiv(100, 80, gm, 100, 30.0_dp, 2, kc, k, piv, t, kc, ier)
    call rla_did_qrpivf(100, 80, matvec_d, ipar, pdat, zdum, 30.0_dp, 2, kc, k2, piv2, &
         t2, kc, ier)
    call check('real operator id_qrpiv = dense', k == k2 .and. &
         all(piv(1:80) == piv2(1:80)) .and. &
         maxval(abs(t(1:k, 1:80-k) - t2(1:k, 1:80-k))) <= 1e-12_dp)
    deallocate(pdat)

    ! genuinely matrix-free low-rank product B C (300 x 200, rank 8)
    allocate(bb(300, 8), cc(8, 200), b(300, 200), pdat(300*8 + 8*200))
    call rand_d(g, 300, 8, bb)
    call rand_d(g, 8, 200, cc)
    b = matmul(bb, cc)
    pdat(1:300*8) = reshape(bb, (/ 300*8 /))
    pdat(300*8+1:) = reshape(cc, (/ 8*200 /))
    ipar = (/ 2, 8, 0 /)
    call rla_dsvd_sketchf(300, 200, matvec_d, ipar, pdat, zdum, 8.0_dp, 42, 0, 12, g1, &
         kc, k, u, m, s, vt, kc, ier)
    call check_le('real low-rank operator svd rank 8: reconstruction', &
         svd_err_d(b, u(1:300, 1:k), s(1:k), vt(1:k, 1:200)), 1e-12_dp)
    call check('real low-rank operator svd: no materialization', ipar(3) < 200)
    call rla_did_sketchf(300, 200, matvec_d, ipar, pdat, zdum, 8.0_dp, 42, 0, 12, 1, &
         g1, kc, k, piv, t, kc, ier)
    call check_le('real low-rank operator id_sketch rank 8: error', &
         id_err_d(b, k, piv(1:200), t(1:k, 1:200-k)), 1e-12_dp)
    call rla_dqr_sketchf(300, 200, matvec_d, ipar, pdat, zdum, 8.0_dp, 42, 0, 12, g1, &
         kc, k, q, m, r, kc, piv, ier)
    call check_le('real low-rank operator qr_sketch rank 8: error', &
         qr_err_d(b, q(1:300, 1:k), r(1:k, 1:200), piv(1:200)), 1e-12_dp)
    ! wide: C^T B^T (200 x 300)
    pdat(1:200*8) = reshape(transpose(cc), (/ 200*8 /))
    pdat(200*8+1:) = reshape(transpose(bb), (/ 8*300 /))
    call rla_dsvd_sketchf(200, 300, matvec_d, ipar, pdat, zdum, 8.0_dp, 42, 0, 12, g1, &
         kc, k, u, m, s, vt, kc, ier)
    call check_le('real low-rank wide operator svd rank 8: reconstruction', &
         svd_err_d(transpose(b), u(1:200, 1:k), s(1:k), vt(1:k, 1:300)), 1e-12_dp)
    deallocate(bb, cc, b, pdat)

    ! ---------------- power iteration, seeds ----------------
    deallocate(a)
    allocate(a(300, 200))
    do j = 1, 200
       sv(j) = 1.0_dp / j
    end do
    call with_svals_d(g, 300, 200, sv(1:200), a)
    do j = 1, 3
       g1 = (/ 1, 2, 3, 5 /)
       call rla_dsvd_sketch(300, 200, a, 300, 10.0_dp, 42, j - 1, 12, g1, kc, &
            k, u, m, s, vt, kc, ier)
       e(j) = svd_err_d(a, u(1:300, 1:k), s(1:k), vt(1:k, 1:200))
    end do
    call check('real power_iter 0 -> 1 -> 2 does not hurt accuracy', &
         e(2) <= 1.01_dp*e(1) .and. e(3) <= 1.01_dp*e(2))
    g1 = (/ 7, 7, 7, 7 /); g2 = g1
    call rla_dsvd_sketch(300, 200, a, 300, 10.0_dp, 42, 0, 12, g1, kc, k, u, &
         m, s, vt, kc, ier)
    call rla_dsvd_sketch(300, 200, a, 300, 10.0_dp, 42, 0, 12, g2, kc, k2, &
         u2, m, s2, vt2, kc, ier)
    call check('real same seed -> identical output', k == k2 .and. &
         maxval(abs(s(1:k) - s2(1:k))) <= 0 .and. all(g1 == g2))
  end subroutine test_d

  subroutine test_z()
    integer, parameter :: m = 400, n = 300, kc = 300
    complex(dp), allocatable :: a(:,:), aw(:,:), gm(:,:), lr(:,:), zm(:,:), b(:,:)
    complex(dp), allocatable :: q(:,:), r(:,:), u(:,:), vt(:,:), t(:,:)
    complex(dp), allocatable :: q2(:,:), r2(:,:), u2(:,:), vt2(:,:), t2(:,:)
    complex(dp), allocatable :: pdat(:), bb(:,:), cc(:,:)
    real(dp), allocatable :: sv(:), d(:), s(:), s2(:)
    integer, allocatable :: piv(:), piv2(:)
    real(dp) :: rdum(1), tail, e(3), nan
    complex(dp) :: zdum(1)
    integer :: g(4), g1(4), g2(4), ipar(3), k, k2, flag, ier, im, j

    write(*, '(a)') '--- Complex ---'
    rdum = 0
    zdum = 0
    nan = transfer(9221120237041090560_i8, 1.0_dp)
    allocate(sv(n), a(m, n), aw(n, m), gm(100, 80))
    do j = 1, n
       sv(j) = 10.0_dp**(-real(j - 1, dp)/4)
    end do
    g = (/ 11, 22, 33, 45 /)
    call with_svals_z(g, m, n, sv, a)
    aw = conjg(transpose(a))
    call rand_z(g, 100, 80, gm)
    ! Output buffers sized for every call below (leading dimensions m, kc)
    allocate(q(m, kc), r(kc, m), u(m, kc), vt(kc, m), t(kc, m), s(kc), d(kc))
    allocate(q2(m, kc), r2(kc, m), u2(m, kc), vt2(kc, m), t2(kc, m), s2(kc))
    allocate(piv(m), piv2(m))

    ! ---------------- orth_sketch ----------------
    g1 = (/ 1, 2, 3, 5 /)
    call rla_zorth_sketch(m, n, a, m, 1e-6_dp, 42, 0, 12, g1, kc, k, q, m, &
         d, flag, ier)
    call check('cplx orth tol: ier 0, flag 0, accepted at block 42', &
         ier == 0 .and. flag == 0 .and. k == 42)
    call check_le('cplx orth tol: span error', span_err_z(a, q(:, 1:k)), 1e-6_dp)
    call check_le('cplx orth tol: orthonormality', orth_err_z(q(:, 1:k)), 1e-13_dp)
    call check('cplx orth tol: diagr decreasing', all(d(1:k-1) >= d(2:k)))
    call check('cplx orth: iseed advanced', any(g1 /= (/ 1, 2, 3, 5 /)))
    call rla_zorth_sketch(m, n, a, m, 1e-10_dp, 42, 0, 12, g1, kc, k, q, m, &
         d, flag, ier)
    call check_le('cplx orth tol 1e-10: span error', span_err_z(a, q(:, 1:k)), &
         1e-9_dp)
    call rla_zorth_sketch(m, n, a, m, 20.0_dp, 42, 0, 12, g1, kc, k, q, m, &
         d, flag, ier)
    call check('cplx orth rank 20: k = 32', ier == 0 .and. flag == 0 .and. k == 32)
    ! first 20 rows only, through lda > m
    call rla_zorth_sketch(20, n, a, m, 15.7_dp, 42, 0, 12, g1, kc, k, q, m, &
         d, flag, ier)
    call check('cplx orth rank 15 on 20 x 300 (lda > m): k = 20', &
         ier == 0 .and. k == 20)
    call check_le('cplx orth rank 15 on 20 x 300: orthonormality', &
         orth_err_z(q(1:20, 1:k)), 1e-13_dp)
    call rla_zorth_sketch(m, n, a, m, 1e-6_dp, 42, 0, 0, g1, kc, k, q, m, &
         d, flag, ier)
    call check_le('cplx orth tol, extra 0: span error', &
         span_err_z(a, q(:, 1:k)), 1e-5_dp)
    call rla_zorth_sketch(m, n, a, m, 1e-17_dp, 42, 0, 12, g1, kc, k, q, m, &
         d, flag, ier)
    call check('cplx orth rtol < eps: flag 1, k = 0', &
         ier == 0 .and. flag == 1 .and. k == 0)
    call rla_zorth_sketch(100, 80, gm, 100, 1e-6_dp, 42, 0, 12, g1, kc, k, q, &
         m, d, flag, ier)
    call check('cplx orth full rank: flag 1, k = 0', &
         ier == 0 .and. flag == 1 .and. k == 0)
    g2 = g1
    call rla_zorth_sketch(m, n, a, m, 20.0_dp, 42, 0, 12, g1, 10, k, q, m, &
         d, flag, ier)
    call check('cplx orth kcap 10 < 32: ier 4, k = 32, iseed unchanged', &
         ier == RLA_ERR_KCAP .and. k == 32 .and. all(g1 == g2))

    ! ---------------- qr_sketch ----------------
    call rla_zqr_sketch(m, n, a, m, 1e-6_dp, 42, 0, 12, g1, kc, k, q, m, r, &
         kc, piv, ier)
    call check('cplx qr tol: ier 0, 20 < k < 42, permutation', &
         ier == 0 .and. k > 20 .and. k < 42 .and. is_perm(piv(1:n), n))
    call check_le('cplx qr tol: ||A(:,p) - QR||/||A||', &
         qr_err_z(a, q(:, 1:k), r(1:k, 1:n), piv(1:n)), 1e-5_dp)
    call check('cplx qr tol: R upper triangular', lower_max_z(r(1:k, 1:n)) <= 0)
    call check_le('cplx qr tol: orthonormality', orth_err_z(q(:, 1:k)), 1e-13_dp)
    call rla_zqr_sketch(m, n, a, m, 25.0_dp, 42, 0, 12, g1, kc, k, q, m, r, &
         kc, piv, ier)
    call pqr_z(m, n, a, q2, r2, piv2)
    call check('cplx qr rank: k = 25', ier == 0 .and. k == 25)
    call check_le('cplx qr rank: error / pivoted-QR error', &
         qr_err_z(a, q(:, 1:25), r(1:25, 1:n), piv(1:n)) / &
         qr_err_z(a, q2(:, 1:25), r2(1:25, 1:n), piv2(1:n)), 4.0_dp)
    call rla_zqr_sketch(n, m, aw, n, 1e-6_dp, 42, 0, 12, g1, kc, k, q, m, r, &
         kc, piv, ier)
    call check_le('cplx qr wide tol: error', &
         qr_err_z(aw, q(1:n, 1:k), r(1:k, 1:m), piv(1:m)), 1e-5_dp)
    call check('cplx qr wide tol: R upper, permutation', &
         lower_max_z(r(1:k, 1:m)) <= 0 .and. is_perm(piv(1:m), m))
    call rla_zqr_sketch(n, m, aw, n, 25.0_dp, 42, 0, 12, g1, kc, k, q, m, r, &
         kc, piv, ier)
    call check_le('cplx qr wide rank: error', &
         qr_err_z(aw, q(1:n, 1:k), r(1:k, 1:m), piv(1:m)), 1e-5_dp)
    call rla_zqr_sketch(100, 80, gm, 100, 1e-6_dp, 42, 0, 12, g1, kc, k, q, &
         m, r, kc, piv, ier)
    call pqr_z(100, 80, gm, q2, r2, piv2)
    call check('cplx qr fallback = deterministic pivoted QR', ier == 0 .and. &
         k == 80 .and. all(piv(1:80) == piv2(1:80)) .and. &
         maxval(abs(q(1:100, 1:80) - q2(1:100, 1:80))) <= 0 .and. &
         maxval(abs(r(1:80, 1:80) - r2(1:80, 1:80))) <= 0)

    ! ---------------- svd_sketch ----------------
    tail = sqrt(sum(sv(21:n)**2) / sum(sv**2))
    call rla_zsvd_sketch(m, n, a, m, 1e-6_dp, 42, 0, 12, g1, kc, k, u, m, s, &
         vt, kc, ier)
    call check_le('cplx svd tol: reconstruction', &
         svd_err_z(a, u(:, 1:k), s(1:k), vt(1:k, 1:n)), 1e-5_dp)
    call check_le('cplx svd tol: U orthonormal', orth_err_z(u(:, 1:k)), 1e-13_dp)
    call check_le('cplx svd tol: V orthonormal', &
         orth_rows_z(vt(1:k, 1:n)), 1e-13_dp)
    call check('cplx svd tol: s decreasing', all(s(1:k-1) >= s(2:k)))
    call rla_zsvd_sketch(m, n, a, m, 20.0_dp, 42, 0, 12, g1, kc, k, u, m, s, &
         vt, kc, ier)
    call check('cplx svd rank: k = 20', ier == 0 .and. k == 20)
    call check_le('cplx svd rank: error / optimal', &
         svd_err_z(a, u(:, 1:k), s(1:k), vt(1:k, 1:n)) / tail, 4.0_dp)
    call check_le('cplx svd rank: singular values', &
         maxval(abs(s(1:20) - sv(1:20))) / sv(1), 1e-4_dp)
    call rla_zsvd_sketch(n, m, aw, n, 1e-6_dp, 42, 0, 12, g1, kc, k, u, m, s, &
         vt, kc, ier)
    call check_le('cplx svd wide tol: reconstruction', &
         svd_err_z(aw, u(1:n, 1:k), s(1:k), vt(1:k, 1:m)), 1e-5_dp)
    call check_le('cplx svd wide tol: V orthonormal', &
         orth_rows_z(vt(1:k, 1:m)), 1e-13_dp)
    call rla_zsvd_sketch(n, m, aw, n, 20.0_dp, 42, 0, 12, g1, kc, k, u, m, s, &
         vt, kc, ier)
    call check_le('cplx svd wide rank: error / optimal', &
         svd_err_z(aw, u(1:n, 1:k), s(1:k), vt(1:k, 1:m)) / tail, 4.0_dp)
    call rla_zsvd_sketch(100, 80, gm, 100, 1e-6_dp, 42, 0, 12, g1, kc, k, u, &
         m, s, vt, kc, ier)
    call check_le('cplx svd fallback: full SVD, k = 80', &
         svd_err_z(gm, u(1:100, 1:k), s(1:k), vt(1:k, 1:80)), 1e-13_dp)
    call check('cplx svd fallback: k = 80', ier == 0 .and. k == 80)

    ! ---------------- id_sketch / id_qrpiv ----------------
    do im = 1, 3
       call rla_zid_sketch(m, n, a, m, 1e-6_dp, 42, 0, 12, im, g1, kc, k, &
            piv, t, kc, ier)
       call check_le('cplx id_sketch tol ' // trim(mname(im)) // ': error', &
            id_err_z(a, k, piv(1:n), t(1:k, 1:n-k)), 1e-5_dp)
       call rla_zid_sketch(m, n, a, m, 20.0_dp, 42, 0, 12, im, g1, kc, k, &
            piv, t, kc, ier)
       call check_le('cplx id_sketch rank ' // trim(mname(im)) // ': error', &
            id_err_z(a, k, piv(1:n), t(1:k, 1:n-k)), 1e-3_dp)
       call check('cplx id_sketch rank ' // trim(mname(im)) // ': k = 20', k == 20)
       call rla_zid_qrpiv(m, n, a, m, 1e-6_dp, im, kc, k, piv, t, kc, ier)
       call check_le('cplx id_qrpiv tol ' // trim(mname(im)) // ': error', &
            id_err_z(a, k, piv(1:n), t(1:k, 1:n-k)), 1e-5_dp)
       call rla_zid_qrpiv(m, n, a, m, 20.0_dp, im, kc, k, piv, t, kc, ier)
       call check_le('cplx id_qrpiv rank ' // trim(mname(im)) // ': error', &
            id_err_z(a, k, piv(1:n), t(1:k, 1:n-k)), 1e-3_dp)
       call rla_zid_sketch(n, m, aw, n, 1e-6_dp, 42, 0, 12, im, g1, kc, k, &
            piv, t, kc, ier)
       call check_le('cplx id_sketch wide tol ' // trim(mname(im)) // ': error', &
            id_err_z(aw, k, piv(1:m), t(1:k, 1:m-k)), 1e-5_dp)
    end do

    ! rank-deficient: requested rank 10 > true rank 5
    allocate(lr(60, 40), bb(60, 5), cc(5, 40))
    call rand_z(g, 60, 5, bb)
    call rand_z(g, 5, 40, cc)
    lr = matmul(bb, cc)
    deallocate(bb, cc)
    do im = 1, 3
       call rla_zid_sketch(60, 40, lr, 60, 10.0_dp, 42, 0, 12, im, g1, kc, k, &
            piv, t, kc, ier)
       call check('cplx id_sketch rank-deficient ' // trim(mname(im)) // ': k = 10, T finite', &
            ier == 0 .and. k == 10 .and. maxval(abs(t(1:k, 1:40-k))) < huge(1.0_dp))
       call check_le('cplx id_sketch rank-deficient ' // trim(mname(im)) // ': error', &
            id_err_z(lr, k, piv(1:40), t(1:k, 1:40-k)), 1e-10_dp)
       call rla_zid_qrpiv(60, 40, lr, 60, 10.0_dp, im, kc, k, piv, t, kc, ier)
       call check_le('cplx id_qrpiv rank-deficient ' // trim(mname(im)) // ': error', &
            id_err_z(lr, k, piv(1:40), t(1:k, 1:40-k)), 1e-10_dp)
    end do

    ! zero matrix: k = 0; full rank requested: k = n, T empty
    allocate(zm(30, 20))
    zm = 0
    call rla_zid_sketch(30, 20, zm, 30, 1e-6_dp, 42, 0, 12, 1, g1, kc, k, piv, &
         t, kc, ier)
    call check('cplx id_sketch zero matrix: k = 0', ier == 0 .and. k == 0 .and. &
         is_perm(piv(1:20), 20))
    call rla_zid_qrpiv(30, 20, zm, 30, 1e-6_dp, 1, kc, k, piv, t, kc, ier)
    call check('cplx id_qrpiv zero matrix: k = 0', ier == 0 .and. k == 0)
    call rla_zid_qrpiv(100, 80, gm, 100, 80.0_dp, 1, kc, k, piv, t, kc, ier)
    call check('cplx id_qrpiv k = n', ier == 0 .and. k == 80 .and. is_perm(piv(1:80), 80))
    call rla_zid_sketch(100, 80, gm, 100, 80.0_dp, 42, 0, 12, 3, g1, kc, k, &
         piv, t, kc, ier)
    call check('cplx id_sketch k = n (lstsq)', ier == 0 .and. k == 80)
    call rla_zid_qrpiv(m, n, a, m, 1e-6_dp, 4, kc, k, piv, t, kc, ier)
    call check('cplx id_qrpiv invalid method: ier 1', ier == RLA_ERR_METHOD .and. k == 0)

    ! ---------------- argument checks ----------------
    g2 = g1
    call rla_zsvd_sketch(m, n, a, m - 1, 20.0_dp, 42, 0, 12, g1, kc, k, u, m, &
         s, vt, kc, ier)
    call check('cplx lda < m: ier 2', ier == RLA_ERR_ARG)
    call rla_zsvd_sketch(m, n, a, m, 20.0_dp, -1, 0, 12, g1, kc, k, u, m, s, &
         vt, kc, ier)
    call check('cplx block size < 0: ier 2', ier == RLA_ERR_ARG)
    call rla_zsvd_sketch(m, n, a, m, nan, 42, 0, 12, g1, kc, k, u, m, s, vt, &
         kc, ier)
    call check('cplx rtol NaN: ier 2', ier == RLA_ERR_ARG)
    call rla_zsvd_sketch(m, n, a, m, 1e30_dp, 42, 0, 12, g1, kc, k, u, m, s, &
         vt, kc, ier)
    call check('cplx rtol 1e30: ier 2', ier == RLA_ERR_ARG)
    call rla_zsvd_sketch(m, n, a, m, 20.0_dp, 42, 0, 12, g1, kc, k, u, m, s, &
         vt, 10, ier)
    call check('cplx ldvt < kcap: ier 2', ier == RLA_ERR_ARG)
    call check('cplx iseed unchanged after errors', all(g1 == g2))
    g2 = (/ 1, 2, 3, 4 /)
    call rla_zsvd_sketch(m, n, a, m, 20.0_dp, 42, 0, 12, g2, kc, k, u, m, s, &
         vt, kc, ier)
    call check('cplx even iseed(4): ier 2', ier == RLA_ERR_ARG)
    g2 = (/ 4096, 2, 3, 5 /)
    call rla_zsvd_sketch(m, n, a, m, 20.0_dp, 42, 0, 12, g2, kc, k, u, m, s, &
         vt, kc, ier)
    call check('cplx iseed entry > 4095: ier 2', ier == RLA_ERR_ARG)

    ! ---------------- matrix-free ----------------
    ! the dense matrix behind a callback (dgemm, as in the dense path). The
    ! tolerance-mode comparisons use rtol = 1.3e-6, between singular values
    ! 24 and 25: at 1e-6 = sv(25) rounding decides the rank.
    allocate(pdat(m*n))
    pdat = reshape(a, (/ m*n /))
    ipar = (/ 1, 0, 0 /)
    g1 = (/ 1, 2, 3, 5 /); g2 = g1
    call rla_zorth_sketch(m, n, a, m, 10.0_dp, 42, 0, 12, g1, kc, k, q, m, d, &
         flag, ier)
    call rla_zorth_sketchf(m, n, matvec_z, ipar, rdum, pdat, 10.0_dp, 42, 0, 12, g2, &
         kc, k2, q2, m, s, flag, ier)
    call check('cplx operator orth rank = dense (bitwise), same iseed after', &
         k == k2 .and. maxval(abs(q(:, 1:k) - q2(:, 1:k))) <= 0 .and. all(g1 == g2))
    call rla_zqr_sketch(m, n, a, m, 20.0_dp, 42, 0, 12, g1, kc, k, q, m, r, &
         kc, piv, ier)
    call rla_zqr_sketchf(m, n, matvec_z, ipar, rdum, pdat, 20.0_dp, 42, 0, 12, g2, &
         kc, k2, q2, m, r2, kc, piv2, ier)
    call check('cplx operator qr rank = dense: k, piv', &
         k == k2 .and. all(piv(1:n) == piv2(1:n)))
    call check_le('cplx operator qr rank = dense: R', &
         maxval(abs(r(1:k, 1:n) - r2(1:k, 1:n))) / abs(r(1, 1)), 1e-12_dp)
    call rla_zsvd_sketch(m, n, a, m, 1.3e-6_dp, 42, 1, 12, g1, kc, k, u, m, s, &
         vt, kc, ier)
    call rla_zsvd_sketchf(m, n, matvec_z, ipar, rdum, pdat, 1.3e-6_dp, 42, 1, 12, g2, &
         kc, k2, u2, m, s2, vt2, kc, ier)
    call check_le('cplx operator svd tol (power_iter=1) = dense', &
         maxval(abs(s(1:k) - s2(1:k))) / s(1), 1e-12_dp)
    call rla_zid_sketch(m, n, a, m, 1.3e-6_dp, 42, 0, 12, 3, g1, kc, k, piv, t, &
         kc, ier)
    call rla_zid_sketchf(m, n, matvec_z, ipar, rdum, pdat, 1.3e-6_dp, 42, 0, 12, 3, g2, &
         kc, k2, piv2, t2, kc, ier)
    call check('cplx operator id_sketch lstsq = dense: k, piv', &
         k == k2 .and. all(piv(1:n) == piv2(1:n)))
    call check_le('cplx operator id_sketch lstsq = dense: T', &
         maxval(abs(t(1:k, 1:n-k) - t2(1:k, 1:n-k))), 1e-9_dp)
    deallocate(pdat)

    ! wide operator: svd_sketch goes through the adjoint
    allocate(pdat(n*m))
    pdat = reshape(aw, (/ n*m /))
    call rla_zsvd_sketch(n, m, aw, n, 15.0_dp, 42, 0, 12, g1, kc, k, u, m, s, &
         vt, kc, ier)
    call rla_zsvd_sketchf(n, m, matvec_z, ipar, rdum, pdat, 15.0_dp, 42, 0, 12, g2, &
         kc, k2, u2, m, s2, vt2, kc, ier)
    call check_le('cplx operator svd wide rank = dense', &
         maxval(abs(s(1:k) - s2(1:k))) / s(1), 1e-12_dp)
    call check_le('cplx operator svd wide rank: reconstruction', &
         svd_err_z(aw, u2(1:n, 1:k2), s2(1:k2), vt2(1:k2, 1:m)) / &
         sqrt(sum(sv(16:n)**2) / sum(sv**2)), 4.0_dp)
    deallocate(pdat)

    ! tolerance-mode fallback materializes the operator
    allocate(pdat(100*80))
    pdat = reshape(gm, (/ 100*80 /))
    call rla_zqr_sketch(100, 80, gm, 100, 1e-6_dp, 42, 0, 12, g1, kc, k, q, &
         m, r, kc, piv, ier)
    ipar(3) = 0
    call rla_zqr_sketchf(100, 80, matvec_z, ipar, rdum, pdat, 1e-6_dp, 42, 0, 12, g2, &
         kc, k2, q2, m, r2, kc, piv2, ier)
    call check('cplx operator qr fallback = dense (materialized)', &
         k == k2 .and. all(piv(1:80) == piv2(1:80)) .and. &
         maxval(abs(q(1:100, 1:k) - q2(1:100, 1:k))) <= 1e-12_dp .and. &
         maxval(abs(r(1:k, 1:80) - r2(1:k, 1:80))) <= 1e-12_dp)
    call check('cplx operator qr fallback applied >= n columns', ipar(3) >= 80)
    call rla_zsvd_sketch(100, 80, gm, 100, 1e-6_dp, 42, 0, 12, g1, kc, k, u, &
         m, s, vt, kc, ier)
    call rla_zsvd_sketchf(100, 80, matvec_z, ipar, rdum, pdat, 1e-6_dp, 42, 0, 12, g2, &
         kc, k2, u2, m, s2, vt2, kc, ier)
    call check_le('cplx operator svd fallback = dense', &
         maxval(abs(s(1:k) - s2(1:k))), 1e-12_dp)
    call rla_zid_qrpiv(100, 80, gm, 100, 30.0_dp, 2, kc, k, piv, t, kc, ier)
    call rla_zid_qrpivf(100, 80, matvec_z, ipar, rdum, pdat, 30.0_dp, 2, kc, k2, piv2, &
         t2, kc, ier)
    call check('cplx operator id_qrpiv = dense', k == k2 .and. &
         all(piv(1:80) == piv2(1:80)) .and. &
         maxval(abs(t(1:k, 1:80-k) - t2(1:k, 1:80-k))) <= 1e-12_dp)
    deallocate(pdat)

    ! genuinely matrix-free low-rank product B C (300 x 200, rank 8)
    allocate(bb(300, 8), cc(8, 200), b(300, 200), pdat(300*8 + 8*200))
    call rand_z(g, 300, 8, bb)
    call rand_z(g, 8, 200, cc)
    b = matmul(bb, cc)
    pdat(1:300*8) = reshape(bb, (/ 300*8 /))
    pdat(300*8+1:) = reshape(cc, (/ 8*200 /))
    ipar = (/ 2, 8, 0 /)
    call rla_zsvd_sketchf(300, 200, matvec_z, ipar, rdum, pdat, 8.0_dp, 42, 0, 12, g1, &
         kc, k, u, m, s, vt, kc, ier)
    call check_le('cplx low-rank operator svd rank 8: reconstruction', &
         svd_err_z(b, u(1:300, 1:k), s(1:k), vt(1:k, 1:200)), 1e-12_dp)
    call check('cplx low-rank operator svd: no materialization', ipar(3) < 200)
    call rla_zid_sketchf(300, 200, matvec_z, ipar, rdum, pdat, 8.0_dp, 42, 0, 12, 1, &
         g1, kc, k, piv, t, kc, ier)
    call check_le('cplx low-rank operator id_sketch rank 8: error', &
         id_err_z(b, k, piv(1:200), t(1:k, 1:200-k)), 1e-12_dp)
    call rla_zqr_sketchf(300, 200, matvec_z, ipar, rdum, pdat, 8.0_dp, 42, 0, 12, g1, &
         kc, k, q, m, r, kc, piv, ier)
    call check_le('cplx low-rank operator qr_sketch rank 8: error', &
         qr_err_z(b, q(1:300, 1:k), r(1:k, 1:200), piv(1:200)), 1e-12_dp)
    ! wide: C^H B^H (200 x 300)
    pdat(1:200*8) = reshape(conjg(transpose(cc)), (/ 200*8 /))
    pdat(200*8+1:) = reshape(conjg(transpose(bb)), (/ 8*300 /))
    call rla_zsvd_sketchf(200, 300, matvec_z, ipar, rdum, pdat, 8.0_dp, 42, 0, 12, g1, &
         kc, k, u, m, s, vt, kc, ier)
    call check_le('cplx low-rank wide operator svd rank 8: reconstruction', &
         svd_err_z(conjg(transpose(b)), u(1:200, 1:k), s(1:k), vt(1:k, 1:300)), 1e-12_dp)
    deallocate(bb, cc, b, pdat)

    ! ---------------- power iteration, seeds ----------------
    deallocate(a)
    allocate(a(300, 200))
    do j = 1, 200
       sv(j) = 1.0_dp / j
    end do
    call with_svals_z(g, 300, 200, sv(1:200), a)
    do j = 1, 3
       g1 = (/ 1, 2, 3, 5 /)
       call rla_zsvd_sketch(300, 200, a, 300, 10.0_dp, 42, j - 1, 12, g1, kc, &
            k, u, m, s, vt, kc, ier)
       e(j) = svd_err_z(a, u(1:300, 1:k), s(1:k), vt(1:k, 1:200))
    end do
    call check('cplx power_iter 0 -> 1 -> 2 does not hurt accuracy', &
         e(2) <= 1.01_dp*e(1) .and. e(3) <= 1.01_dp*e(2))
    g1 = (/ 7, 7, 7, 7 /); g2 = g1
    call rla_zsvd_sketch(300, 200, a, 300, 10.0_dp, 42, 0, 12, g1, kc, k, u, &
         m, s, vt, kc, ier)
    call rla_zsvd_sketch(300, 200, a, 300, 10.0_dp, 42, 0, 12, g2, kc, k2, &
         u2, m, s2, vt2, kc, ier)
    call check('cplx same seed -> identical output', k == k2 .and. &
         maxval(abs(s(1:k) - s2(1:k))) <= 0 .and. all(g1 == g2))
  end subroutine test_z

  ! Cross-port check: the same five lines in every experimental port
  subroutine crossport()
    real(dp), allocatable :: ar(:,:), q(:,:), d(:), t(:,:), s(:)
    complex(dp), allocatable :: ac(:,:), qc(:,:), u(:,:), vt(:,:)
    integer, allocatable :: piv(:)
    integer :: g(4), seed(4), k, flag, ier, i
    character(len=512) :: line

    write(*, '(a)') '--- crossport ---'
    allocate(ar(50, 30), q(50, 30), d(30))
    call hilbert_r(50, 30, ar)
    g = (/ 1, 2, 3, 5 /)
    call rla_dorth_sketch(50, 30, ar, 50, 5.0_dp, 42, 0, 3, g, 30, k, q, 50, &
         d, flag, ier)
    seed = g
    line = 'CROSSPORT orth_real'
    do i = 1, k
       line = trim(line) // ' ' // trim(fmt_e(d(i)))
    end do
    write(*, '(a)') trim(line)

    allocate(ac(50, 30), qc(50, 30))
    call hilbert_c(50, 30, ac)
    g = (/ 1, 2, 3, 5 /)
    call rla_zorth_sketch(50, 30, ac, 50, 5.0_dp, 42, 0, 3, g, 30, k, qc, 50, &
         d, flag, ier)
    line = 'CROSSPORT orth_cplx'
    do i = 1, k
       line = trim(line) // ' ' // trim(fmt_e(d(i)))
    end do
    write(*, '(a)') trim(line)

    line = 'CROSSPORT seed_after'
    do i = 1, 4
       line = trim(line) // ' ' // trim(itoa(seed(i)))
    end do
    write(*, '(a)') trim(line)

    deallocate(ar)
    allocate(ar(300, 200), piv(200), t(200, 200))
    call hilbert_r(300, 200, ar)
    g = (/ 1, 2, 3, 5 /)
    call rla_did_sketch(300, 200, ar, 300, 1e-10_dp, 42, 0, 12, 1, g, 200, k, &
         piv, t, 200, ier)
    line = 'CROSSPORT id_real ' // itoa(k)
    do i = 1, 10
       line = trim(line) // ' ' // trim(itoa(piv(i) - 1))
    end do
    write(*, '(a)') trim(line)

    deallocate(ac)
    allocate(ac(120, 80), u(120, 80), s(80), vt(80, 80))
    call hilbert_c(120, 80, ac)
    g = (/ 1, 2, 3, 5 /)
    call rla_zsvd_sketch(120, 80, ac, 120, 10.0_dp, 42, 1, 12, g, 80, k, u, &
         120, s, vt, 80, ier)
    line = 'CROSSPORT svd_cplx ' // itoa(k)
    do i = 1, 5
       line = trim(line) // ' ' // trim(fmt_e(s(i)))
    end do
    write(*, '(a)') trim(line)
  end subroutine crossport

  ! Ar(i, j) = 1 / (i + j + 1), 0-based
  subroutine hilbert_r(m, n, a)
    integer, intent(in) :: m, n
    real(dp), intent(out) :: a(m, n)
    integer :: i, j
    do j = 1, n
       do i = 1, m
          a(i, j) = 1.0_dp / real(i + j - 1, dp)
       end do
    end do
  end subroutine hilbert_r

  ! Ac(i, j) = (1 + 1i*(i - j)/80) / (i + j + 1), 0-based
  subroutine hilbert_c(m, n, a)
    integer, intent(in) :: m, n
    complex(dp), intent(out) :: a(m, n)
    integer :: i, j
    do j = 1, n
       do i = 1, m
          a(i, j) = cmplx(1.0_dp, real(i - j, dp) / 80, dp) / real(i + j - 1, dp)
       end do
    end do
  end subroutine hilbert_c

end program test_all

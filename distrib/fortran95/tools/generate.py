def wrap_line(line, indent="     "):
    """Break a free-form statement at commas to stay within 80 columns."""
    if len(line) <= 80:
        return line
    cut = line.rfind(", ", 0, 78)
    return line[:cut + 1] + " &\n" + wrap_line(indent + line[cut + 2:], indent)


def wrappers(t):
    out = []
    for name, args, decl, call, desc in FUNCS:
        drv = DRV[name]
        for free in (False, True):
            rname = f"rla_{t}{name}{'f' if free else ''}"
            if free:
                head = f"m, n, matvec, ipar, rpar, zpar, {args}"
                opdecl = """  integer, intent(in) :: m, n
  external :: matvec
  integer :: ipar(*)
  real(dp) :: rpar(*)
  complex(dp) :: zpar(*)"""
                locals_ = """  type(op_t) :: op
  @S :: adum(1)
  adum = 0
  op = make_op(m, n, 1, .false.)"""
                callargs = f"op, adum, matvec, ipar, rpar, zpar, {call}"
                kind = "matrix-free"
            else:
                head = f"m, n, a, lda, {args}"
                opdecl = """  integer, intent(in) :: m, n, lda
  @S, intent(in) :: a(lda, *)"""
                locals_ = """  type(op_t) :: op
  integer :: idum(1)
  real(dp) :: rdum(1)
  complex(dp) :: zdum(1)
  idum = 0
  rdum = 0
  zdum = 0
  op = make_op(m, n, lda, .true.)"""
                callargs = f"op, a, nomv_{t}, idum, rdum, zdum, {call}"
                kind = "dense"
            uses = f"op_t, make_op, drv_{drv}_{t}" + ("" if free else f", nomv_{t}")
            text = f"""
! {rname}: {desc} ({TYPES[t]['NAME'].lower()}, {kind})
{wrap_line(f"subroutine {rname}({head})")}
  use rla95_core, only: {uses}
  implicit none
  integer, parameter :: dp = kind(1.0d0)
{opdecl}
{decl}
  ! locals
{locals_}
{wrap_line(f"  call drv_{drv}_{t}({callargs})", "       ")}
end subroutine {rname}
"""
            out.append(expand(text, t))
    return "".join(out)



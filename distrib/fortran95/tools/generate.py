"""Generate the real and complex halves of the librla95 sources.

Fortran 95 has no generics over kinds, so each algorithm exists twice: as a
real (_d) and a complex (_z) routine. They are written once, as templates in
this directory, and expanded here:

    core.f90.in          -> src/rla95_core.f90 (with the shared helpers below)
    (this script)        -> src/librla95.f90, src/librla95_interfaces.f90
    test_support.f90.in,
    test_main.f90.in     -> test/test_all.f90

Template tokens: @T (d or z), @S (real(dp) or complex(dp)), @TC ('T' or 'C'),
@H (T or H, in comments), @ADJ(x) (transpose or conjugate transpose), @NAME,
@OPARGS/@OPDECL (the operator arguments), plus test-only tokens in
TEST_TOKENS.

Usage, from distrib/fortran95:
    python3 tools/generate.py           # rewrite the generated files
    python3 tools/generate.py --check   # exit 1 if any is out of date

Author: Adrianna Gillman, Zydrunas Gimbutas
SPDX-License-Identifier: MIT
Assisted by: Claude Code (Anthropic)
"""

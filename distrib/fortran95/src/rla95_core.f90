    real(dp), intent(in) :: a(*)
    external :: mv
    integer :: ipar(*)
    real(dp) :: rpar(*)
    complex(dp) :: zpar(*)
    integer, intent(in) :: l, pit
    integer, intent(inout) :: iseed(4)
    real(dp), pointer :: y(:,:)

  ! Dense placeholder for the matvec argument of the dense entry points
  subroutine nomv_z(itrans, m, n, k, x, y, ipar, rpar, zpar)
    integer, intent(in) :: itrans, m, n, k
    complex(dp), intent(in) :: x(*)
    complex(dp), intent(inout) :: y(*)
    integer :: ipar(*)
    real(dp) :: rpar(*)
    complex(dp) :: zpar(*)
    ! Never called: dense operators do not use mv. References every
    ! argument so the compiler does not flag them as unused.
    if (itrans < 0 .and. m < 0 .and. n < 0 .and. k < 0 .and. ipar(1) < 0 &
         .and. rpar(1) < 0 .and. abs(zpar(1)) < 0) y(1) = x(1)
  end subroutine nomv_z

  ! y = op(A) x, k columns: itrans = 0: y (m x k) = A x; itrans = 1:
  ! y (n x k) = A^H x, with (m, n) the shape seen by the algorithms
  subroutine apply_z(op, a, mv, ipar, rpar, zpar, itrans, k, x, y)
    type(op_t), intent(in) :: op
    complex(dp), intent(in) :: a(*)
    external :: mv
    integer :: ipar(*)
    real(dp) :: rpar(*)
    complex(dp) :: zpar(*)
    integer, intent(in) :: itrans, k
    complex(dp), intent(in) :: x(*)
    complex(dp), intent(inout) :: y(*)
    integer :: bt, mb, nb, nout, nin
    if (op%adj) then
       mb = op%n; nb = op%m; bt = 1 - itrans
    else
       mb = op%m; nb = op%n; bt = itrans
    end if
    if (bt == 0) then
       nout = mb; nin = nb
    else
       nout = nb; nin = mb
    end if
    if (nout == 0 .or. k == 0) return
    if (nin == 0) then
       y(1:nout*k) = 0
       return
    end if
    if (op%dense) then
       if (bt == 0) then
          call gemm_z('N', 'N', mb, k, nb, a, op%lda, x, nb, y, mb)
       else
          call gemm_z('C', 'N', nb, k, mb, a, op%lda, x, mb, y, nb)
       end if
    else
       call mv(bt, mb, nb, k, x, y, ipar, rpar, zpar)
    end if
  end subroutine apply_z

  ! Dense copy of A (m x n, allocated): the stored matrix, the adjoint of
  ! the base, or the base applied to blocks of identity columns
  subroutine get_matrix_z(op, a, mv, ipar, rpar, zpar, am)
    type(op_t), intent(in) :: op
    complex(dp), intent(in) :: a(*)
    external :: mv
    integer :: ipar(*)
    real(dp) :: rpar(*)
    complex(dp) :: zpar(*)
    complex(dp), pointer :: am(:,:)
    complex(dp), allocatable :: bm(:,:)
    allocate(am(op%m, op%n))
    if (op%adj) then
       allocate(bm(op%n, op%m))
       call base_matrix_z(op, a, mv, ipar, rpar, zpar, op%n, op%m, bm)
       am = conjg(transpose(bm))
       deallocate(bm)
    else
       call base_matrix_z(op, a, mv, ipar, rpar, zpar, op%m, op%n, am)
    end if
  end subroutine get_matrix_z

  subroutine base_matrix_z(op, a, mv, ipar, rpar, zpar, mb, nb, bm)
    type(op_t), intent(in) :: op
    complex(dp), intent(in) :: a(*)
    external :: mv
    integer :: ipar(*)
    real(dp) :: rpar(*)
    complex(dp) :: zpar(*)
    integer, intent(in) :: mb, nb
    complex(dp), intent(out) :: bm(mb, nb)
    complex(dp), allocatable :: e(:,:)
    integer :: j0, j1, j
    if (mb == 0 .or. nb == 0) return
    if (op%dense) then
       do j = 1, nb
          bm(:, j) = a((j - 1)*op%lda + 1:(j - 1)*op%lda + mb)
       end do
       return
    end if
    do j0 = 1, nb, materialize_block
       j1 = min(j0 + materialize_block - 1, nb)
       allocate(e(nb, j1 - j0 + 1))
       e = 0
       do j = j0, j1
          e(j, j - j0 + 1) = 1
       end do
       call mv(0, mb, nb, j1 - j0 + 1, e, bm(1, j0), ipar, rpar, zpar)
       deallocate(e)
    end do
  end subroutine base_matrix_z

  ! b (kq x n, allocated) = Q^H A; for anything but a stored matrix,
  ! (A^H Q)^H
  subroutine qh_times_a_z(op, a, mv, ipar, rpar, zpar, kq, q, b)
    type(op_t), intent(in) :: op
    complex(dp), intent(in) :: a(*)
    external :: mv
    integer :: ipar(*)
    real(dp) :: rpar(*)
    complex(dp) :: zpar(*)
    integer, intent(in) :: kq
    complex(dp), intent(in) :: q(:,:)
    complex(dp), pointer :: b(:,:)
    complex(dp), allocatable :: z(:,:)
    allocate(b(kq, op%n))
    if (op%dense .and. .not. op%adj) then
       call gemm_z('C', 'N', kq, op%n, op%m, q, max(1, op%m), a, op%lda, &
            b, max(1, kq))
    else
       allocate(z(op%n, kq))
       call apply_z(op, a, mv, ipar, rpar, zpar, 1, kq, q, z)
       b = conjg(transpose(z))
       deallocate(z)
    end if
  end subroutine qh_times_a_z


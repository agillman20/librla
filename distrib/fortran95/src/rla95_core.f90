    ierr = RLA_OK
    call get_matrix_d(op, a, mv, ipar, rpar, zpar, am)
    ! The QR overwrites its input: keep A only when lstsq needs it
    if (meth == METHOD_LSTSQ) then
       allocate(w(op%m, n))
       w = am
       call qrpiv_d(op%m, n, w, r, piv, qd, .false., info)
    else
       call qrpiv_d(op%m, n, am, r, piv, qd, .false., info)
    end if
    if (info /= 0) then
       ierr = RLA_ERR_LAPACK
       k = 0
       deallocate(r)
       if (associated(am)) deallocate(am)
       return
    end if
    if (rtol >= 1) then
       k = min(kmax_of(rtol), min(op%m, n))
       rts = 0
    else
       k = rank_from_diag_d(r, rtol)
       rts = rtol
    end if
    if (k == 0 .or. k == n) then
       allocate(t(k, n - k))
    else if (meth == METHOD_LSTSQ) then
       call t_lstsq_d(am, piv, k, t, ierr)
    else
       call compute_t_d(op, a, mv, ipar, rpar, zpar, r, piv, k, meth, rts, t, ierr)
    end if
    if (associated(am)) deallocate(am)
    deallocate(r)
  end subroutine idq_core_d

  ! T (k x (n-k), allocated) from R (rows 1:k used) and the pivots
  subroutine compute_t_d(op, a, mv, ipar, rpar, zpar, r, piv, k, meth, rts, t, ierr)
    type(op_t), intent(in) :: op
    real(dp), intent(in) :: a(*)
    external :: mv
    integer :: ipar(*)
    real(dp) :: rpar(*)
    complex(dp) :: zpar(*)
    real(dp), intent(in) :: r(:,:)
    integer, intent(in) :: piv(:), k, meth
    real(dp), intent(in) :: rts
    real(dp), pointer :: t(:,:)
    integer, intent(out) :: ierr
    real(dp), pointer :: am(:,:)
    ierr = RLA_OK
    select case (meth)
    case (METHOD_LSTSQ)
       if (k == 0 .or. k >= op%n) then
          allocate(t(k, op%n - k))
          t = 0
       else
          call get_matrix_d(op, a, mv, ipar, rpar, zpar, am)
          call t_lstsq_d(am, piv, k, t, ierr)
          deallocate(am)
       end if
    case (METHOD_SVD)
       call t_svd_d(r, k, rts, t, ierr)
    case default
       call t_fast_d(r, k, rts, t, ierr)
    end select
  end subroutine compute_t_d

  ! T = lstsq(A(:, piv(1:k)), A(:, piv(k+1:n)))
  subroutine t_lstsq_d(am, piv, k, t, ierr)
    real(dp), intent(in) :: am(:,:)
    integer, intent(in) :: piv(:), k
    real(dp), pointer :: t(:,:)
    integer, intent(out) :: ierr
    integer :: info, n
    n = size(am, 2)
    ierr = RLA_OK
    call lstsq_d(am(:, piv(1:k)), am(:, piv(k+1:n)), t, info)
    if (info /= 0) ierr = RLA_ERR_LAPACK
  end subroutine t_lstsq_d

  ! T = pinv(R11) R12, dropping singular values below max(rts, eps) * smax
  subroutine t_svd_d(r, k, rts, t, ierr)
    real(dp), intent(in) :: r(:,:)
    integer, intent(in) :: k
    real(dp), intent(in) :: rts
    real(dp), pointer :: t(:,:)
    integer, intent(out) :: ierr
    real(dp), pointer :: u(:,:), vt(:,:)
    real(dp), pointer :: s(:)
    real(dp), allocatable :: uk(:,:), vk(:,:), r12(:,:), w(:,:)
    integer, allocatable :: keep(:)
    real(dp) :: smax, cut
    integer :: n, nk, i, info

    n = size(r, 2)
    ierr = RLA_OK
    allocate(t(k, n - k))
    t = 0
    if (k == 0) return
    call svd_d(r(1:k, 1:k), u, s, vt, info)
    if (info /= 0) then
       ierr = RLA_ERR_LAPACK
       deallocate(u, s, vt)
       return
    end if
    smax = maxval(s)
    cut = max(rts, eps)*smax
    nk = count(s >= cut)
    if (smax > 0 .and. nk > 0) then
       allocate(keep(nk), uk(k, nk), vk(nk, k), r12(k, n - k), w(nk, n - k))
       keep = pack((/ (i, i = 1, k) /), s >= cut)
       uk = u(:, keep)
       vk = vt(keep, :)
       r12 = r(1:k, k+1:n)
       call gemm_d('T', 'N', nk, n - k, k, uk, k, r12, k, w, nk)
       do i = 1, nk
          w(i, :) = w(i, :) / s(keep(i))
       end do
       call gemm_d('T', 'N', k, n - k, nk, vk, nk, w, nk, t, k)
       deallocate(keep, uk, vk, r12, w)
    end if
    deallocate(u, s, vt)
  end subroutine t_svd_d

  ! T = R11 \ R12 by triangular solve, or t_svd if R11 is near-singular
  subroutine t_fast_d(r, k, rts, t, ierr)
    real(dp), intent(in) :: r(:,:)
    integer, intent(in) :: k
    real(dp), intent(in) :: rts
    real(dp), pointer :: t(:,:)
    integer, intent(out) :: ierr
    real(dp) :: dmin, dmax
    integer :: n, i

    n = size(r, 2)
    ierr = RLA_OK
    if (k == 0) then
       allocate(t(0, n))
       return
    end if
    dmin = abs(r(1, 1)); dmax = dmin
    do i = 2, k
       dmin = min(dmin, abs(r(i, i)))
       dmax = max(dmax, abs(r(i, i)))
    end do
    if (dmin <= eps*dmax) then
       call t_svd_d(r, k, rts, t, ierr)
       return
    end if
    allocate(t(k, n - k))
    t = r(1:k, k+1:n)
    call trsm_d(k, n - k, r, size(r, 1), t, k)
  end subroutine t_fast_d


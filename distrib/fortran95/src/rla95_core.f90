  end subroutine drv_svd_z

  subroutine drv_ids_z(op, a, mv, ipar, rpar, zpar, rtol, nb, npow, nextra, method, iseed, &
       kcap, k, piv, t, ldt, ier)
    type(op_t), intent(in) :: op
    complex(dp), intent(in) :: a(*)
    external :: mv
    integer :: ipar(*)
    real(dp) :: rpar(*)
    complex(dp) :: zpar(*)
    real(dp), intent(in) :: rtol
    integer, intent(in) :: nb, npow, nextra, method, kcap, ldt
    integer, intent(inout) :: iseed(4)
    integer, intent(out) :: k, ier
    integer, intent(inout) :: piv(*)
    complex(dp), intent(inout) :: t(ldt, *)
    complex(dp), pointer :: tt(:,:)
    integer, pointer :: pp(:)
    integer :: seed(4)
    k = 0
    call check_method(method, ier)
    if (ier == RLA_OK) &
         call check_sketch(op, rtol, nb, npow, nextra, iseed, kcap, ier)
    if (ier == RLA_OK .and. ldt < max(1, kcap)) ier = RLA_ERR_ARG
    if (ier /= RLA_OK) return
    seed = iseed
    call ids_core_z(op, a, mv, ipar, rpar, zpar, rtol, nb, npow, nextra, method, seed, k, pp, &
         tt, ier)
    if (ier /= RLA_OK) then
       k = 0
       if (associated(pp)) deallocate(pp)
       if (associated(tt)) deallocate(tt)
       return
    end if
    call copy_id_z(op%n, k, pp, tt, kcap, piv, t, ldt, ier)
    if (ier == RLA_OK) iseed = seed
  end subroutine drv_ids_z

  subroutine drv_idq_z(op, a, mv, ipar, rpar, zpar, rtol, method, kcap, k, piv, t, ldt, ier)
    type(op_t), intent(in) :: op
    complex(dp), intent(in) :: a(*)
    external :: mv
    integer :: ipar(*)
    real(dp) :: rpar(*)
    complex(dp) :: zpar(*)
    real(dp), intent(in) :: rtol
    integer, intent(in) :: method, kcap, ldt
    integer, intent(out) :: k, ier
    integer, intent(inout) :: piv(*)
    complex(dp), intent(inout) :: t(ldt, *)
    complex(dp), pointer :: tt(:,:)
    integer, pointer :: pp(:)
    k = 0
    call check_method(method, ier)
    if (ier == RLA_OK) call check_shape(op, rtol, 0, kcap, ier)
    if (ier == RLA_OK .and. ldt < max(1, kcap)) ier = RLA_ERR_ARG
    if (ier /= RLA_OK) return
    call idq_core_z(op, a, mv, ipar, rpar, zpar, rtol, method, k, pp, tt, ier)
    if (ier /= RLA_OK) then
       k = 0
       if (associated(pp)) deallocate(pp)
       if (associated(tt)) deallocate(tt)
       return
    end if
    call copy_id_z(op%n, k, pp, tt, kcap, piv, t, ldt, ier)
  end subroutine drv_idq_z

  subroutine copy_id_z(n, k, pp, tt, kcap, piv, t, ldt, ier)
    integer, intent(in) :: n, k, kcap, ldt
    integer, pointer :: pp(:)
    complex(dp), pointer :: tt(:,:)
    integer, intent(inout) :: piv(*)
    complex(dp), intent(inout) :: t(ldt, *)
    integer, intent(out) :: ier
    ier = RLA_OK
    if (k > kcap) then
       ier = RLA_ERR_KCAP
    else
       piv(1:n) = pp
       t(1:k, 1:n-k) = tt
    end if
    deallocate(pp, tt)
  end subroutine copy_id_z


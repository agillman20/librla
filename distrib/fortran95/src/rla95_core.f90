  recursive subroutine svd_core_d(op, a, mv, ipar, rpar, zpar, rtol, bs, pit, es, iseed, u, s, &
       vt, ierr)
    type(op_t), intent(in) :: op
    real(dp), intent(in) :: a(*)
    external :: mv
    integer :: ipar(*)
    real(dp) :: rpar(*)
    complex(dp) :: zpar(*)
    real(dp), intent(in) :: rtol
    integer, intent(in) :: bs, pit, es
    integer, intent(inout) :: iseed(4)
    real(dp), pointer :: u(:,:), vt(:,:)
    real(dp), pointer :: s(:)
    integer, intent(out) :: ierr
    type(op_t) :: opa
    real(dp), pointer :: qs(:,:), b(:,:), up(:,:), vp(:,:)
    real(dp), pointer :: d(:), sp(:)
    logical :: rank_mode, fallback
    integer :: mn, flag, k, rank, info

    nullify(u, s, vt)

    ! Wide matrix: factor the adjoint and swap the factors
    if (op%m < op%n) then
       opa = op
       opa%m = op%n; opa%n = op%m; opa%adj = .not. op%adj
       call svd_core_d(opa, a, mv, ipar, rpar, zpar, rtol, bs, pit, es, &
            iseed, up, s, vp, ierr)
       if (ierr /= RLA_OK) return
       allocate(u(op%m, size(vp, 1)), vt(size(up, 2), op%n))
       u = transpose(vp)
       vt = transpose(up)
       deallocate(up, vp)
       return
    end if

    mn = min(op%m, op%n)
    rank_mode = rtol >= 1
    call orth_core_d(op, a, mv, ipar, rpar, zpar, rtol, bs, pit, es, iseed, qs, d, flag, ierr)
    if (ierr /= RLA_OK) return
    deallocate(d)
    k = mn
    if (flag == 0) k = size(qs, 2)
    fallback = (flag /= 0 .or. k >= mn) .and. .not. rank_mode

    if (fallback) then
       deallocate(qs)
       call get_matrix_d(op, a, mv, ipar, rpar, zpar, b)
    else
       call qh_times_a_d(op, a, mv, ipar, rpar, zpar, size(qs, 2), qs, b)
    end if
    call svd_d(b, up, sp, vp, info)
    deallocate(b)
    if (info /= 0) then
       ierr = RLA_ERR_LAPACK
       deallocate(up, sp, vp)
       if (.not. fallback) deallocate(qs)
       return
    end if
    if (rank_mode) then
       rank = min(kmax_of(rtol), size(sp))
    else
       rank = rank_from_svals(sp, rtol)
    end if
    allocate(u(op%m, rank), s(rank), vt(rank, op%n))
    if (fallback) then
       u = up(:, 1:rank)
    else
       call gemm_d('N', 'N', op%m, rank, size(qs, 2), qs, max(1, op%m), &
            up, max(1, size(up, 1)), u, max(1, op%m))
       deallocate(qs)
    end if
    s = sp(1:rank)
    vt = vp(1:rank, :)
    deallocate(up, sp, vp)
  end subroutine svd_core_d


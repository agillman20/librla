  ! Complex: drivers behind the public rla_z* routines (argument checks,
  ! capacity checks, copy-out). iseed is updated only on success.
  ! ==================================================================

  subroutine drv_orth_z(op, a, mv, ipar, rpar, zpar, rtol, nb, npow, nextra, iseed, kcap, k, &
       q, ldq, diagr, flag, ier)
    type(op_t), intent(in) :: op
    complex(dp), intent(in) :: a(*)
    external :: mv
    integer :: ipar(*)
    real(dp) :: rpar(*)
    complex(dp) :: zpar(*)
    real(dp), intent(in) :: rtol
    integer, intent(in) :: nb, npow, nextra, kcap, ldq
    integer, intent(inout) :: iseed(4)
    integer, intent(out) :: k, flag, ier
    complex(dp), intent(inout) :: q(ldq, *)
    real(dp), intent(inout) :: diagr(*)
    complex(dp), pointer :: qq(:,:)
    real(dp), pointer :: d(:)
    integer :: seed(4)
    k = 0
    flag = 1
    call check_sketch(op, rtol, nb, npow, nextra, iseed, kcap, ier)
    if (ier == RLA_OK .and. ldq < max(1, op%m)) ier = RLA_ERR_ARG
    if (ier /= RLA_OK) return
    seed = iseed
    call orth_core_z(op, a, mv, ipar, rpar, zpar, rtol, nb, npow, nextra, seed, qq, d, flag, ier)
    if (ier /= RLA_OK) then
       flag = 1
       return
    end if
    k = size(qq, 2)
    if (k > kcap) then
       ier = RLA_ERR_KCAP
    else
       q(1:op%m, 1:k) = qq
       diagr(1:k) = d
       iseed = seed
    end if
    deallocate(qq, d)
  end subroutine drv_orth_z

  subroutine drv_qr_z(op, a, mv, ipar, rpar, zpar, rtol, nb, npow, nextra, iseed, kcap, k, &
       q, ldq, r, ldr, piv, ier)
    type(op_t), intent(in) :: op
    complex(dp), intent(in) :: a(*)
    external :: mv
    integer :: ipar(*)
    real(dp) :: rpar(*)
    complex(dp) :: zpar(*)
    real(dp), intent(in) :: rtol
    integer, intent(in) :: nb, npow, nextra, kcap, ldq, ldr
    integer, intent(inout) :: iseed(4)
    integer, intent(out) :: k, ier
    complex(dp), intent(inout) :: q(ldq, *), r(ldr, *)
    integer, intent(inout) :: piv(*)

    else
       q(1:op%m, 1:k) = qq
       r(1:k, 1:op%n) = rr
       piv(1:op%n) = pp
       iseed = seed
    end if
    deallocate(qq, rr, pp)
  end subroutine drv_qr_z

  subroutine drv_svd_z(op, a, mv, ipar, rpar, zpar, rtol, nb, npow, nextra, iseed, kcap, k, &
       u, ldu, s, vt, ldvt, ier)
    type(op_t), intent(in) :: op
    complex(dp), intent(in) :: a(*)
    external :: mv
    integer :: ipar(*)
    real(dp) :: rpar(*)
    complex(dp) :: zpar(*)
    real(dp), intent(in) :: rtol

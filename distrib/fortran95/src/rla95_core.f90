       flag, ierr)
    type(op_t), intent(in) :: op
    real(dp), intent(in) :: a(*)
    external :: mv
    integer :: ipar(*)
    real(dp) :: rpar(*)
    complex(dp) :: zpar(*)
    real(dp), intent(in) :: rtol
    integer, intent(in) :: bs, pit, es
    integer, intent(inout) :: iseed(4)
    real(dp), pointer :: q(:,:)
    real(dp), pointer :: diagr(:)
    integer, intent(out) :: flag, ierr
    integer :: mn, l, nd

    mn = min(op%m, op%n)
    flag = 0
    nullify(q, diagr)

    ! Rank mode: one sketch of floor(rtol) + extra_samples columns
    if (rtol >= 1) then
       call sketch_qr_d(op, a, mv, ipar, rpar, zpar, kmax_of(rtol) + es, pit, iseed, q, diagr, ierr)
       return
    end if

    ! Tolerance mode: fresh sketch per pass, block size grows 4x
    ierr = RLA_OK
    if (rtol < eps .or. bs >= mn) then
       flag = 1
       allocate(q(op%m, 0), diagr(0))
       return
    end if
    l = bs
    do
       call sketch_qr_d(op, a, mv, ipar, rpar, zpar, l, pit, iseed, q, diagr, ierr)
       if (ierr /= RLA_OK) return
       nd = size(diagr)
       if (nd == 0) return
       if (nd > es) then
          if (diagr(nd - es) <= rtol*diagr(1)) return
       end if
       l = min(4*l, mn)
       deallocate(q, diagr)
       if (l >= mn) then
          flag = 1
          allocate(q(op%m, 0), diagr(0))
          return
       end if
    end do

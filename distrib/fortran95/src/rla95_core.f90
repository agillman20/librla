  ! y (m x l', allocated) = A x with x = Omega (n x l) after pit power
  ! iterations x <- orth(A^H A x); l' = l, or min(n, l) when pit > 0
  subroutine sample_z(op, a, mv, ipar, rpar, zpar, l, pit, iseed, y, ierr)
    type(op_t), intent(in) :: op
    complex(dp), intent(in) :: a(*)
    external :: mv
    integer :: ipar(*)
    real(dp) :: rpar(*)
    complex(dp) :: zpar(*)
    integer, intent(in) :: l, pit
    integer, intent(inout) :: iseed(4)
    complex(dp), pointer :: y(:,:)
    integer, intent(out) :: ierr
    complex(dp), pointer :: x(:,:), z(:,:), r(:,:), xn(:,:)
    integer, pointer :: jp(:)
    integer :: it, kx, info
    ierr = RLA_OK
    allocate(x(op%n, l))
    call larnv_z(iseed, op%n*l, x)
    do it = 1, pit
       kx = size(x, 2)
       allocate(y(op%m, kx), z(op%n, kx))
       call apply_z(op, a, mv, ipar, rpar, zpar, 0, kx, x, y)
       call apply_z(op, a, mv, ipar, rpar, zpar, 1, kx, y, z)
       deallocate(y, x)
       call qrpiv_z(op%n, kx, z, r, jp, xn, .true., info)
       deallocate(r, jp)
       if (info /= 0) then
          ierr = RLA_ERR_LAPACK
          nullify(y)
          return
       end if
       x => xn
    end do
    kx = size(x, 2)
    allocate(y(op%m, kx))
    call apply_z(op, a, mv, ipar, rpar, zpar, 0, kx, x, y)
    deallocate(x)
  end subroutine sample_z

  ! Q (m x k) and diagr = |diag R| of the pivoted QR of the sketch
  subroutine orth_core_z(op, a, mv, ipar, rpar, zpar, rtol, bs, pit, es, iseed, q, diagr, &
       flag, ierr)
    type(op_t), intent(in) :: op
    complex(dp), intent(in) :: a(*)
    external :: mv
    integer :: ipar(*)
    real(dp) :: rpar(*)
    complex(dp) :: zpar(*)
    real(dp), intent(in) :: rtol
    integer, intent(in) :: bs, pit, es
    integer, intent(inout) :: iseed(4)
    complex(dp), pointer :: q(:,:)
    real(dp), pointer :: diagr(:)
    integer, intent(out) :: flag, ierr
    integer :: mn, l, nd

    mn = min(op%m, op%n)
    flag = 0
    nullify(q, diagr)

    ! Rank mode: one sketch of floor(rtol) + extra_samples columns
    if (rtol >= 1) then
       call sketch_qr_z(op, a, mv, ipar, rpar, zpar, kmax_of(rtol) + es, pit, iseed, q, diagr, ierr)
       return
    end if

    ! Tolerance mode: fresh sketch per pass, block size grows 4x
    ierr = RLA_OK
    if (rtol < eps .or. bs >= mn) then
       flag = 1
       allocate(q(op%m, 0), diagr(0))
       return
    end if
    l = bs
    do
       call sketch_qr_z(op, a, mv, ipar, rpar, zpar, l, pit, iseed, q, diagr, ierr)
       if (ierr /= RLA_OK) return
       nd = size(diagr)
       if (nd == 0) return
       if (nd > es) then
          if (diagr(nd - es) <= rtol*diagr(1)) return
       end if
       l = min(4*l, mn)
       deallocate(q, diagr)
       if (l >= mn) then
          flag = 1
          allocate(q(op%m, 0), diagr(0))
          return
       end if
    end do
  end subroutine orth_core_z

  ! One sketch of l columns and its pivoted QR: q (m x k), diagr (k)
  subroutine sketch_qr_z(op, a, mv, ipar, rpar, zpar, l, pit, iseed, q, diagr, ierr)
    type(op_t), intent(in) :: op
    complex(dp), intent(in) :: a(*)
    external :: mv
    integer :: ipar(*)
    real(dp) :: rpar(*)
    complex(dp) :: zpar(*)
    integer, intent(in) :: l, pit
    integer, intent(inout) :: iseed(4)
    complex(dp), pointer :: q(:,:)
    real(dp), pointer :: diagr(:)
    integer, intent(out) :: ierr
    complex(dp), pointer :: y(:,:), r(:,:)
    integer, pointer :: jp(:)
    integer :: i, info
    nullify(q, diagr)
    call sample_z(op, a, mv, ipar, rpar, zpar, l, pit, iseed, y, ierr)
    if (ierr /= RLA_OK) return
    call qrpiv_z(size(y, 1), size(y, 2), y, r, jp, q, .true., info)
    if (info /= 0) then
       ierr = RLA_ERR_LAPACK
       deallocate(r, jp)
       if (associated(q)) deallocate(q)
       return
    end if
    allocate(diagr(size(r, 1)))
    do i = 1, size(r, 1)
       diagr(i) = abs(r(i, i))
    end do
    deallocate(r, jp)
  end subroutine sketch_qr_z

  subroutine qr_core_z(op, a, mv, ipar, rpar, zpar, rtol, bs, pit, es, iseed, q, r, piv, ierr)
    type(op_t), intent(in) :: op
    complex(dp), intent(in) :: a(*)
    external :: mv
    integer :: ipar(*)
    real(dp) :: rpar(*)
    complex(dp) :: zpar(*)
    real(dp), intent(in) :: rtol
    integer, intent(in) :: bs, pit, es
    integer, intent(inout) :: iseed(4)
    complex(dp), pointer :: q(:,:), r(:,:)
    integer, pointer :: piv(:)
    integer, intent(out) :: ierr
    complex(dp), pointer :: qs(:,:), b(:,:), qp(:,:), rp(:,:)
    real(dp), pointer :: d(:)
    logical :: rank_mode, fallback
    integer :: mn, flag, k, rank, info

    nullify(q, r, piv)
    mn = min(op%m, op%n)
    rank_mode = rtol >= 1
    call orth_core_z(op, a, mv, ipar, rpar, zpar, rtol, bs, pit, es, iseed, qs, d, flag, ierr)
    if (ierr /= RLA_OK) return
    deallocate(d)
    k = mn
    if (flag == 0) k = size(qs, 2)
    fallback = (flag /= 0 .or. k >= mn) .and. .not. rank_mode

    if (fallback) then
       deallocate(qs)
       call get_matrix_z(op, a, mv, ipar, rpar, zpar, b)
    else
       call qh_times_a_z(op, a, mv, ipar, rpar, zpar, size(qs, 2), qs, b)
    end if
    call qrpiv_z(size(b, 1), size(b, 2), b, rp, piv, qp, .true., info)
    if (info /= 0) then
       ierr = RLA_ERR_LAPACK
       deallocate(rp, piv)
       if (associated(qp)) deallocate(qp)
       if (.not. fallback) deallocate(qs)
       return
    end if
    if (rank_mode) then
       rank = min(kmax_of(rtol), size(qp, 2))
    else
       rank = rank_from_diag_z(rp, rtol)
    end if
    allocate(q(op%m, rank), r(rank, op%n))
    if (fallback) then
       q = qp(:, 1:rank)
    else
       call gemm_z('N', 'N', op%m, rank, size(qs, 2), qs, max(1, op%m), &
            qp, max(1, size(qp, 1)), q, max(1, op%m))
       deallocate(qs)
    end if
    r = rp(1:rank, :)
    deallocate(qp, rp)
  end subroutine qr_core_z

  recursive subroutine svd_core_z(op, a, mv, ipar, rpar, zpar, rtol, bs, pit, es, iseed, u, s, &
       vt, ierr)
    type(op_t), intent(in) :: op
    complex(dp), intent(in) :: a(*)
    external :: mv
    integer :: ipar(*)
    real(dp) :: rpar(*)
    complex(dp) :: zpar(*)
    real(dp), intent(in) :: rtol
    integer, intent(in) :: bs, pit, es
    integer, intent(inout) :: iseed(4)
    complex(dp), pointer :: u(:,:), vt(:,:)
    real(dp), pointer :: s(:)
    integer, intent(out) :: ierr
    type(op_t) :: opa
    complex(dp), pointer :: qs(:,:), b(:,:), up(:,:), vp(:,:)
    real(dp), pointer :: d(:), sp(:)
    logical :: rank_mode, fallback
    integer :: mn, flag, k, rank, info

    nullify(u, s, vt)

    ! Wide matrix: factor the adjoint and swap the factors
    if (op%m < op%n) then
       opa = op
       opa%m = op%n; opa%n = op%m; opa%adj = .not. op%adj
       call svd_core_z(opa, a, mv, ipar, rpar, zpar, rtol, bs, pit, es, &
            iseed, up, s, vp, ierr)
       if (ierr /= RLA_OK) return
       allocate(u(op%m, size(vp, 1)), vt(size(up, 2), op%n))
       u = conjg(transpose(vp))
       vt = conjg(transpose(up))
       deallocate(up, vp)
       return
    end if

    mn = min(op%m, op%n)
    rank_mode = rtol >= 1
    call orth_core_z(op, a, mv, ipar, rpar, zpar, rtol, bs, pit, es, iseed, qs, d, flag, ierr)
    if (ierr /= RLA_OK) return
    deallocate(d)
    k = mn
    if (flag == 0) k = size(qs, 2)
    fallback = (flag /= 0 .or. k >= mn) .and. .not. rank_mode

    if (fallback) then
       deallocate(qs)
       call get_matrix_z(op, a, mv, ipar, rpar, zpar, b)
    else
       call qh_times_a_z(op, a, mv, ipar, rpar, zpar, size(qs, 2), qs, b)
    end if
    call svd_z(b, up, sp, vp, info)
    deallocate(b)
    if (info /= 0) then
       ierr = RLA_ERR_LAPACK
       deallocate(up, sp, vp)
       if (.not. fallback) deallocate(qs)
       return
    end if
    if (rank_mode) then
       rank = min(kmax_of(rtol), size(sp))
    else
       rank = rank_from_svals(sp, rtol)
    end if
    allocate(u(op%m, rank), s(rank), vt(rank, op%n))
    if (fallback) then
       u = up(:, 1:rank)
    else
       call gemm_z('N', 'N', op%m, rank, size(qs, 2), qs, max(1, op%m), &
            up, max(1, size(up, 1)), u, max(1, op%m))
       deallocate(qs)
    end if
    s = sp(1:rank)
    vt = vp(1:rank, :)
    deallocate(up, sp, vp)
  end subroutine svd_core_z

  subroutine ids_core_z(op, a, mv, ipar, rpar, zpar, rtol, bs, pit, es, meth, iseed, k, piv, &
       t, ierr)
    type(op_t), intent(in) :: op
    complex(dp), intent(in) :: a(*)
    external :: mv
    integer :: ipar(*)
    real(dp) :: rpar(*)
    complex(dp) :: zpar(*)
    real(dp), intent(in) :: rtol
    integer, intent(in) :: bs, pit, es, meth
    integer, intent(inout) :: iseed(4)
    integer, intent(out) :: k, ierr
    integer, pointer :: piv(:)
    complex(dp), pointer :: t(:,:)
    complex(dp), pointer :: q(:,:), r(:,:)
    real(dp) :: rts

    nullify(t)
    k = 0
    call qr_core_z(op, a, mv, ipar, rpar, zpar, rtol, bs, pit, es, iseed, q, r, piv, ierr)
    if (ierr /= RLA_OK) return
    deallocate(q)
    k = size(r, 1)
    rts = rtol
    if (rtol >= 1) rts = 0
    call compute_t_z(op, a, mv, ipar, rpar, zpar, r, piv, k, meth, rts, t, ierr)
    deallocate(r)
  end subroutine ids_core_z

  subroutine idq_core_z(op, a, mv, ipar, rpar, zpar, rtol, meth, k, piv, t, ierr)
    type(op_t), intent(in) :: op
    complex(dp), intent(in) :: a(*)
    external :: mv
    integer :: ipar(*)
    real(dp) :: rpar(*)
    complex(dp) :: zpar(*)
    real(dp), intent(in) :: rtol
    integer, intent(in) :: meth
    integer, intent(out) :: k, ierr
    integer, pointer :: piv(:)
    complex(dp), pointer :: t(:,:)
    complex(dp), pointer :: am(:,:), w(:,:), r(:,:), qd(:,:)
    real(dp) :: rts
    integer :: n, info

    nullify(t)
    n = op%n
    ierr = RLA_OK
    call get_matrix_z(op, a, mv, ipar, rpar, zpar, am)
    ! The QR overwrites its input: keep A only when lstsq needs it
    if (meth == METHOD_LSTSQ) then
       allocate(w(op%m, n))
       w = am
       call qrpiv_z(op%m, n, w, r, piv, qd, .false., info)
    else
       call qrpiv_z(op%m, n, am, r, piv, qd, .false., info)
    end if
    if (info /= 0) then
       ierr = RLA_ERR_LAPACK
       k = 0
       deallocate(r)
       if (associated(am)) deallocate(am)
       return
    end if
    if (rtol >= 1) then
       k = min(kmax_of(rtol), min(op%m, n))
       rts = 0
    else
       k = rank_from_diag_z(r, rtol)
       rts = rtol
    end if
    if (k == 0 .or. k == n) then
       allocate(t(k, n - k))
    else if (meth == METHOD_LSTSQ) then
       call t_lstsq_z(am, piv, k, t, ierr)
    else
       call compute_t_z(op, a, mv, ipar, rpar, zpar, r, piv, k, meth, rts, t, ierr)
    end if
    if (associated(am)) deallocate(am)
    deallocate(r)
  end subroutine idq_core_z

  ! T (k x (n-k), allocated) from R (rows 1:k used) and the pivots
  subroutine compute_t_z(op, a, mv, ipar, rpar, zpar, r, piv, k, meth, rts, t, ierr)
    type(op_t), intent(in) :: op
    complex(dp), intent(in) :: a(*)
    external :: mv
    integer :: ipar(*)
    real(dp) :: rpar(*)
    complex(dp) :: zpar(*)
    complex(dp), intent(in) :: r(:,:)
    integer, intent(in) :: piv(:), k, meth
    real(dp), intent(in) :: rts
    complex(dp), pointer :: t(:,:)
    integer, intent(out) :: ierr
    complex(dp), pointer :: am(:,:)
    ierr = RLA_OK
    select case (meth)
    case (METHOD_LSTSQ)
       if (k == 0 .or. k >= op%n) then
          allocate(t(k, op%n - k))
          t = 0
       else
          call get_matrix_z(op, a, mv, ipar, rpar, zpar, am)
          call t_lstsq_z(am, piv, k, t, ierr)
          deallocate(am)
       end if
    case (METHOD_SVD)
       call t_svd_z(r, k, rts, t, ierr)
    case default
       call t_fast_z(r, k, rts, t, ierr)
    end select
  end subroutine compute_t_z

  ! T = lstsq(A(:, piv(1:k)), A(:, piv(k+1:n)))
  subroutine t_lstsq_z(am, piv, k, t, ierr)
    complex(dp), intent(in) :: am(:,:)
    integer, intent(in) :: piv(:), k
    complex(dp), pointer :: t(:,:)
    integer, intent(out) :: ierr
    integer :: info, n
    n = size(am, 2)
    ierr = RLA_OK
    call lstsq_z(am(:, piv(1:k)), am(:, piv(k+1:n)), t, info)
    if (info /= 0) ierr = RLA_ERR_LAPACK
  end subroutine t_lstsq_z

  ! T = pinv(R11) R12, dropping singular values below max(rts, eps) * smax
  subroutine t_svd_z(r, k, rts, t, ierr)
    complex(dp), intent(in) :: r(:,:)
    integer, intent(in) :: k
    real(dp), intent(in) :: rts
    complex(dp), pointer :: t(:,:)
    integer, intent(out) :: ierr
    complex(dp), pointer :: u(:,:), vt(:,:)
    real(dp), pointer :: s(:)
    complex(dp), allocatable :: uk(:,:), vk(:,:), r12(:,:), w(:,:)
    integer, allocatable :: keep(:)
    real(dp) :: smax, cut
    integer :: n, nk, i, info

    n = size(r, 2)
    ierr = RLA_OK
    allocate(t(k, n - k))
    t = 0
    if (k == 0) return
    call svd_z(r(1:k, 1:k), u, s, vt, info)
    if (info /= 0) then
       ierr = RLA_ERR_LAPACK
       deallocate(u, s, vt)
       return
    end if
    smax = maxval(s)
    cut = max(rts, eps)*smax
    nk = count(s >= cut)
    if (smax > 0 .and. nk > 0) then
       allocate(keep(nk), uk(k, nk), vk(nk, k), r12(k, n - k), w(nk, n - k))
       keep = pack((/ (i, i = 1, k) /), s >= cut)
       uk = u(:, keep)
       vk = vt(keep, :)
       r12 = r(1:k, k+1:n)
       call gemm_z('C', 'N', nk, n - k, k, uk, k, r12, k, w, nk)
       do i = 1, nk
          w(i, :) = w(i, :) / s(keep(i))
       end do
       call gemm_z('C', 'N', k, n - k, nk, vk, nk, w, nk, t, k)
       deallocate(keep, uk, vk, r12, w)
    end if
    deallocate(u, s, vt)
  end subroutine t_svd_z

  ! T = R11 \ R12 by triangular solve, or t_svd if R11 is near-singular
  subroutine t_fast_z(r, k, rts, t, ierr)
    complex(dp), intent(in) :: r(:,:)
    integer, intent(in) :: k
    real(dp), intent(in) :: rts
    complex(dp), pointer :: t(:,:)
    integer, intent(out) :: ierr
    real(dp) :: dmin, dmax
    integer :: n, i

    n = size(r, 2)
    ierr = RLA_OK
    if (k == 0) then
       allocate(t(0, n))
       return
    end if
    dmin = abs(r(1, 1)); dmax = dmin
    do i = 2, k
       dmin = min(dmin, abs(r(i, i)))
       dmax = max(dmax, abs(r(i, i)))
    end do
    if (dmin <= eps*dmax) then
       call t_svd_z(r, k, rts, t, ierr)
       return
    end if
    allocate(t(k, n - k))
    t = r(1:k, k+1:n)
    call trsm_z(k, n - k, r, size(r, 1), t, k)
  end subroutine t_fast_z

